Возможно, один из них — вы.

## Пять шагов, которые можно сделать сегодня

- **Выберите направление «на пробу».** Не на всю жизнь — на полгода. Интерес может поменяться, и это нормально.
- **Найдите свой пробел.** Возьмите предмет, который «не идёт», и выясните, с какой темы начались трудности.
- **Занимайтесь понемногу, но каждый день.** Двадцать минут в день дают больше, чем три часа раз в неделю.
- **Найдите живого героя.** Поговорите со взрослым, который работает в интересной вам сфере.
- **Ведите дневник роста.** Раз в месяц записывайте, что научились делать. Через год перечитайте.

## Родителям

Если вы дочитали серию — спасибо. Вот несколько мыслей для вас:

- **Не сравнивайте ребёнка с другими.** Сравнивайте его с ним самим и отмечайте рост.
- **Показывайте настоящих людей.** Расскажите о знакомых инженерах, врачах, мастерах — о том, как они начинали.
- **Хвалите усилия, а не только оценки.** «Ты долго разбирался и понял» ценнее, чем «молодец, пятёрка».
- **Будьте рядом, когда трудно.** Фраза «я в тебя верю» работает лучше любых технологий.

