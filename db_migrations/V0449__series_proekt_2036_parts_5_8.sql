## Правило десяти лет

Почти у всех героев между партой и первым большим результатом прошло около десяти лет. Это не совпадение. Чтобы стать мастером в любом деле, нужно время: на знания, на практику, на ошибки.

Хорошая новость: если вам сейчас 14, через десять лет вам будет 24. Это не «когда-нибудь». Это вполне конкретный срок, за который можно стать инженером, врачом, исследователем, мастером своего дела.

Плохая новость — если её можно так назвать: эти десять лет пройдут в любом случае. Вопрос только в том, кем вы будете в их конце.

## Почему стоит сравнивать себя с собой

Вернёмся к мысли из первой записки. Когда вы сравниваете себя с самым успешным человеком из ленты, вы всегда проигрываете: видите его результат, но не видите десять лет работы за ним.

Когда сравниваете себя с собой год назад — видите свой реальный путь. И этот путь мотивирует, потому что он ваш.

- Год назад вы не могли решить такую задачу, а сейчас можете.
- Год назад вы не знали, что вам интересно, а сейчас есть хотя бы догадка.
- Год назад вы сдавались после первой ошибки, а сейчас пробуете ещё раз.

Это и есть рост. И его никто не может отнять.

## Будущее, которое стоит строить

