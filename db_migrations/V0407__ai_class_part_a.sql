## Ось 1. Режим мышления: быстрая или рассуждающая

Самое важное разделение последних двух лет — и самое непонятое.

**Быстрые модели** отвечают сразу. Вы задали вопрос — получили ответ за секунду. Так работали все нейросети до 2024 года и так работает большинство запросов сейчас.

**Рассуждающие модели** перед ответом строят внутреннюю цепочку размышлений: разбивают задачу, проверяют промежуточные шаги, отбрасывают тупиковые ветки. Ответ приходит дольше — от нескольких секунд до минут — и стоит дороже. Взамен резко растёт качество на задачах, где нужна многошаговая логика.

Практическое правило:

- **Переписать текст, ответить на письмо, придумать заголовки, перевести** — быстрая модель. Рассуждающая здесь просто дольше и дороже, результат тот же.
- **Разобрать спорный договор, найти ошибку в расчёте, спроектировать архитектуру, решить задачу в несколько действий** — рассуждающая. Быстрая уверенно выдаст правдоподобную чепуху.

Главное новшество последнего поколения — **гибридный режим**: модель сама решает, сколько думать над конкретным запросом. GPT-5 научился этому первым, Claude и Gemini подхватили. GPT-6 Astra довела идею до конца: переключение происходит незаметно для пользователя.

