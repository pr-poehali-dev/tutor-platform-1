## Почему рейтинги перестали работать

Три причины, и все три структурные.

**Первая: модели обновляются быстрее, чем пишутся обзоры.** За последний год вышли Claude Opus 4.5, Gemini 3, GPT-5.1 и GPT-5.2 подряд, а теперь GPT-6 Astra. Любой рейтинг живёт до следующего релиза — то есть недели три.

**Вторая: разрыв между флагманами сократился до незначимого.** На большинстве бенчмарков лидеры идут в пределах нескольких пунктов друг от друга. Разница между первым и третьим местом меньше, чем разница между хорошо и плохо сформулированным запросом к любому из них.

**Третья, главная: бенчмарки измеряют не то, что вам нужно.** Модель может решать олимпиадные задачи по математике на уровне призёра — и при этом хуже другой писать письмо клиенту на русском. Эти навыки не связаны.

