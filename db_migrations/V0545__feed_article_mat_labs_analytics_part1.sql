По ИНН или названию: выручка, прибыль, рентабельность, выручка на сотрудника — и всё это **в сравнении с медианой отрасли в регионе**. Плюс господдержка за 2024–2026 годы, руководитель, список прямых конкурентов с похожей выручкой и контакты, если они найдены.

