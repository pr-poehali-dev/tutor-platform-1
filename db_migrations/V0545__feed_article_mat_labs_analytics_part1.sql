- **Размер компаний** — сколько игроков с выручкой до 10 млн, до 120 млн, до 800 млн рублей и выше.
- **Приток новых игроков** — сколько компаний появилось за последние годы.
- **Риски** — доля компаний с налоговыми долгами.
