## 2. Профиль доверия специалиста

На квалифицированной позиции работодатель задаёт три вопроса: есть ли документы, умеет ли человек работать и что о нём скажут. Профиль доверия отвечает на все три.

**Публичная визитка.** Страница резюме по короткой ссылке: опыт, документы о квалификации, сертификаты оценки, рекомендации. Контакты скрыты.

**Рекомендации по личной ссылке.** Специалист отправляет одноразовую ссылку бывшему главврачу, главному инженеру или мастеру участка. Тот оставляет отзыв без регистрации и указывает, кем приходится кандидату.

