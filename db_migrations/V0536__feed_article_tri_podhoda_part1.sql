Персонализация — это когда маршрут строится от конкретного ученика: его уровня, темпа, пробелов и цели. Ещё в 1984 году американский психолог Бенджамин Блум показал, что ученики, которые занимались индивидуально с наставником, в среднем обгоняли сверстников из обычного класса настолько, что оказывались лучше большинства из них. Проблема была одна: личного репетитора невозможно дать каждому. Сегодня часть этой работы могут взять на себя цифровые инструменты.

