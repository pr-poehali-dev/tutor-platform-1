## Подход 2. Делать, а не слушать

### В чём суть

Можно прослушать объяснение, кивнуть, переписать пример с доски — и через неделю не помнить ничего. Знания закрепляются, когда ученик сам совершает усилие: решает, вспоминает, объясняет, спорит, применяет к новой ситуации. Психологи называют это «эффектом активного припоминания»: попытка самому вспомнить материал запоминается лучше, чем повторное чтение того же текста.

К активным методам относятся проекты, разбор реальных ситуаций (кейсы), дебаты, ролевые игры, работа в парах и группах. Одна из самых практичных моделей — **«перевёрнутый класс»**: теорию ученик изучает дома в своём темпе (видео, конспект, короткий урок), а время с учителем уходит на задачи, вопросы и разбор ошибок. Учитель перестаёт быть «диктором» и становится тренером.

### Как это выглядит на практике

**Пример.** В седьмом классе проходят проценты. Вместо десяти однотипных задач из учебника учитель даёт проект: «Сравните три тарифа мобильной связи и докажите, какой выгоднее для вашей семьи». Ученики считают проценты, скидки и переплаты на реальных цифрах, а потом защищают выбор перед классом. Через месяц они помнят тему, потому что применяли её, а не заучивали.

Что ещё работает:

- **Объяснить другому.** Если ребёнок может рассказать тему младшему брату или родителю своими словами — он её понял.
- **Спор и дебаты** — для истории, литературы, обществознания. Аргумент «за» и «против» запоминается лучше параграфа.
- **Ошибка как материал.** Разобрать, почему решение неверное, полезнее, чем просто переписать правильное.

Активные методы развивают и то, что не проверишь контрольной: критическое мышление, умение работать в команде, доводить дело до конца и выступать перед людьми.

### Где ошибаются

- **Активность ради активности.** Групповая работа, где один делает, а трое смотрят, хуже обычного урока. У каждого должна быть своя задача.
- **Без базы не работает.** Нельзя спорить о причинах войны, не зная хронологии. Активные методы — надстройка над знаниями, а не их замена.

### Советы родителям

1. **Попросите ребёнка объяснить новую тему вам.** Если не получается — тема ещё не понята, даже если в дневнике пятёрка.
2. **Ищите предмет в жизни.** Проценты — в магазине и в банке, физика — на кухне и в машине, география — в отпуске. Вопрос «а как это посчитать?» в обычной ситуации стоит часа зубрёжки.
3. **Вместо «выучи параграф» — «закрой книгу и расскажи, что запомнил».** Пересказ по памяти работает лучше повторного чтения.

