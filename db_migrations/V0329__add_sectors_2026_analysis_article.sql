Раньше можно было сказать: «экономика растёт на 2%» — и это описывало реальность для большинства компаний. Сегодня такая фраза не значит ничего.

Рост ВВП около нуля — это не состояние экономики. Это **среднее арифметическое между секторами, которые идут в противоположных направлениях**.

Обработка растёт, добыча падает. Банки теряют прибыль, но наращивают активы. Девелоперы режут запуски, а инфраструктурное строительство ускоряется. Ритейл в рублях растёт, а в штуках сжимается.

Для профучастника это означает главное: **отраслевая принадлежность контрагента сейчас важнее его финансовой отчётности**. Компания с хорошим балансом в падающем секторе рискованнее компании со средним балансом в растущем.

Разберём разлом по шести секторам.

## 1. Промышленность: раскол внутри одного сектора

Самый показательный пример нового расслоения.

**Обрабатывающие производства растут примерно на 4,5-5% годовых.** Драйверы понятны: гособоронзаказ, импортозамещение, машиностроение, химия. Загрузка мощностей на этих предприятиях близка к историческим максимумам.

**Добыча падает примерно на 3%.** Причины внешние: ограничения по добыче нефти, санкционное давление, слабый экспортный спрос, укрепление рубля, съедающее валютную выручку.

Раньше эти два блока двигались вместе — сырьевой цикл тянул за собой всё. Сейчас связь разорвана.

**Что это значит стратегически.** Промышленность перестала быть единым классом риска. Кредитовать, поставлять и заходить в проекты нужно по подсекторам, а не по отрасли целиком.

Второе следствие важнее: обработка растёт при остром дефиците кадров. Это структурный, а не циклический дефицит — он не рассосётся со снижением ставки. Значит, всё, что заменяет людей или готовит их, получает многолетний спрос независимо от макроцикла: автоматизация, аутсорс непрофильных функций, обучение рабочим специальностям, вахтовые схемы.

Третье: рост обработки завязан на бюджетный импульс. Это делает его устойчивым в горизонте года, но уязвимым при пересмотре бюджетных приоритетов. Держите это в оценке риска на 2027-й.

## 2. Банки: прибыль обвалилась, а баланс вырос

Здесь самая недооценённая история года.

**Прибыль сектора в первом полугодии упала примерно на 60% год к году.** Заголовок звучит катастрофично, но смотреть надо не на прибыль.

Причина падения — не отток клиентов и не потеря бизнеса. Основное давление идёт от двух вещей: резкий рост стоимости фондирования (банки платят вкладчикам 15-18%, а старые кредиты выданы дешевле) и растущие резервы под проблемные долги.

**При этом активы сектора и депозитная база выросли.** Более 66 триллионов рублей средств населения — это исторический максимум, а доля физлиц в пассивах превысила 35%, чего не было семь лет.

**Что это значит стратегически.** Банковский сектор проходит не кризис, а **перенастройку маржи**. Он сжал прибыль, но накопил ресурсную базу.

Отсюда прямое следствие для всех остальных: как только стоимость фондирования пойдёт вниз вслед за ставкой, у банков появится и мотивация, и ресурс агрессивно наращивать кредитование. Разворот кредитного предложения произойдёт быстрее, чем разворот спроса.

Практический вывод: договариваться о лимитах и линиях выгоднее сейчас, когда банк голоден до качественного заёмщика, а не через год, когда за деньгами выстроится очередь.

Второй сигнал — рост резервов. Он говорит, что банки уже видят ухудшение платёжной дисциплины в портфелях. Значит, требования к обеспечению и ковенантам будут ужесточаться раньше, чем подешевеют деньги.

## 3. Девелопмент: запуски режут, но это не обвал

**Запуски новых проектов сократились примерно на 20% год к году.** Ипотека дорогая, спрос слабый, распроданность в новых корпусах низкая.

Но интерпретировать это как коллапс отрасли — ошибка.

Сокращение запусков — рациональное поведение, а не агония. Застройщики не строят то, что не продадут, и переносят проекты на более благоприятный цикл. Крупные игроки с доступом к проектному финансированию переживут паузу. Уйдут средние и мелкие, у которых нет запаса.

**Что это значит стратегически.** Отрасль идёт к консолидации. Через 12-18 месяцев рынок будет более концентрированным: меньше игроков, выше барьеры входа, крупнее средний проект.

Для профучастников это создаёт два окна:

Первое — **окно активов**. Земельные участки, недостроенные объекты и проектная документация уходящих игроков будут продаваться дёшево. Это классический момент для тех, у кого есть ликвидность и горизонт.

Второе — **отложенный дефицит предложения**. Сокращённые сегодня запуски — это дефицит готового жилья через два-три года. Когда ипотека подешевеет, спрос вернётся быстро, а предложения не будет. Цены отреагируют резко.

Кто сейчас накапливает земельный банк, тот встретит следующий цикл с товаром. Кто распродаётся — зафиксирует убыток на дне.

## 4. Ритейл: рост в рублях, сжатие в штуках

Самая обманчивая статистика года.

Оборот розницы в деньгах растёт, и отчётность выглядит прилично. Но это **инфляционный рост, а не рост потребления**. В натуральном выражении объёмы стагнируют или снижаются.

Потребитель не обеднел — он изменил модель. Люди отказываются от необязательных трат (ремонт, замена техники, крупные покупки), покупают меньше и переключаются на более дешёвые позиции.

И главное: **вклад под 15-18% стал прямым конкурентом любой крупной покупки**. Ритейл конкурирует не с соседним магазином, а с кнопкой «открыть вклад».

**Что это значит стратегически.** Сегмент расслаивается по вертикали. Устойчивы два полюса — дискаунтеры и жёсткий эконом внизу, и премиум наверху, где покупатель нечувствителен к ставке. Вымывается середина: то, что «неплохо, но дорого».

Для поставщиков и арендодателей вывод прикладной: смотреть не на выручку арендатора, а на его позиционирование. Сеть в среднем сегменте с растущей рублёвой выручкой может быть опаснее дискаунтера со стагнирующей.

Второе: онлайн продолжит отъедать долю у офлайна, потому что при экономном потребителе цена и сравнение важнее опыта покупки.

## 5. Логистика: рынок переезжает на восток

Сектор живёт двумя разнонаправленными процессами.

**Экспортное направление сжимается** вслед за падением добычи и слабым внешним спросом.

**Внутренняя дистрибуция и восточное направление растут.** Развернувшиеся торговые потоки требуют новых маршрутов, складов и обработки. Маркетплейсы продолжают наращивать объёмы даже при экономном потребителе — потому что забирают долю у офлайна.

**Что это значит стратегически.** Логистика — один из немногих секторов, где структурный сдвиг работает на вас независимо от макроцикла. Переориентация торговли на восток и юг — это процесс на годы, а не на квартал.

Узкое место здесь не спрос, а инфраструктура: складские мощности в нужных точках, пропускная способность направлений, кадры. Кто вкладывается в мощности сейчас, при дорогих деньгах, получит дефицитный актив, когда поток вырастет.

Риск обратный: сектор капиталоёмкий, а деньги дорогие. Экспансия на заёмные средства под 20% при текущих ставках аренды может не сойтись. Считать надо не доходность проекта, а срок, за который вы обслужите долг.

## 6. IT: рост замедлился, но спрос сменил природу

Взрывной рост на волне импортозамещения прошёл. Бюджеты компаний на цифровизацию режут вместе с остальными расходами.

Но происходит замена мотива покупки, и это важнее темпов.

Раньше покупали, чтобы **заместить ушедшее ПО**. Сейчас покупают, чтобы **сократить расходы на персонал** — потому что дефицит кадров и рост зарплат делают автоматизацию дешевле найма.

**Что это значит стратегически.** Выигрывают решения с быстрым и считаемым эффектом на издержки. Проигрывают долгие трансформационные проекты с окупаемостью в три года — их режут первыми при дорогих деньгах.

Практический вывод для продавцов: продавать нужно не функциональность, а конкретную экономию. «Заменит двух сотрудников» работает, «повысит эффективность процессов» — уже нет.

Второй сдвиг: заказчик уходит от капитальных вложений к подписке. При дорогих деньгах компании не хотят замораживать капитал — сервисные модели с ежемесячным платежом выигрывают у покупки лицензий.

## Три сквозных вывода

Соберём картину целиком.

**Первое: средних показателей больше не существует.**

Когда обработка растёт на 5%, а добыча падает на 3%, «промышленность» как класс риска перестаёт что-либо значить. Любая оценка контрагента, отрасли или портфеля по агрегированным данным сейчас даёт систематическую ошибку.

Работать нужно на уровне подсекторов. Это главное изменение в методологии, которое требует 2026 год.

**Второе: разделяйте циклическое и структурное.**

Дорогие деньги — циклично, это пройдёт со снижением ставки. Дефицит кадров, разворот торговых потоков на восток, замена найма автоматизацией — структурно, это останется.

Ставка на циклическое — спекуляция на таймингe, и вы можете не угадать момент. Ставка на структурное работает независимо от того, когда именно ЦБ дойдёт до 12%.

**Третье: главный актив сейчас — ликвидность, а не доходность.**

Во всех шести секторах повторяется один сюжет: слабые игроки уходят, их активы и клиенты перераспределяются в пользу тех, кто дожил.

Девелоперы продают земельные банки. Ритейл освобождает торговые площади. Промышленность выставляет непрофильные активы. Логистика отдаёт мощности.

Это происходит одновременно во всей экономике — и это редкая конфигурация. Обычно кризис бьёт по одному-двум секторам, а сейчас перераспределение идёт широким фронтом.

Тот, у кого есть свободные деньги и горизонт в два года, входит сейчас в активы по ценам, которых не будет через год.

## Итог

2026-й не про рост и не про падение. Он про **разлом**.

Экономика не движется в одну сторону — она расходится. Одни сектора набирают ход на бюджетном импульсе и структурных сдвигах, другие сжимаются под внешним давлением и дорогими деньгами.

Для профессионального участника это меняет саму постановку вопроса. Не «что будет с экономикой», а «на какой стороне разлома находится мой контрагент, мой актив, мой портфель».

Средние цифры больше не отвечают ни на один важный вопрос. Отвечает только разбор по подсекторам.

