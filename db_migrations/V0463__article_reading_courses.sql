## Почему современные дети читают медленнее

Медленное чтение почти никогда не связано с ленью. Быстрое чтение с пониманием держится на нескольких навыках:

- **поле зрения** — сколько букв глаз схватывает за одну остановку
- **внимание** — может ли ребёнок 5–10 минут не отвлекаться от текста
- **память** — удерживает ли он начало фразы, пока дочитывает конец
- **словарь** — понимает ли значения слов, которые читает

Если проседает хотя бы один навык, страдает всё чтение. Добавьте к этому привычку возвращаться глазами к уже прочитанному и гаджеты, которые всегда интереснее книги, — и получится картина, которую видят многие родители и учителя.

Хорошая новость: эти навыки тренируются короткими регулярными занятиями. Не часом чтения из-под палки, а 10–15 минутами игр и упражнений в день.

## Курс «Скорочтение для детей 6–11 лет»

Курс для детей, которые читают по слогам, читают, но не понимают, или просто не любят читать. Подходит и будущим первоклассникам.

**Как устроен:** 24 занятия по 15 минут, 4 модуля.

- **Старт и замер.** Узнаём скорость и понимание чтения, разогреваем внимание таблицами Шульте.
- **Видим больше.** Клин, флеш-слова, пирамиды слов — учимся читать словами, а не по слогам.
- **Понимаю, что читаю.** Угадываем окончания, восстанавливаем пропущенные слова, учимся пересказывать.
- **Люблю читать.** Книги по интересам, стихи и скороговорки, финальный замер и сравнение с первым занятием.

Каждые две недели — повторный замер скорости, прогресс видно на графике. Родитель получает подсказки, как заниматься без давления, а ИИ-наставник отвечает на вопросы ребёнка и взрослого.

