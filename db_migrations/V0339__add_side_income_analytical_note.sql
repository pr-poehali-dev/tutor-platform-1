# Вариант 1. Продажа существующего навыка как услуги

**Суть.** Вы уже что-то умеете по основной работе. Бухгалтер умеет считать, инженер — читать чертежи, педагог — объяснять, менеджер — вести переговоры. Этот навык продаётся отдельно от работодателя.

**Почему работает.** Здесь нет самого дорогого этапа — обучения с нуля. Вы уже прошли его за счёт работодателя. Остаётся научиться только продавать.

**Реальные цифры.** Начальная ставка обычно 500–1 500 ₽ за час в зависимости от области. Через полгода регулярной практики — 2 000–3 500 ₽. При загрузке 10–15 часов в неделю это 30–60 тысяч в месяц дополнительно.

**Вложения.** До 5 тысяч: оформление самозанятости бесплатно, нужен только приличный микрофон, если работа голосовая, и время на оформление профиля.

**Срок до первых денег.** Две-четыре недели. Первый клиент почти всегда приходит из личных контактов, а не с площадки.

**Как начать конкретно.** Сформулируйте услугу в одном предложении по формуле «я решаю проблему X для людей типа Y». Не «консультирую по бухгалтерии», а «привожу в порядок учёт у ИП, которые запустили документы за год». Дальше — сообщите об этом двадцати знакомым лично, не постом в соцсети. Из двадцати обычно откликаются двое.

**Главный риск.** Конфликт с основной работой. Проверьте трудовой договор на предмет ограничений, и не берите клиентов, которые могли бы стать клиентами работодателя.

**Потолок.** Ваше время. Обходится переходом от почасовой оплаты к пакетам за результат, но это уже следующий этап.

