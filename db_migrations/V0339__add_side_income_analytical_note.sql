## Часть 3. Что общего у всех трёх вариантов

**Первое: вы продаёте то, что уже умеете.** Ни один не требует осваивать профессию с нуля. Это главное отличие от «бизнеса в гараже», где нужно одновременно учиться производить и учиться продавать — две задачи сразу.

**Второе: риск ограничен временем, а не деньгами.** Если не пошло, вы потеряли несколько недель. При вложении 200 тысяч в оборудование неудача стоит 200 тысяч и года жизни.

**Третье: доход растёт от повторных обращений, а не от новых вложений.** Ваша ценность накапливается в репутации и опыте, а не в купленном станке, который через год устареет.

**Четвёртое: всё легально и просто оформляется.** Самозанятость регистрируется за десять минут в приложении, ставка 4% при работе с физлицами и 6% с компаниями. До 2,4 млн рублей в год этого режима достаточно. Отчётности нет, касса не нужна.

## Часть 4. Четыре проверки перед стартом любого варианта

**Проверка на десять клиентов.** Найдите десять человек, которые платят за похожую услугу прямо сейчас. Не «которым может быть интересно», а которые уже платят. Не нашли — рынка нет.

**Проверка на час.** Разделите ожидаемый месячный доход на количество часов, которые придётся потратить. Если получается меньше, чем вы зарабатываете на основной работе, — считайте это обучением, а не заработком.

**Проверка на депозит.** Если вариант требует вложений, сравните ожидаемую доходность со вкладом. Проект должен обгонять депозит существенно, иначе он не окупает риск и усилия.

**Проверка на выход.** Заранее определите: сколько денег и месяцев вы готовы потратить, и при каком результате остановитесь. Без этой точки люди досыпают ресурсы в неработающую затею годами.

