# Вариант 2. Операционная поддержка малого бизнеса на удалёнке

**Суть.** Небольшие компании и предприниматели тонут в рутине: обработка заказов, ответы клиентам, ведение таблиц, выставление счетов, координация исполнителей. Нанимать сотрудника в штат дорого, а несколько часов в день — востребовано.

**Почему работает.** Это направление растёт по структурной причине: при дефиците кадров и дорогих деньгах компании сокращают штат, но объём рутины не уменьшается. Его отдают на сторону.

Второе преимущество: порог входа низкий по навыкам, но высокий по надёжности. Исполнителей много, а тех, кто отвечает вовремя и не пропадает, — мало. Это редкий рынок, где обязательность важнее квалификации.

**Реальные цифры.** Старт — 25–35 тысяч в месяц за неполную занятость с одним заказчиком. Через несколько месяцев, с двумя-тремя заказчиками — 50–80 тысяч. Опытные исполнители, которые берут на себя целые процессы, выходят к сотне и выше.

**Вложения.** Практически нулевые: компьютер и стабильный интернет. Из платного — возможно, курс по таблицам, если с ними плохо.

**Срок до первых денег.** Три-шесть недель. Дольше, чем в первом варианте, потому что нужно доказать надёжность незнакомому человеку.

**Как начать конкретно.** Не откликайтесь на вакансии «помощник руководителя» — там сотни соискателей. Работает другое: выберите конкретную нишу (например, интернет-магазины на маркетплейсах), изучите её типовые процессы и обращайтесь напрямую к владельцам с конкретным предложением: «вижу, что у вас задержки с ответами на отзывы — возьму это на себя, первая неделя бесплатно».

**Главный риск.** Заказчик, который платит нерегулярно. Защита: предоплата за первый месяц или еженедельные расчёты, пока не сложилось доверие.

**Потолок.** Тоже время, но выше первого варианта — часть задач можно автоматизировать, а рутину передать.

