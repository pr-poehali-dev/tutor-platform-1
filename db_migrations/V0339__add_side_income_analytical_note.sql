# Вариант 3. Обучение других тому, что вы уже делаете

**Суть.** Не «инфобизнес» и не курсы о том, как делать курсы. Обучение конкретному прикладному навыку, которым вы владеете на практике: работа на станке, сварка, ведение учёта, конкретная программа, язык, подготовка к экзамену.

**Почему работает.** Дефицит кадров в 2026 году острый, особенно в рабочих и технических специальностях. Люди готовы платить за то, чтобы освоить профессию с реальным спросом. При этом преподавателей-практиков мало: те, кто умеет, обычно работают, а не учат.

**Реальные цифры.** Индивидуальные занятия — 1 000–2 500 ₽ за час в зависимости от темы. Групповые — выгоднее в разы: группа из шести человек по 3 000 ₽ за курс из четырёх занятий даёт 18 тысяч за примерно шесть часов работы.

При двух группах в месяц это 30–40 тысяч дополнительно.

**Вложения.** До 10 тысяч: минимальная техника для записи, если планируете дистанционный формат, и время на подготовку программы.

**Срок до первых денег.** Три-восемь недель. Дольше остальных вариантов, потому что нужно собрать первую группу.

**Как начать конкретно.** Начните с одного ученика бесплатно — в обмен на подробный отзыв и разрешение использовать его результат как пример. Это единственный способ получить доказательство, что вы умеете не только делать, но и учить. Дальше первая платная группа собирается уже с опорой на этот результат.

Второе: не пытайтесь учить «всему». Узкая тема с понятным результатом продаётся лучше широкой. «Научу варить трубы под давлением» продаётся, «курс сварщика» — нет.

**Главный риск.** Умение делать не равно умению объяснять. Первые занятия почти всегда идут плохо. Это нормально и проходит примерно к пятому.

**Потолок.** Выше всех трёх вариантов: записанная программа продаётся многократно без вашего участия. Но путь туда — не меньше года.

