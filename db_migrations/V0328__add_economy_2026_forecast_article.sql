Тот, кто доживёт до этого момента без долгов и с сохранённой клиентской базой, получит рынок тех, кто не дожил.

Поэтому главный вопрос года — не «как вырасти». А «сколько месяцев я продержусь при нынешней выручке» и «что я успею забрать, пока другие уходят».

