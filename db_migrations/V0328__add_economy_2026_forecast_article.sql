## Почему снижение ставки не ощущается

Когда ставка падает с 21% до 14%, звучит как облегчение. Но важна не абсолютная величина, а разница между стоимостью денег и инфляцией.

Восемь пунктов сверх инфляции — одна из самых жёстких денежных политик в мире. Для бизнеса с рентабельностью 10-15% кредит под 18-22% (именно столько выходит для малой компании с банковской надбавкой) остаётся математически бессмысленным.

Простой тест: если ваш бизнес зарабатывает 15% годовых на вложенный капитал, а деньги стоят 20% — вы не развиваетесь. Вы медленно уменьшаетесь. Просто не всегда это замечаете, потому что выручка в рублях растёт вместе с ценами.

И есть второй слой проблемы.

Высокая ставка сделала кредиты и рефинансирование почти неподъёмными для микробизнеса, который традиционно живёт на заёмных средствах. К середине 2026 года ставка начала снижаться — но бизнес всё ещё обслуживает долги, набранные раньше.

То есть смягчение уже началось, а расплата за прошлую жёсткость — ещё нет. Между этими событиями лежит от трёх до шести кварталов: именно столько, по оценкам ЦБ, изменение ставки транслируется в спрос и инфляцию.

Проще говоря: облегчение придёт. Но не всем хватит запаса дожить.

## Что происходит с бизнесом на земле

