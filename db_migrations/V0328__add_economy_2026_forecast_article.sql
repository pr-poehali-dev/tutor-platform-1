Это не всплеск предпринимательства. Это сжатие размера ячейки.

Компании с наёмным штатом, арендой и белой отчётностью превращаются в ИП без сотрудников. Бизнес не умирает — он мельчает, чтобы снизить издержки. Один человек вместо пяти, самозанятые подрядчики вместо трудовых договоров, работа из дома вместо офиса.

Для экономики это плохой сигнал: падает налоговая база и занятость. Для конкретного предпринимателя — наоборот, рабочая стратегия выживания.

## Куда делись деньги

Вот парадокс, который многие упускают: денег в стране не стало меньше. Они просто перестали двигаться.

На 1 апреля 2026 года объём средств населения на депозитах составил 66,7 трлн рублей. Доля средств физлиц в пассивах банков превысила 35% — максимум за семь лет.

Это прямое следствие политики ЦБ. Одна из задач жёсткой денежной политики — перевести население от потребительской модели к сберегательной.

Задача выполнена. Люди понесли деньги в банк, потому что вклад под 15-18% оказался выгоднее любой покупки и почти любого бизнеса.

Но у этого есть обратная сторона, о которой редко говорят прямо: **депозит стал конкурентом вашего товара**.

Вы конкурируете не с соседним магазином. Вы конкурируете с кнопкой «открыть вклад» в банковском приложении.

При этом потребитель не обеднел — он стал избирательным. Люди либо отказываются от необязательных трат вроде ремонта и замены техники, либо покупают меньше и выбирают дешевле.

## Первые трещины: бизнес перестал верить в спрос

Самый тревожный сигнал этого лета — не в статистике продаж, а в ожиданиях.

За последний месяц существенно снизились ожидания бизнеса по будущему спросу и выпуску. Это опережающий индикатор: компании сначала перестают верить в спрос, потом сокращают закупки и найм, и только через квартал это видно в отчётности.

Напомню: во втором квартале основной вклад в рост экономики внёс именно потребительский спрос. Если он замедлится, у роста не останется опоры — инвестиционная активность восстанавливается, но остаётся сдержанной.

## Прогноз до конца 2026 года

Соберём всё вместе. Три сценария с оценкой вероятности.

### Базовый: медленное сползание к нулю — около 60%

Ставка снижается осторожно, малыми шагами. Часть аналитиков ожидает, что на сентябрьском заседании ЦБ сохранит 14%: регулятор традиционно осторожнее на промежуточных заседаниях, летняя статистика зашумлена сезонностью, а параметры бюджета станут известны только в октябре.

К декабрю — 13-13,5%. Год закрываем с ростом ВВП около нуля. Волна закрытий продолжается, но без обвала.

**Что это значит для вас:** дешёвых денег до конца года не будет. Планы, построенные на «вот-вот подешевеет кредит», нужно переписать.

### Оптимистичный: разворот спроса — около 25%

Инфляция закрепляется ниже 6%, ЦБ ускоряет снижение до 12,5-13%. Ставки по вкладам падают ниже психологической планки, и часть из 66 триллионов начинает возвращаться в потребление.

Первыми выигрывают отложенные покупки: ремонт, техника, автомобили, недвижимость.

**Что это значит:** если вы в этих нишах — готовьте запас товара и оборотку заранее, а не когда развернётся. Разворот спроса всегда застаёт врасплох тех, кто резал закупки.

### Негативный: спрос ломается раньше, чем дешевеют деньги — около 15%

Ожидания бизнеса продолжают падать, компании режут найм, доходы населения замедляются — и потребительский спрос, единственная опора роста, уходит.

ЦБ в этом случае вынужден снижать ставку быстрее, но эффект придёт с лагом в те самые 3-6 кварталов, то есть уже в 2027-м.

**Что это значит:** решающим становится не рост, а запас прочности. Выживает не самый прибыльный, а тот, у кого меньше долгов и короче цикл возврата денег.

## Что с этим делать: пять выводов

Теперь практика. Без «держитесь» и «оптимизируйте расходы».

**1. Перестаньте смотреть на прибыль — смотрите на оборачиваемость.**

При дорогих деньгах решает не маржа, а скорость возврата вложенного. Бизнес с рентабельностью 12% и циклом в месяц сильнее бизнеса с рентабельностью 30% и циклом в полгода. Считайте, сколько раз за год ваш рубль успевает обернуться.

**2. Кредит на рост — не ваш инструмент в этом году.**

Кредит сейчас оправдан только для закрытия кассового разрыва под уже подписанный контракт. Занимать «на развитие» под 20% при рентабельности 15% — это не риск, это арифметическая ошибка.

**3. Ищите плательщика, у которого деньги не кончились.**

Население экономит. А предприятия, у которых дефицит рабочих рук, платят охотно. Обучение персонала, промышленный аутсорс, автоматизация вместо найма, обязательные по закону услуги — этот спрос не зависит от настроения потребителя.

Правило простое: если ваш клиент платит из своего кошелька — вы в зоне риска. Если из бюджета компании под конкретную задачу — вы устойчивее.

**4. Уменьшайтесь осознанно, а не в панике.**

Сокращение юрлиц на 5,2% при росте ИП на 7,8% — это массовый переход в более лёгкую форму. В нём нет позора: аренда вместо покупки, подрядчики вместо штата, склад под заказ вместо запаса.

Задача — снизить постоянные расходы так, чтобы пережить ещё 12 месяцев дорогих денег. Не «дорасти», а «дожить».

**5. Готовьтесь собирать рынок ушедших.**

Это главное. Когда закрытий вдвое больше, чем открытий, а регистрации падают на 22% — конкурентов в вашей нише становится меньше. Их клиенты никуда не делись, они ищут, к кому уйти.

Кризис перераспределяет долю рынка в пользу тех, кто выстоял. Если у вас есть запас прочности — сейчас время не сворачиваться, а забирать освободившихся клиентов. Через год эта возможность закроется.

