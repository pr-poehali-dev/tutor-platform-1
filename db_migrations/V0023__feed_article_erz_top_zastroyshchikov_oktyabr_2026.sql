## Концентрация: рынок не консолидируется

Есть распространённое мнение, что при высокой ставке крупные игроки забирают рынок. Данные ЕРЗ этого пока не подтверждают:

- ТОП-10 держит **18,7%** стройки (год назад 18,9%)
- ТОП-100 — **46,5%** (было 47,8%)
- компании с портфелем меньше 100 тыс. м² — **40%**, как и год назад

Медианный застройщик строит около 13 тыс. м², то есть один-два дома. Рынок остаётся раздробленным. Перераспределение идёт не от малых к большим, а из Москвы в регионы.

## Что это значит для бизнеса

**Девелоперам и инвесторам.** Объём новой стройки перестал расти, а значит, через 1,5–2 года не будет и прироста ввода. Конкуренция за покупателя в регионах роста — Кубань, Петербург, Урал, Крым — усилится: туда уходит предложение, которое сокращается в Москве.

**Подрядчикам и поставщикам.** Проверяйте застройщика в ЕРЗ до подписания договора: смотрите долю переноса, длительность переноса и рейтинг. Перенос у генподрядчика — ранний признак задержки платежей по цепочке.

**Банкам и лизингу.** Средний перенос в 3,3 месяца при ставке 14% — прямые дополнительные расходы на обслуживание проектного кредита. Риск сосредоточен у небольших застройщиков (20% переносов) и у отдельных крупных компаний.

**Покупателям и агентствам.** 68% застройщиков сдают дома без переносов. Однако перенесённая площадь растёт быстрее, чем стройка в целом. Срок сдачи в договоре стоит сверять с историей переносов у конкретной компании.

## Главное

1. Рынок жилищного строительства год стоит на месте: **126 млн м²** без учёта изменения в учёте реновации.
2. Переносы растут быстрее объёма: **19,1 млн м²**, или 15,1% стройки, в среднем на 3,3 месяца.
3. Лидер рынка Самолет дал 10% всех переносов страны и опустился в рейтинге ЕРЗ до 2,5 балла.
4. Москва за год потеряла 10,5% объёма. Растут Кубань, Петербург, Крым, Дагестан и Алтай.
5. Консолидации нет: на ТОП-10 приходится меньше 19% рынка, малые компании держат 40%.

