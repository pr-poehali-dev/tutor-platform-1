**Самолет — главный сигнал года.** Доля перенесённой площади у лидера рынка росла каждый квартал: 6,9% в январе 2025, 21% в октябре 2025, 33,6% в апреле 2026, 42,9% сейчас. Средний перенос за то же время вырос с 0,8 до 7,3 месяца, а рейтинг ЕРЗ снизился с 4,5 до 2,5 балла. Только Самолет даёт **10% всей перенесённой площади страны**. Без него доля переносов на рынке составляет 14,1%: тоже рост, но более плавный.

**Масштаб снижает риск, но не убирает его.** У 13 компаний с портфелем больше 1 млн м², кроме Самолета, перенесено в среднем 5,1% площади (год назад 7,3%). У 2 732 застройщиков с портфелем меньше 100 тыс. м² — **20,3%**. У 585 компаний перенесён весь объём строительства.

