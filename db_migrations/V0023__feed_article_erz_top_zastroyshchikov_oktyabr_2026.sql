## Главный риск: переносы сроков

Через проектное финансирование и эскроу-счета рынок защищает покупателя от потери денег, но не от ожидания. Перенос срока означает, что деньги дольше лежат на эскроу, а кредит дольше обслуживается по высокой ставке.

**Перенесённая площадь сосредоточена у нескольких компаний.** Первая десятка по объёму переносов:

