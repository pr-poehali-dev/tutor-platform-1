## Архитектура: единая цифровая модель и сквозная валидация

Базовая идея СмартМаш — **единая цифровая модель изделия**, через которую последовательно проходят все контуры:

**КД → CAE → CAM → MES**

Каждый контур валидирует данные и передаёт следующему только верифицированный результат. Переход возможен лишь при совпадении версий, поэтому рассогласования не накапливаются по цепочке.

**Контур КД.** Параметрическая библиотека типовых деталей по ГОСТ и DIN формирует цифровую модель — единый источник геометрии. При каждом изменении запускается проверка геометрических коллизий, а несогласованные данные не уходят в расчёт.

**Контур CAE.** Конечно-элементный, тепловой и динамический анализ выполняются прямо на модели из КД. Результаты усталостного расчёта с коэффициентом запаса прочности записываются в цифровой паспорт и становятся **технологическими ограничениями для CAM**.

**Контур CAM.** Управляющие программы привязаны к версии модели и к конкретному станку. Проверка технологичности сверяет УП с расчётными ограничениями ещё до выпуска программы. При изменении геометрии в КД связанные УП автоматически отправляются на повторную проверку.

**Контур ЖЦИ.** Цифровой паспорт детали фиксирует всю цепочку стадий: черновик → разработка → согласование → производство → архив. Каждый переход проходит автоматические проверки совместимости версий.

**Контур MES.** Производственное задание формируется из паспорта изделия и привязано к верифицированной УП и конкретному оборудованию. Телеметрия станков фиксирует фактические режимы, а отклонения записываются в паспорт детали.

В итоге производственное задание объединяет всё сразу: модель из КД, ограничения из CAE, проверенную УП из CAM и статус исполнения из MES. От конструкторского решения до операции на станке — одна прослеживаемая цепочка.

## ИИ-конструктор: чертёж по текстовому описанию

В редактор чертежей СмартМаш встроен агент **«ИИ-инженер»** (сейчас в статусе BETA). Его задача сформулирована предельно конкретно: **по текстовому описанию детали построить плоский рабочий чертёж прямо на холсте редактора**.

Инженер пишет обычным техническим языком, например:

> *Вал ступенчатый ∅40 и ∅30, длина 200, две проточки, фаски 2×45°*

Агент возвращает не картинку, а **структурированный набор чертёжных примитивов**: линии нужных типов (основная, тонкая, штриховая, невидимого контура), окружности, дуги, осевые, линейные размеры и обозначения диаметров. Всё это ложится на холст редактора как полноценные объекты, которые можно править, перемещать и раскладывать по слоям.

Что важно с инженерной точки зрения — агент работает в рамках ЕСКД:

- **ГОСТ 2.305** — главный вид, при необходимости вид сбоку или сечение;
- **ГОСТ 2.307** — простановка размеров: габаритные размеры снаружи, выносные линии не пересекают контур, размерные линии вынесены на 12–20 мм;
- **ГОСТ 2.303** — типы линий;
- тела вращения строятся как контур с обязательной горизонтальной осевой, симметричные детали — всегда с осью симметрии;
- используются стандартные значения диаметров, фасок, проточек и отверстий;
- в чертёж добавляются **технические требования**: неуказанные предельные отклонения, шероховатость, термообработка;
- заполняются наименование, обозначение и материал (например, «Сталь 45 ГОСТ 1050»), выбирается формат листа.

Принцип простой: чем подробнее описание, тем детальнее чертёж. Разработчики сами предупреждают прямо в интерфейсе: **«Проверяйте результат — ИИ может ошибаться в размерах»**. Так что это не замена конструктору, а ускоритель. Агент снимает рутину первичного построения и разметки, а инженер проверяет результат и доводит его.

Рядом с генератором чертежей в модуле проектирования работает **ИИ-помощник конструктора**. Он консультирует по выбору материалов, допускам и посадкам, шероховатости, стандартам ЕСКД, ГОСТ, DIN и ISO, а также по подбору типовых деталей из библиотеки. Для сборочных единиц есть отдельный помощник: состав изделия, спецификации по **ГОСТ 2.106**, передаточные числа, подбор подшипников и крепежа.

## ИИ-технолог: от режимов резания до G-кода

Второй ключевой инструмент живёт в модуле **«Программы ЧПУ (CAM)»**. Это **ИИ-технолог-программист ЧПУ** — помощник, настроенный на задачи технологической подготовки.

Он помогает с:

- **написанием управляющих программ** (G-код);
- **выбором режимов резания**: подачи, скорости, глубины;
- **стратегиями обработки**: черновой, чистовой, многоосевой;
- **выбором инструмента**;
- **оптимизацией программ ЧПУ**.

Типовые вопросы, которые технолог задаёт системе:

- какие режимы резания выбрать для фрезерования стали 45;
- как написать цикл сверления в управляющей программе;
- как работает коррекция на радиус инструмента;
- как рассчитать подачу для токарной операции;
- какую стратегию выбрать для обработки кармана;
- какой постпроцессор нужен под Siemens 840D;
- как оптимизировать траекторию при пятиосевой обработке.

Рядом с ИИ-технологом есть детерминированный инструмент — **калькулятор режимов резания**. По материалу и параметрам фрезы (диаметр, число зубьев) он рассчитывает классический набор:

- **Vc** — скорость резания, м/мин;
- **n** — частота вращения шпинделя, об/мин;
- **Vf** — минутная подача, мм/мин;
- **ap / ae** — осевая и радиальная глубина резания, мм;
- **MRR** — производительность съёма материала, см³/мин.

Результат сразу выводится в виде **фрагмента G-кода** с комментариями: задание оборотов шпинделя (S… M03), врезание на пониженной подаче и рабочие перемещения. ИИ-технолог отвечает на вопрос «почему так» и предлагает альтернативы, а калькулятор даёт воспроизводимые цифры. Такая связка ценна для производства: генеративная модель не подменяет инженерный расчёт, а дополняет его.

Главное преимущество ИИ-технолога внутри СмартМаш по сравнению с универсальным чат-ботом — **контекст**. Управляющая программа здесь не отдельный файл на сетевом диске, а объект, привязанный к версии модели, к расчётным ограничениям из CAE и к конкретному станку.

## Ассистенты в каждом модуле

Конструктор и технолог — самые заметные, но не единственные ИИ-роли платформы. Каждый модуль получил своего узкоспециализированного помощника:

- **Инженер-расчётчик (МКЭ)** — интерпретация прочностных, тепловых и динамических расчётов, граничные условия, запасы прочности, усталостный анализ;
- **Специалист по оборудованию ЧПУ** — диагностика аварий, расшифровка кодов ошибок **Fanuc, Siemens, Heidenhain**, параметры, плановое обслуживание;
- **Менеджер жизненного цикла** — согласование КД, версии, переходы между стадиями, извещения об изменениях;
- **Производственный аналитик** — приоритеты заданий, узкие места, **ОЭО (OEE)**, планирование загрузки и снижение простоев.

Каждый ассистент знает, в каком разделе он работает, и отвечает в его терминах: конкретными цифрами, ссылками на стандарты и шагами диагностики. Для предприятия это прежде всего **снижение порога входа**: молодой технолог или наладчик быстрее выходит на самостоятельную работу, а опытные специалисты меньше отвлекаются на типовые вопросы.

