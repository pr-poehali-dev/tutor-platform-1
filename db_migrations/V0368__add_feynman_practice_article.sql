## Где это пригодится уже на следующей неделе

**Школьнику.** Готовитесь к экзамену — не перечитывайте конспект в пятый раз. Закройте его и объясните тему вслух пустой комнате. Места, где запнулись, и есть то, что вы не знаете. Остальное перечитывать бессмысленно.

**Родителю.** Ребёнок говорит «я всё выучил». Попросите объяснить вам как маленькому. За две минуты станет ясно, выучил или пролистал.

**Руководителю.** Перед совещанием объясните свою идею простыми словами самому себе. Если не получается — на совещании тоже не получится, только там будет дороже.

**Кому угодно.** Прочитали статью, посмотрели ролик, прошли курс. Прежде чем сказать «я разобрался» — объясните вслух. Разница между «понял» и «понимаю» обнаружится мгновенно.

