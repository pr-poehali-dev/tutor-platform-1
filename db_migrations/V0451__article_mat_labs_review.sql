## СмартМаш: попытка закрыть разрыв в станкостроении

Это самый «тяжёлый» продукт компании. Проблема, которую он решает, знакома любому машиностроительному производству: конструкторская документация (КД), прочностные расчёты (CAE), управляющие программы для станков (CAM) и производственное исполнение (MES) живут как независимые артефакты. Конструктор меняет геометрию, а расчёт и управляющая программа остаются старыми. Ошибка всплывает на сборке.

Архитектура СмартМаш строится вокруг **единой цифровой модели изделия** и шести контуров:

- **КД** — параметрическая библиотека из 20 типовых деталей по ГОСТ и DIN и автоматический поиск геометрических коллизий.
- **CAE** — конечно-элементный, тепловой, динамический и усталостный анализ прямо на цифровой модели.
- **CAM** — управляющие программы привязаны к версии модели и конкретному станку и проходят проверку технологичности.
- **ЖЦИ** — цифровой паспорт фиксирует цепочку от черновика до архива.
- **MES** — телеметрия станков пишет фактические режимы обработки обратно в паспорт детали.
- **Сквозные задания** — агрегируют данные всех контуров.

Главная инженерная идея — **переход между контурами возможен только при совпадении версий**. Несогласованная документация блокируется на уровне протокола передачи данных, а не регламента.

**Где проект сейчас.** Компания честно указывает уровень готовности: **TRL 5**, то есть проверка в условиях, близких к реальным. По данным компании, в пилотной эксплуатации обработано 12 деталей и к контуру мониторинга подключено 4 станка. Время согласования КД сократилось с 7 до 2 дней, доля ошибок в управляющих программах снизилась на 38%. Переход на TRL 6 запланирован при расширении испытаний на 2–3 предприятия.

Выборка пока маленькая, и это нужно понимать. Но для российского ПО в станкостроении сама постановка задачи — редкость.

## SoloFly: дроны без оператора

SoloFly — экспериментальная система автономного управления БПЛА, сейчас в **открытой бете (v0.9)**.

Архитектура разделена на три слоя:

- **Борт** — полётный контроллер Pixhawk или Cube Orange с прошивкой Ardupilot или PX4, бортовой компьютер Raspberry Pi или Jetson Nano, обмен телеметрией по MAVLink v2, связь по 4G/LTE или радиоканалу. Вычисления критического пути выполняются на борту.
- **Облако** — приём телеметрии в реальном времени, планирование маршрутов и миссий, компьютерное зрение на YOLO11, координация роя, REST API и MAVLink-прокси.
- **Командный центр** — веб-интерфейс без установки: карта с позициями дронов, телеметрия, конструктор миссий по точкам, журнал полётов.

Ставка на открытый стек MAVLink, Ardupilot и PX4 позволяет работать с широким кругом аппаратов, а серверы в России закрывают требования 152-ФЗ.

**Где проект сейчас.** Компания ведёт НИОКР в четыре этапа. Математическая модель адаптивной маршрутизации и алгоритм принятия решений с объяснимым ИИ (XAI) находятся в разработке. Сценарии потери связи и лётная верификация на полигоне — в планах. То есть это исследовательский проект с работающим интерфейсом, а не серийный продукт. Компания так его и подаёт.

