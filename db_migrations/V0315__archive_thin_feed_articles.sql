-- Чистка ленты: убираем из показа автоматические новости-пересказы,
-- которые никто не читает и которые не относятся к продуктам платформы.
--
-- Логика отбора (только заведомый балласт):
--   source_kind = 'agent'  — сгенерировано автоматически, не редакция
--   views = 0              — за всё время ни одного прочтения
--   LENGTH(content) < 1000 — слишком короткие, поиск считает такое «тонким» контентом
--
-- Ничего не удаляем: ставим статус 'archived'. Статьи исчезают из ленты,
-- из карты сайта и из поиска, но остаются в базе и их можно вернуть одним UPDATE.
-- Авторские статьи (manual/editorial) и всё, что хоть раз читали, не трогаем.

UPDATE t_p78828167_tutor_platform_1.feed_articles
SET status = 'archived',
    updated_at = now()
WHERE status = 'published'
  AND source_kind = 'agent'
  AND views = 0
  AND LENGTH(content) < 1000;
