## Ось 2. Размер и место запуска

Вторая ось — куда более практичная, чем кажется.

**Флагманы.** Самые большие модели, работают только в облаке разработчика. GPT-6 Astra, Claude Opus, Gemini Ultra. Максимальное качество, максимальная цена, ваши данные уходят на чужие серверы.

**Средние.** Компромисс, на котором работает большинство реальных продуктов: заметно дешевле флагмана, качество для типовых задач сопоставимое. Sonnet у Anthropic, Flash у Google, mini-версии у OpenAI.

**Малые и открытые.** Запускаются на своём железе, иногда на обычном ноутбуке. Llama, Qwen, Mistral, российские GigaChat и YandexGPT в компактных версиях. Качество ниже флагманов, но для узкой задачи — достаточное.

Здесь возникает вопрос, который стал решающим для бизнеса: **где физически лежат ваши данные**.

Если вы обрабатываете персональные данные клиентов, медицинские записи, финансовую отчётность или коммерческую тайну — вопрос «какая модель умнее» отступает перед вопросом «куда уходит запрос». Открытая модель на своём сервере проигрывает флагману в эрудиции, но не отправляет ваш договор в чужое облако. Для многих отраслей это не предпочтение, а требование закона.

Для российских компаний добавляется практическая сторона: доступ к зарубежным флагманам нестабилен, оплата затруднена, а [GigaChat и YandexGPT](/courses/ai) работают без этих сложностей и лучше понимают локальный контекст — от делового этикета до особенностей документооборота.

## Ось 3. Модальность: с чем модель работает

Третья ось — что модель умеет принимать на вход и выдавать на выходе.

**Текстовые.** Классика: текст на входе, текст на выходе.

**Мультимодальные.** Понимают картинки, документы, схемы, скриншоты, аудио. Сюда же — распознавание рукописного текста и чтение таблиц с фотографии. Все современные флагманы мультимодальны.

**Генеративные по медиа.** Отдельный класс: рисуют изображения, монтируют видео, синтезируют речь и музыку. Midjourney, Sora, Runway, Kandinsky. Это **не** конкуренты текстовым моделям — они решают другую задачу и живут по другим правилам.

**Агентные.** Самое интересное направление 2026 года. Модель не просто отвечает, а действует: ходит в интернет, запускает код, работает с файлами, вызывает внешние сервисы, выполняет цепочку шагов без вашего участия на каждом.

Именно агентность — главная линия конкуренции сейчас. Claude Opus 4.5 позиционируется как сильнейшая модель для программирования и работы с компьютером, Gemini 3 сделал ставку на агентные сценарии, GPT-6 Astra — на длинные автономные задачи. Умение отвечать красиво перестало быть преимуществом. Умение довести дело до конца — стало.

