## Проблема: две правды о магазине

У владельца интернет-магазина обычно две системы, которые не знают друг о друге:

- **Яндекс Метрика** показывает визиты, источники трафика и конверсии
- **МойСклад** показывает заказы, отгрузки, выручку и остатки

По отдельности они не отвечают на главный вопрос: **реклама и трафик превращаются в деньги или нет?** Визитов стало больше — а заказов? Конверсия упала — это сайт или просто кончился ходовой товар?

Обычно ответ ищут так: раз в неделю выгружают оба отчёта в Excel и сверяют по датам. Ниже — как сделать, чтобы данные собирались сами каждое утро.

## Что понадобится

| Что | Где взять |
|---|---|
| Рабочая почта | На неё придёт код входа в кабинет |
| Токен МойСклад | МойСклад → «Настройки» → «Токены» |
| Номер счётчика Метрики | Список счётчиков на metrika.yandex.ru |
| OAuth-токен Метрики | oauth.yandex.ru, право «Получение статистики» |
| ID цели (по желанию) | Метрика → «Настройки» → «Цели» |

Всё это бесплатно и делается без программиста. Подключение занимает около 10 минут.

## Пример: что хотим получить

Условный магазин «ЭкоЛавка» продаёт товары для дома, около 40 заказов в день. Владелец хочет каждое утро видеть на одном экране:

- сколько было визитов и откуда
- сколько оформлено заказов и на какую сумму
- какая доля визитов превращается в заказы

Понадобится два источника: **заказы покупателей из МойСклад** и **источники трафика из Метрики**. Оба помещаются в бесплатный тариф «Старт»: 2 источника до 10 000 строк в каждом.

## Шаг 0. Вход в кабинет — 1 минута

1. Откройте [mat-labs.ru/analytics/pipes](https://mat-labs.ru/analytics/pipes) и нажмите «Подключить бесплатно».
2. Введите почту и код из письма. Пароль не нужен, аккаунт на тарифе «Старт» создаётся автоматически.

## Шаг 1. Подключаем МойСклад — 2 минуты

1. В МойСклад откройте «Настройки» → «Токены».
2. Создайте токен для пользователя **с правами только на чтение** нужных документов. Лучше завести для этого отдельного пользователя.
3. В кабинете конвейера нажмите «Новый источник» и выберите **МойСклад**.
4. Вставьте токен в поле «Токен доступа».
5. В поле «Что загружать» выберите, что нужно для отчёта:

| Вариант | Когда выбирать |
|---|---|
| Заказы покупателей | Хотите видеть спрос — что заказали на сайте |
| Отгрузки | Хотите видеть реальную выручку — что отправили клиенту |
| Остатки по товарам | Хотите видеть, что заканчивается на складе |
| Товары, Контрагенты | Справочники для более сложных отчётов |

Для «ЭкоЛавки» берём **«Заказы покупателей»** — их проще всего сравнивать с визитами на сайт.

Хорошая новость: суммы в МойСклад хранятся в копейках, а конвейер **сам переводит их в рубли**.

Нажмите «Проверить подключение» — мастер покажет первые строки заказов.

## Шаг 2. Подключаем Яндекс Метрику — 3 минуты

1. **Номер счётчика.** Откройте metrika.yandex.ru — номер указан рядом с названием сайта в списке счётчиков.
2. **OAuth-токен.** На oauth.yandex.ru создайте приложение с правом **«Получение статистики»** и получите токен. Это доступ только к чтению отчётов, изменить настройки счётчика по нему нельзя.
3. В кабинете нажмите «Новый источник» и выберите **Яндекс Метрика**.
4. Заполните поля:

| Поле | Что выбрать для «ЭкоЛавки» |
|---|---|
| Номер счётчика | например, `12345678` |
| OAuth-токен | токен из шага 2 |
| Отчёт | **Источники и UTM по дням** |
| ID цели | номер цели «Заказ оформлен» — добавит достижения цели и конверсию |
| За сколько дней | **90 дней** |

Кроме источников, доступны ещё два отчёта: **«Страницы входа по дням»** (какие страницы приводят покупателей) и **«Города и устройства по дням»** (откуда и с чего заходят).

**Совет про цель.** Если в Метрике настроена цель на оформление заказа, обязательно укажите её ID. Тогда в отчёте появятся не просто визиты, а конверсия по каждому источнику: видно, что из рекламы приходит много людей, но покупают в основном те, кто пришёл из поиска.

## Шаг 3. Чистим данные — 1 минута

Для обоих источников отметьте в мастере:

- **Удалить пустые строки** и **убрать лишние пробелы**
- **Удалить дубли** — для заказов дублем стоит считать одинаковый номер заказа
- **Даты к формату ГГГГ-ММ-ДД** — это важно: так даты из МойСклад и Метрики совпадут, и их можно сопоставить день в день
- **Часовой пояс отчётов** — одинаковый для обоих источников, например московское время. Иначе поздний вечерний заказ может «уехать» на следующий день

Результат виден сразу на живой пробе данных.

## Шаг 4. Ставим расписание — 30 секунд

Выберите **«Раз в сутки»**: к утру в отчёте будут вчерашние визиты и заказы. Если загрузка сломается, например истечёт токен, придёт письмо с причиной, а сервис сам повторит попытку.

## Шаг 5. Смотрим отчёт — 2 минуты

У каждого источника есть кнопка **«Открыть в BI»**. [Облачный BI](https://mat-labs.ru/analytics/bi) сам распознает даты, суммы и категории и построит графики. Клик по столбцу фильтрует весь дашборд — например, можно оставить только один источник трафика или один день.

Что увидит владелец «ЭкоЛавки»:

| Вопрос | Где ответ |
|---|---|
| Сколько визитов и из каких источников | Дашборд Метрики |
| Какой источник даёт больше всего оформленных заказов | Дашборд Метрики с целью |
| Сколько заказов и на какую сумму по дням | Дашборд МойСклад |
| Средний чек и самые частые позиции | Дашборд МойСклад |

### Как увидеть всё на одном графике

Каждый источник открывается в BI отдельно. Чтобы положить визиты и заказы на одну ось, используйте **постоянные CSV-ссылки** источников — они всегда отдают свежие данные:

1. Подключите обе ссылки в Google Таблицы, Yandex DataLens или Power BI.
2. Соедините таблицы по дате — для этого мы и приводили даты к одному формату.
3. Добавьте расчёт: **заказы за день ÷ визиты за день** — это и есть реальная конверсия сайта в продажи.

Если хочется готовую единую витрину без настройки — её собирают на тарифе «Под ключ».

## Что обычно выясняется в первую неделю

Типичные находки, ради которых такой отчёт и стоит собрать:

- **Дни с высоким трафиком и провалом заказов.** Часто это не сайт, а закончившийся ходовой товар. Проверить помогает третий источник — «Остатки по товарам».
- **Источник с большим трафиком и почти нулевой конверсией.** Повод пересмотреть рекламную кампанию, а не наращивать бюджет.
- **Заказы и отгрузки расходятся.** Если подключить и то и другое, видно, сколько заказов отменяется и не доходит до клиента.

