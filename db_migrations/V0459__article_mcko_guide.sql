## Что такое МЦКО

МЦКО — Московский центр качества образования. Центр составляет и проводит независимые диагностики в школах Москвы: проверяет, как ученики усвоили программу и умеют ли применять знания на практике.

Важно понимать: диагностика МЦКО — это не экзамен. Её задача — показать школе и учителю, какие темы класс понял хорошо, а какие нужно повторить. Но для ученика это всё равно контрольная, и хорошая подготовка снимает лишний стресс.

## Когда проходят диагностики

График утверждают в начале учебного года, и он меняется от года к году. Основная часть работ обычно приходится на вторую половину учебного года. Актуальный график для своего класса уточняйте на сайте МЦКО или у классного руководителя: школа публикует его у себя на сайте.

Работы бывают двух форматов:
- **бланковые** — на бумаге, как обычная контрольная
- **компьютерные** — ученик отвечает за компьютером в школе

Для компьютерных работ на сайте МЦКО есть онлайн-тренажёры. Обязательно пройдите тренажёр хотя бы раз: многие ошибки на диагностике — не от незнания, а от непривычного интерфейса.

## Математика: что проверяют

Задания похожи на обычные школьные, но с акцентом на понимание, а не на шаблон:
- вычисления и действия с дробями
- текстовые задачи на движение, покупки, проценты
- работа с таблицами, диаграммами и графиками
- геометрия: периметр, площадь, углы, чтение чертежа
- логические задачи и задачи «на смекалку»

**Пример задания в формате диагностики (учебный, составлен редакцией).** Тетрадь стоит 48 ₽, а при покупке трёх тетрадей действует скидка 10% на всю покупку. Сколько рублей сдачи получит покупатель с 200 ₽ за три тетради?

*Решение:* 48 × 3 = 144 ₽. Скидка 10% — это 14,4 ₽. К оплате 129,6 ₽. Сдача: 200 − 129,6 = 70,4 ₽.

Типичная ошибка — посчитать скидку только с одной тетради. Поэтому главный навык для математики МЦКО — внимательно читать условие и проверять, ответил ли ты именно на заданный вопрос.

**Как готовиться:** по 2–3 текстовые задачи в день, и после каждой — проговорить, что было дано и что спрашивали. В 9 классе подготовка к диагностике по алгебре и геометрии во многом совпадает с подготовкой к ОГЭ.

## Русский язык: что проверяют

- орфография и пунктуация — правило нужно не только знать, но и найти в предложении
- морфология и синтаксис: части речи, члены предложения, сложные предложения
- лексика: значение слова, синонимы, фразеологизмы
- работа с текстом: главная мысль, тип и стиль речи

**Как готовиться:** короткие ежедневные диктанты по 5–7 предложений с разбором ошибок дают больше, чем час правил перед контрольной. Записывайте свои ошибки в отдельную тетрадь — через две недели станет видно, какие темы «проседают».

## Читательская грамотность: самое недооценённое

Это умение не просто прочитать текст, а **найти в нём информацию, понять и оценить её**. Задания обычно построены вокруг одного или нескольких текстов: статьи, инструкции, объявления, таблицы.

Что нужно уметь:
1. Найти конкретный факт в тексте.
2. Сформулировать главную мысль своими словами.
3. Сопоставить два источника и найти противоречие.
4. Оценить, можно ли доверять информации и почему.

**Пример (учебный).** Объявление: «Бассейн закрыт на ремонт с 3 по 10 марта. Абонементы будут продлены на срок закрытия». Маша купила абонемент до 15 марта. До какого числа он теперь действует?

*Ответ:* бассейн закрыт 8 дней (с 3 по 10 марта включительно), значит абонемент продлевается до 23 марта. Здесь проверяется не арифметика, а умение внимательно прочитать условие объявления.

Именно здесь чаще всего теряют баллы дети, которые читают медленно: на чтение уходит слишком много времени, и на задания его не хватает. Поэтому подготовку к читательской грамотности стоит начинать с проверки скорости и понимания чтения.

## Функциональная грамотность: знания в жизни

Функциональная грамотность — комплексная проверка: читательская, математическая и естественно-научная грамотность в одной работе. Задания построены на жизненных ситуациях: рассчитать бюджет поездки, выбрать выгодный тариф, понять инструкцию к прибору, объяснить явление природы.

**Как готовиться:** чаще давайте ребёнку реальные задачи. Посчитать, сколько стоит продуктовая корзина. Сравнить два тарифа мобильной связи. Прочитать инструкцию и объяснить её своими словами. Такие задания тренируют ровно то, что проверяет диагностика.

