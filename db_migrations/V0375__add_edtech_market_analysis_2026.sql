## Кто выиграет в ближайшие два года

Три типа игроков.

**Первые — те, кто научится доводить до конца.** Если у вас доходимость 40% против рыночных 10%, вы можете платить за привлечение втрое больше конкурентов и всё равно оставаться в плюсе. Это самое сильное конкурентное преимущество в отрасли.

**Вторые — узкие специалисты.** Общие курсы «всё для всех» проигрывают. Выигрывают те, кто глубоко закрывает конкретную задачу конкретной аудитории.

**Третьи — те, у кого повторные покупки.** Ученик, вернувшийся за вторым курсом, обходится почти бесплатно. Модель «продал один раз и забыл» перестаёт сходиться экономически.

## Что это значит на практике

**Если вы запускаете онлайн-школу:** не стройте модель на дешёвом трафике — его больше нет. Считайте не стоимость привлечения, а сколько денег приносит ученик за всё время. Вкладывайтесь в доходимость до того, как начнёте вкладываться в рекламу.

**Если вы выбираете, где учиться:** спрашивайте не про программу, а про то, сколько человек доходит до конца и что происходит, когда вы застреваете. Обещания результата без цифр — маркетинг.

**Если вы преподаёте:** ваша ценность смещается от объяснения материала к сопровождению. Объяснить может и машина. Не дать бросить — пока нет.

