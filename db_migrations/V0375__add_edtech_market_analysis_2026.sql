## Сколько стоит рынок

По итогам 2025 года объём российского рынка онлайн-образования оценивается примерно в **150–160 млрд рублей**. Оценки разных исследователей расходятся: методики считают по-разному — кто-то включает корпоративное обучение, кто-то нет, кто-то учитывает репетиторов-физлиц.

