**Главная цифра не в объёме, а в динамике.** В 2021–2022 годах рынок рос на 30–40% в год. По итогам 2025-го — примерно на 12–15%. Прогноз на 2026-й: рост в пределах 10–14%.

Это не спад. Это переход от бурного роста к нормальному, и он меняет правила игры сильнее, чем кажется.

