**Пандемийный эффект закончился.** Всплеск 2020–2021 годов был вынужденным: людей загнали в онлайн обстоятельства. Часть из них после снятия ограничений вернулась в офлайн — особенно в детском сегменте, где родители ценят живой контакт с преподавателем.

