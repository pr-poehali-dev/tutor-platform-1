## 3. Оркестратор: перестать получать «сделали не то»

**Ситуация.** Ольга третий раз нанимает копирайтера на удалёнке. Каждый раз одно и то же: текст приходит в последний день и не совпадает с ожиданием. Виноватыми кажутся исполнители.

**Что делает инструмент.** Вы описываете роль и специфику проекта — например, «копирайтер для интернет-магазина детской одежды». ИИ собирает трек адаптации:

**Матрицу навыков** — что исполнитель обязан уметь, а что желательно. Разделение критично: без него любой кандидат выглядит неподходящим.

**Входной контроль** — как проверить эти навыки до старта работы, а не через месяц.

**План онбординга по дням** — что человек делает в первый день, на третий, на первой неделе.

**Микрозадачи с критериями «готово»** — самое ценное. Не «написать текст», а описание результата, при котором работа считается принятой. Именно отсутствие таких критериев порождает бесконечные правки.

**Карту рисков** — где конкретно в этой роли обычно случаются срывы.

**В чём была ошибка Ольги.** Не в исполнителях. Она передавала задачу словами «нужен текст для карточек товара, посмотрите как у конкурентов». Три разных человека поняли это тремя разными способами — и все три раза были по-своему правы.

**Чем отличается от таск-трекера.** Трекер хранит список задач. Здесь выстроена связка: онбординг → задачи → обучение → метрики. Входной контроль отсеивает слабых до старта, критерии «готово» снижают правки, карточки качества показывают риски по каждому исполнителю заранее.

