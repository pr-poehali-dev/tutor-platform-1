  '## Почему сочинение не получается

Большинство школьных сочинений проваливаются по одной причине: вместо мысли в них пересказ. Ученик честно прочитал книгу и честно рассказывает, что в ней произошло. Учитель ставит «три» и пишет на полях: «Где ваша позиция?»

Журналиста с первого курса учат обратному. Читателю не нужен пересказ событий — ему нужен **ответ на вопрос**, который его волнует. Хороший материал всегда отвечает на один вопрос, держится на фактах и ведёт читателя от заголовка до последней строки.

Сочинение по литературе устроено точно так же. Ниже — методика в семь шагов, которую можно применить к любому произведению: от «Капитанской дочки» в 8 классе до «Войны и мира» в 10-м.

## Шаг 1. Читайте как репортёр, а не как зритель

Журналист приходит на событие с блокнотом. Читатель сочинения тоже должен.

Пока читаете, заведите **рабочую тетрадь** и записывайте три вещи:

- **Поступки героев** — с номером страницы. Не «Печорин плохой», а «Печорин похищает Бэлу ради скуки, с. 34».
- **Яркие цитаты** — короткие, по 5–15 слов. Длинную цитату вы не вспомните на экзамене.
- **Свои вопросы** — «Почему Татьяна отказала Онегину, если любит?». Из вопросов потом вырастают темы.

Это ваши «факты с места событий». Без них сочинение превращается в мнение без доказательств, а журналист такой материал в печать не сдаст.

**Лайфхак:** если времени мало, после каждой главы запишите одно предложение — «что изменилось». Через неделю у вас будет готовая карта книги.

## Шаг 2. Найдите «новость» — свою главную мысль

В журналистике есть правило: у материала одна главная мысль, и её можно сказать за 20 секунд. В школе её называют **тезисом**.

Тема сочинения — это вопрос. Тезис — ваш ответ на него.

- Тема: «Почему Раскольников признался в преступлении?»
- Слабый тезис: «Раскольников признался, потому что его мучила совесть». Это правда, но это знает каждый.
- Сильный тезис: «Раскольников признаётся не из страха наказания, а потому что его теория рухнула: он понял, что он не „право имеющий“, а обычный человек, и жить с этим в одиночку невозможно».

Проверьте тезис журналистским тестом: **может ли с ним кто-то поспорить?** Если не может — это не мысль, а очевидность. Хорошая «новость» всегда немного спорная.

## Шаг 3. Соберите доказательства, как факты для статьи

Журналист не пишет «все знают, что…». Он приводит факт, цитату, свидетеля. В сочинении ваши факты — это **аргументы из текста**.

Для каждого аргумента нужно три элемента — запомните формулу **«эпизод — цитата — вывод»**:

1. **Эпизод.** Где и что происходит: «В сцене последнего объяснения с Онегиным…»
2. **Цитата или деталь.** «…Татьяна говорит: „Я вас люблю (к чему лукавить?), но я другому отдана“».
3. **Вывод.** Что это доказывает для вашего тезиса: «Для неё верность слову выше чувства — и в этом её сила, а не слабость».

Самая частая ошибка — пропустить третий шаг. Цитата без вывода — это как фотография без подписи: читатель видит картинку, но не понимает, зачем вы её показали.

**Сколько аргументов нужно:** в итоговом сочинении — минимум один из литературы, лучше два. В обычном школьном — два-три. Один подробно разобранный эпизод лучше трёх упомянутых вскользь.

## Шаг 4. Постройте материал: заход, тело, финал

У журналистского текста три части, и они идеально ложатся на школьную структуру.

### Заход (вступление) — 10–15% текста

Задача захода — зацепить. Журналисты используют несколько приёмов, и все они работают в сочинении:

- **Вопрос:** «Можно ли убить ради счастья человечества?»
- **Парадокс:** «Самый честный герой романа — убийца».
- **Деталь:** «Желтый цвет преследует Раскольникова по всему Петербургу: обои, лица, вода в канале».
- **Связь с сегодняшним днём:** «Каждый, кто хоть раз оправдывал плохой поступок „высокой целью“, немного Раскольников».

После захода — тезис. Одно-два предложения. Это ваше обещание читателю.

**Чего избегать:** биографии автора («Ф. М. Достоевский родился в 1821 году…») и общих фраз («Эта тема всегда была актуальной»). Это «вода», за которую снимают баллы.

### Тело (основная часть) — 70–80% текста

Каждый аргумент — отдельный абзац по формуле «эпизод — цитата — вывод». Между абзацами — **связки**, чтобы мысль не прыгала:

- «Однако этим дело не ограничивается…»
- «Ещё ярче это проявляется в сцене…»
- «На первый взгляд кажется, что…, но на самом деле…»

Журналистский приём: расставьте аргументы **по нарастанию силы**. Самый сильный — последним, чтобы читатель вышел из основной части убеждённым.

### Финал (заключение) — 10–15% текста

Финал не повторяет вступление слово в слово. Хорошее заключение делает одно из трёх:

- возвращает к вопросу из захода и отвечает на него;
- расширяет мысль: что этот вывод значит для нас сегодня;
- оставляет точку, которую хочется перечитать.

Пример: «Достоевский не оправдывает и не казнит своего героя. Он показывает: никакая теория не стоит одной человеческой жизни — даже жизни „ненужной“ старухи».

## Шаг 5. Заголовок и первая фраза решают всё

Редакторы говорят: если первая фраза скучная, вторую уже не прочтут. Учитель прочтёт, но настроение у него будет соответствующее.

Сравните:

- «В романе И. С. Тургенева „Отцы и дети“ поднимается много проблем».
- «Базаров отрицает всё — любовь, искусство, природу. И проигрывает именно тому, что отрицал».

Второй вариант сразу показывает, что у автора есть мысль. Потратьте на первую фразу пять минут — это лучшие пять минут всего сочинения.

## Шаг 6. Редактура: правило «минус 20%»

Журналист никогда не сдаёт первый вариант. После черновика проведите редактуру по чек-листу:

- **Каждый абзац отвечает на тему?** Если абзац интересный, но «не про то» — вычёркивайте.
- **Нет пересказа ради пересказа?** Сюжет пересказываем только настолько, чтобы читатель понял эпизод.
- **Есть вывод после каждой цитаты?**
- **Нет повторов слов?** «Герой… герой… герой» заменяйте на имя, «персонаж», «юноша», «Онегин».
- **Нет штампов?** «Красной нитью проходит», «нельзя не отметить», «в наше нелёгкое время» — вычёркиваем.
- **Предложения не длиннее 25–30 слов?** Длинные фразы путают и вас, и проверяющего.

Сократите черновик примерно на 20%. Почти всегда текст от этого становится сильнее.

## Шаг 7. Проверьте себя критериями

Перед сдачей пройдитесь по главным критериям, которые оценивают и в школе, и на итоговом сочинении:

1. **Соответствие теме** — вы отвечаете именно на поставленный вопрос.
2. **Аргументация** — есть опора на текст произведения, а не только общие слова.
3. **Композиция** — есть вступление, основная часть и заключение, мысль развивается логично.
4. **Качество речи** — мысль выражена точно, без повторов и речевых ошибок.
5. **Грамотность** — орфография, пунктуация, грамматика.

Для итогового сочинения есть два обязательных требования: объём **не меньше 350 слов** и **самостоятельность** — текст не должен быть списан. Если не выполнено хотя бы одно, работу не проверяют дальше.

## Шпаргалка: план сочинения за 10 минут

Когда тема получена, не бросайтесь писать. Потратьте десять минут на план — журналисты называют это «скелетом материала»:

1. **2 минуты** — сформулируйте тезис одним предложением.
2. **4 минуты** — выберите два-три эпизода и запишите к каждому цитату или деталь.
3. **2 минуты** — придумайте заход: вопрос, парадокс или деталь.
4. **2 минуты** — набросайте финальную мысль.

С таким планом сочинение пишется в два раза быстрее, а главное — не «уплывает» от темы на середине.

## Пять ошибок, которые стоят баллов

- **Пересказ вместо анализа.** Помните: учитель читал книгу. Ему интересно, что думаете вы.
- **Цитата без вывода.** Каждую цитату нужно «отработать» — объяснить, что она доказывает.
- **Биография автора во вступлении.** Если она не нужна для ответа на вопрос — не пишите.
- **Слишком много героев и эпизодов.** Лучше глубоко про два эпизода, чем поверхностно про шесть.
- **Финал «в общем, это хорошее произведение».** Заключение — это ваш итоговый вывод по теме, а не оценка книги.

## Как тренироваться

Навык письма растёт только от практики — как у журналиста, который пишет каждый день. Простая система на учебный год:

- **Раз в неделю** пишите короткое эссе на 150–200 слов по прочитанной главе: один тезис, один аргумент.
- **Раз в месяц** — полноценное сочинение по плану выше.
- **Перечитывайте свои тексты через неделю.** Свежим глазом ошибки видны сразу.

