«Я думал, это делает Петров».

Задача провалена. Срок прошёл. И самое неприятное — виноватых нет. Каждый участник искренне считал, что зона ответственности была не его. Формально все правы.

Это не проблема дисциплины и не вопрос мотивации. Это дефект конструкции: **у задачи не было одного владельца**.

Разберём, как этот дефект устроен и как его чинить.

## Почему «ответственны все» означает «не отвечает никто»

Руководителю кажется, что чем больше людей вовлечено в задачу, тем надёжнее результат. Логика понятная: если один недосмотрит, второй подстрахует.

На практике работает противоположный механизм.

Когда за результат отвечают трое, каждый бессознательно снижает собственную включённость — ведь рядом есть ещё двое. Возникает эффект, при котором общая ответственность делится, а не умножается. Задача не проваливается громко: она **провисает тихо**, между зонами, и обнаруживается в день дедлайна.

Ключевой признак: если на вопрос «кто отвечает за результат?» в ответ звучит больше одной фамилии — владельца нет.

## Четыре признака, что ответственность размыта

Прежде чем чинить, нужно увидеть. Вот сигналы, которые обычно списывают на «человеческий фактор», хотя это дефекты конструкции.

**Первый: задача обсуждается, но не двигается.**

На каждом совещании про неё вспоминают, все кивают, статус не меняется неделями. Это классика провисания: обсуждение есть, владельца нет.

**Второй: срок «уточняется».**

Когда владелец есть, он называет дату. Когда владельца нет, дата всё время зависит от кого-то другого: «как только маркетинг пришлёт», «после того как согласуют».

**Третий: результат приходит в последний день — и не тот.**

Никто не сверялся по дороге, потому что сверка — это тоже чья-то зона, а она не назначена.

**Четвёртый: после провала начинается разбор, кто что имел в виду.**

Если восстановление картины требует переписки за три недели, значит роли не были зафиксированы письменно.

## Четыре роли вместо споров

Решение простое по идее и трудное в исполнении: у каждой задачи нужно развести четыре разные роли. Их путают чаще всего, и именно из-за этого возникают споры.

**Владелец результата.** Тот, с кого спросят. Один человек, не отдел и не «команда». Он не обязательно делает работу руками — он отвечает за то, что она сделана.

**Исполнитель.** Тот, кто делает. Их может быть несколько. Это единственная роль, которую можно размножать без ущерба.

**Согласующий.** Тот, без чьего «да» результат не принимается. Опасная роль: если согласующих больше двух, задача застрянет на этапе визирования.

**Информируемый.** Тот, кого нужно держать в курсе, но чьё мнение не блокирует работу. Самая недооценённая роль — её путают с согласующим, и тогда любой наблюдатель получает право вето.

Главная ошибка — смешение первой и второй роли. Руководитель назначает исполнителя и считает, что назначил владельца. Но исполнитель отвечает за свою часть работы, а не за итог целиком.

## Где путаются чаще всего

Три ситуации, в которых конструкция ломается даже у опытных руководителей.

**Задача на стыке отделов.** Маркетинг ждёт от продаж, продажи — от маркетинга. Владельца нет ни там, ни там, потому что каждый руководитель считает владельцем себя только в своей половине. Лечение: владелец назначается один на всю задачу, независимо от того, в чьём отделе он сидит.

**Задача, которую поставил сам руководитель.** Здесь владельцем по умолчанию считают его — и команда ждёт, что он же будет двигать. Лечение: назвать владельца вслух в момент постановки, даже если это очевидно.

**Слишком много согласующих.** Каждый, кого «на всякий случай» добавили в цепочку, получает право затормозить. Лечение: жёстко ограничить число согласующих и перевести остальных в информируемых.

## Экспресс-аудит за пять минут

Проверьте прямо сейчас — не абстрактно, а на конкретной задаче, которая сегодня буксует.

Возьмите одну задачу и ответьте письменно на четыре вопроса:

**1. Назовите одну фамилию — кто владелец результата?**

Если пишете две — вот причина провисания.

**2. Знает ли этот человек, что он владелец?**

Очень частый разрыв: руководитель назначил в голове, а сотруднику не сказал.

**3. Сколько людей могут заблокировать результат?**

Если больше двух — задача застрянет не на работе, а на согласовании.

**4. Где это зафиксировано письменно?**

Если только «проговорили на встрече», через месяц каждый вспомнит свою версию.

Если хотя бы на один вопрос ответа нет — задача провиснет. Это не прогноз, а закономерность.

## Что сделать сегодня

Не нужно перестраивать всю систему управления. Начните с одного действия.

**Возьмите три задачи, которые сейчас буксуют, и назначьте по каждой одного владельца. Письмом, а не устно.**

Формулировка занимает две строки: «По задаче X владелец — Иванов. Он отвечает за результат и срок. Согласует Петрова. Остальные в копии для информации».

Это письмо снимает будущий спор целиком. Через месяц никто не будет восстанавливать, кто что имел в виду.

## Почему это важнее, чем кажется

Размытая ответственность — самая дорогая из управленческих ошибок, потому что она невидима до момента провала. Плохую мотивацию видно сразу, слабого сотрудника видно за месяц. А отсутствие владельца не видно вообще, пока задача не сгорит.

И ещё одно наблюдение. Руководители, которые жалуются на безынициативность команды, почти всегда обнаруживают у себя именно этот дефект. Люди не проявляют инициативу не потому, что не хотят. Они не понимают границ своей зоны — и на всякий случай не выходят за них.

Дайте человеку ясную зону и одну фамилию в графе «владелец». Инициатива появляется как побочный эффект.

