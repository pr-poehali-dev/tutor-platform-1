## Почему бесплатно

Резонный вопрос, особенно когда вокруг всё стоит денег.

Три причины, честно.

**Первая.** Логика — это фундамент, а не надстройка. Ученик, у которого поставлено мышление, лучше идёт по всем остальным предметам. Нам выгодно, чтобы этот фундамент был у всех, кто к нам пришёл.

**Вторая.** Бесплатный курс — лучшая витрина платформы. Вы увидите, как устроены наши уроки, конспекты, практикумы и квизы, ничем не рискуя. Понравится — посмотрите платные курсы. Не понравится — вы всё равно получили 92 урока даром.

**Третья, прагматичная.** Мы зарабатываем на подписке и продаже курсов, а не на входном билете. Отдать логику бесплатно дешевле, чем объяснять, почему за развитие мышления надо платить.

Оплата не требуется ни на каком шаге. Курс для младших помечен «бесплатно навсегда» — это не акция, которая закончится в понедельник.

## Чего мы не обещаем

Тут по-честному, без маркетинга.

**Курсы не сделают ребёнка гением.** Логика — инструмент. Молоток не строит дом, им строит человек.

**Уроки ведёт ИИ-методист, не живой преподаватель.** Он объясняет, даёт задания, проверяет и подсказывает — но он не мотивирует так, как хороший учитель, и не заметит, что у ребёнка сегодня плохое настроение.

**Младшему школьнику нужен взрослый рядом.** Хотя бы первые уроки. Восьмилетка не всегда сам справится с интерфейсом и не всегда честно проверит себя.

**Один курс не заменит олимпиадную подготовку.** Он даёт базу, с которой на олимпиадную подготовку можно приходить. Это разные вещи.

**Результат не будет мгновенным.** Мышление ставится месяцами, а не за выходные.

