## Проблема, которую не видно в дневнике

Учитель говорит: «ребёнок невнимательный». Родитель слышит: «нужно больше стараться». Оба ошибаются.

Посмотрите на типичные жалобы:

— решает задачу, но не может объяснить, почему получилось именно так;
— выучил правило и не применяет его в новой формулировке;
— спорит эмоционально, а не аргументами;
— верит любому видео из интернета, если там уверенный голос;
— в сочинении есть мысли, но они не складываются в доказательство.

Это не пять разных проблем. Это одна: **не поставлено мышление**. Ребёнок умеет запоминать и воспроизводить, но не умеет выводить одно из другого.

Логика — это и есть механика вывода. Как биссектриса делит угол пополам, так силлогизм делит рассуждение на посылки и заключение. Разница в том, что биссектрису показывают в седьмом классе, а силлогизм не показывают никогда.

## Что мы сделали

Три курса под три возраста. Не один курс, разбавленный для младших и усложнённый для старших, — три разные программы, потому что в 8 лет и в 17 лет мышление ставится по-разному.

### 1–4 класс: «Головоломки и закономерности»

24 урока по 15 минут. Четыре модуля: закономерности, лабиринты и пространство, ребусы и истина-ложь, логические игры.

Здесь нет слова «логика» вообще. Есть «продолжи ряд», «найди лишнее», «зеркало и симметрия», «задачи на взвешивание», «головоломки со спичками». Финал курса называется «турнир смекалистых».

Ребёнок думает, что играет. Формально он осваивает классификацию, обобщение, пространственное мышление и различение истинных и ложных высказываний. Это настоящая программа развития мышления, просто упакованная так, чтобы её проходили добровольно.

Курс бесплатный навсегда. 3100 учеников, рейтинг 4.95.

### 5–8 класс: «Алгоритмы, множества и комбинаторика»

36 уроков по 25–30 минут. Это ядро, и здесь становится серьёзно.

**Модуль 1 — высказывания.** Что такое высказывание, связки И/ИЛИ/НЕ, таблицы истинности, задачи про рыцарей и лжецов.

**Модуль 2 — множества.** Круги Эйлера, пересечение, объединение, разность. Тот самый аппарат, которым потом решаются задачи «сколько человек изучают и английский, и немецкий» — за десять секунд вместо десяти минут перебора.

**Модуль 3 — алгоритмы и графы.** Блок-схемы, переливания и взвешивания, вершины и рёбра, кратчайший путь, задачи на рукопожатия.

**Модуль 4 — комбинаторика.** Правила суммы и произведения, перестановки, сочетания, олимпиадные задачи на синтез методов.

Это прямая база для информатики и олимпиад. Задания ОГЭ по информатике на логические выражения и таблицы истинности после этого курса перестают быть отдельной темой для зубрёжки — они становятся очевидными.

Самый популярный курс из трёх: 4200 учеников, рейтинг 4.92.

### 10–11 класс: «Логика и критическое мышление»

32 урока по 35–40 минут. И вот здесь начинается то, ради чего всё затевалось.

**Модуль 1 — формальная логика.** Понятие, его содержание и объём. Суждение. Законы тождества, противоречия, исключённого третьего.

**Модуль 2 — умозаключения.** Дедукция, индукция, аналогия. Категорический силлогизм и его правила. Типичные ошибки вывода.

**Модуль 3 — софизмы, уловки, когнитивные искажения.** Подмена тезиса. Ложная дилемма. Манипуляции и приёмы давления. Искажение подтверждения.

**Модуль 4 — аргументация.** Структура аргумента: тезис, основание, поддержка. Как строить и опровергать доводы. Анализ источников, рекламы и новостей. Финал — дебаты.

Прочитайте список из третьего модуля ещё раз и подумайте, сколько взрослых людей вокруг вас владеют этим материалом.

2400 учеников, рейтинг 4.96 — самый высокий из трёх.

## Зачем это школьнику прямо сейчас

Отложим разговор про «пригодится в жизни». Вот конкретная польза в ближайшие два года.

**Сочинение ЕГЭ.** Эксперт снимает баллы не за плохие мысли, а за недоказанные. Структура «тезис — основание — поддержка» из четвёртого модуля — это буквально то, что требуют критерии.

**Обществознание.** Половина заданий второй части — на аргументацию и примеры. Умение отличать аргумент от мнения даёт баллы напрямую.

**Информатика.** Логические выражения и таблицы истинности — отдельная линия заданий ОГЭ и ЕГЭ.

**Олимпиады.** Задачи на переливания, взвешивания, графы и комбинаторику — стандартный набор школьного этапа почти по любому предмету.

**Математика.** Доказательство в геометрии — это дедукция. Ребёнок, который понимает, как устроен вывод, перестаёт заучивать доказательства и начинает их восстанавливать.

