## Что делать поставщику: пять шагов

1. **Мониторьте ЕИС ежедневно.** При сроке подачи 7–8 дней закупку нужно увидеть в первые 1–2 дня — иначе не останется времени на расчёт и документы. Настройте поиск по ключевым словам и кодам ОКПД2 вашей продукции и получайте новые лоты на почту.
2. **Начните с массового сегмента.** Закупки до 1 млн ₽ — 70% рынка 44-ФЗ. Здесь проще получить первый опыт исполнения контрактов, который потом понадобится для крупных лотов.
3. **Работайте с уполномоченными органами регионов.** Одна подписка на извещения регионального органа закрывает закупки десятков учреждений.
4. **Посмотрите на 223-ФЗ.** Госкомпании платят больше: медиана — 750 тыс. ₽ против 395 тыс. ₽ по 44-ФЗ. Многие проводят отдельные закупки только для малого и среднего бизнеса.
5. **Готовьтесь к сезону сейчас.** Поток уже вырос на 15–20%, впереди ноябрь и декабрь. Подготовьте типовые заявки, коммерческие предложения и обеспечение заранее.

