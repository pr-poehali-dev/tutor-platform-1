## Почему программу показываем до оплаты

Это осознанное решение, и на нём стоит остановиться.

Обычная схема в онлайн-образовании: подробное описание в продающем виде, оплата, и только потом человек понимает, что получил. Отсюда возвраты, разочарования и общее недоверие к отрасли.

Мы делаем наоборот: **сначала программа, потом решение**. Человек видит структуру курса, объём, что именно будет изучать, и решает, стоит ли это денег.

У такого подхода есть цена: часть людей посмотрит программу и уйдёт учиться самостоятельно. Мы считаем это нормальным. Если человеку хватило структуры, чтобы разобраться самому, — значит, платная услуга ему была не нужна, и продавать её было бы нечестно.

Остаются те, кому нужно сопровождение, проверка и экспертиза. С ними и стоит работать.

## Сколько это стоит и почему

Индивидуальный курс — **от 10 000 ₽**.

Разберём, из чего складывается цена. Проектирование программы стало дешёвым — его берёт на себя технология. Дорого стоит человеческая часть: методист согласует детали, эксперт проверяет работы, наставник даёт обратную связь.

Точная сумма зависит от объёма: курс на четыре недели и курс на три месяца стоят по-разному. Поэтому цифра называется после разговора, а не выставляется автоматически.

Сравнение для ориентира. Готовый курс дешевле — но человек платит за всё, а использует часть. Индивидуальные занятия с преподавателем стоят кратно дороже. **Персональная программа находится между ними: дороже коробки, дешевле репетитора.**

## Кому это действительно нужно

Стоит честно очертить границы. Раздел решает четыре ситуации:

**Узкая тема, которой нет в готовых курсах.** Рынку невыгодно делать курс на сто человек — но этим ста людям знания нужны.

**Курс есть, но он «почти о том».** Не хватает вашей специфики: отрасли, масштаба, региона, типа бизнеса.

**Нужны знания под конкретную рабочую задачу.** Не профессия целиком, а решение задачи, которая стоит прямо сейчас.

**Нужен свой темп.** Готовый курс задаёт ритм, который не всегда совпадает с жизнью.

А вот когда **не нужно**: если в каталоге есть курс, который вас устраивает, — берите его, он дешевле. Индивидуальная программа имеет смысл тогда, когда готовая действительно не подходит, а не когда просто хочется «поперсональнее».

