Когда проектирование дешевеет, **преимущество масштаба размывается**. Курс на тысячу человек перестаёт быть единственным способом сделать обучение доступным по цене. Появляется промежуточный формат: программа под конкретный запрос по цене, которую человек готов заплатить.

