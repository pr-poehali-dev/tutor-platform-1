## Что изменилось технологически

Раньше выход был один: индивидуальные занятия с преподавателем. Это работало, но стоило в разы дороже готового курса, потому что каждый час требовал живого человека.

Сейчас изменилась стоимость **проектирования** программы. Разбор запроса, сопоставление с существующими материалами, сборка структуры под конкретную задачу — то, на что методист тратил дни, — делается за минуты.

Дорогим остаётся только то, что действительно требует человека: экспертиза, проверка работ, обратная связь. **Именно поэтому персональная программа перестала быть привилегией и стала доступной услугой.**

Это тот случай, когда технология не заменила специалиста, а убрала за него рутину.

## Как устроен раздел «Заказ курса»

