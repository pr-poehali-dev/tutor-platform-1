Чем подробнее описан запрос, тем точнее программа. Но порог входа намеренно низкий — одна строка, чтобы начать.

**Шаг 2. Система ищет ближайший курс.** Запрос сопоставляется с каталогом платформы — 88 программ. Находится тот курс, который ближе всего по смыслу.

