# Этап 1. Идея и гипотеза

Идея звучит так: «Открыть пекарню в новом жилом комплексе — там 4 тысячи квартир и ни одной нормальной пекарни».

В таком виде это не гипотеза, а надежда. Гипотезу нужно сформулировать проверяемо:

> Жители ЖК готовы покупать свежий хлеб и выпечку в шаговой доступности по цене на 30–40% выше сетевого супермаркета, потому что ценят качество и не хотят ехать.

Теперь понятно, что именно проверять: **готовность платить наценку**, а не «нужен ли людям хлеб».

Это ключевая развилка. Первая формулировка непроверяема и всегда даёт ответ «да». Вторая может дать «нет» — и это её главное достоинство.

# Этап 2. Проверка спроса до вложений

Самая пропускаемая стадия. Обычно её заменяют на «я и сам вижу, что людям надо».

Что делаем вместо этого — три действия, ни одно не требует вложений:

**Считаем реальный трафик.** Не число квартир, а количество людей, проходящих мимо точки. Замер в будни утром (7:30–9:30) и вечером (18:00–20:30), плюс выходной день. Допустим, получили: в будни около 900 человек в день мимо витрины, в выходной — 1400.

**Считаем конкурентов честно.** «Ни одной пекарни» обычно означает «ни одной вывески со словом пекарня». Но хлеб продают два сетевых супермаркета в 700 метрах, пункт выдачи с готовой едой и три точки на маркетплейсах с доставкой. Это конкуренты.

**Проверяем готовность платить.** Не опросом «купили бы вы?», на который все отвечают да. Предзаказ: сделать простую страницу и собрать заявки на пробную субботнюю выпечку с оплатой. Двадцать оплаченных заказов говорят больше, чем двести положительных ответов.

Допустим, из 60 человек, оставивших контакты, оплатили 19. **Конверсия в оплату 32% — гипотеза жива.**

# Этап 3. Юнит-экономика

Здесь проект впервые встречается с реальностью. Считаем не «выручку», а сколько зарабатываем на одном чеке.

**Средний чек:** 480 ₽ (хлеб + выпечка).

**Себестоимость продукта в чеке:** 168 ₽ — мука, масло, начинки, упаковка. Это 35% от чека.

**Валовая прибыль с чека:** 312 ₽.

Теперь постоянные расходы в месяц:

| Статья | Сумма |
|---|---|
| Аренда 45 м² | 135 000 ₽ |
| Зарплаты (2 пекаря, 2 продавца) | 320 000 ₽ |
| Налоги и взносы с ФОТ | 96 000 ₽ |
| Коммунальные и вывоз | 28 000 ₽ |
| Обслуживание оборудования | 15 000 ₽ |
| Маркетинг | 30 000 ₽ |
| Прочее и резерв | 26 000 ₽ |
| **Итого** | **650 000 ₽** |

**Точка безубыточности:** 650 000 / 312 = **2 084 чека в месяц**, то есть около **69 чеков в день**.

Возвращаемся к трафику: 900 человек в будни мимо витрины. 69 чеков — это конверсия 7,7% от проходящего потока. Для пекарни на первой линии с запахом свежего хлеба — достижимо, но не гарантированно.

**Вывод этапа: модель сходится, но запаса нет.** Это ещё не проект, это пока натянутая надежда.

# Этап 4. Стресс-тест — момент, где проект чуть не умер

Здесь начинается самое полезное.

Вопрос: что будет, если продажи окажутся на 40% ниже плана? Не из пессимизма, а потому что первые месяцы почти всегда идут ниже прогноза.

При 69 чеках в день закладывали выручку 993 600 ₽ в месяц. Минус 40% — это **41 чек в день**.

Валовая прибыль: 41 × 30 × 312 = 383 760 ₽.
Постоянные расходы: 650 000 ₽.
**Убыток: −266 240 ₽ в месяц.**

При таком раскладе стартового капитала в 2,5 млн хватит на девять месяцев убытков — и всё.

**Проект в исходном виде стресс-тест не проходит.**

Вот здесь обычно случается развилка. Первый путь — убедить себя, что 40% падения не будет. Второй — перестроить модель так, чтобы она выдержала.

Идём вторым.

# Этап 5. Перестройка модели

Что меняем, не отказываясь от идеи:

**Уменьшаем площадь.** 45 м² под полный цикл — избыточно на старте. Берём 28 м², аренда падает до 84 000 ₽. **Экономия 51 000 ₽.**

**Меняем структуру смены.** Вместо двух пекарей и двух продавцов — один пекарь и два продавца, один из которых обучен на подхвате выпечки. ФОТ падает до 210 000 ₽, взносы до 63 000 ₽. **Экономия 143 000 ₽.**

**Добавляем второй канал выручки.** Утренние корпоративные поставки в бизнес-центр в 1,2 км: предзаказ накануне, доставка к 8:00. Это не требует новых площадей и загружает печь в непиковое время. Осторожная оценка: +180 000 ₽ выручки в месяц при той же марже.

Новые постоянные расходы: **456 000 ₽.**

**Новая точка безубыточности:** 456 000 / 312 = 1 462 чека, около **49 чеков в день**. Минус вклад корпоративного канала — розничная часть должна давать около **30 чеков в день**.

**Повторный стресс-тест:** падение на 40% от плановых 69 чеков даёт 41 чек — выше новой точки безубыточности в 49? Нет, ниже. Но с учётом корпоративного канала, который менее волатилен, суммарно модель выходит в ноль.

**Теперь проект стресс-тест проходит.** Не с блеском — впритык. И это честный результат.

# Этап 6. Вопрос кредита

Соблазн: взять 1,5 млн на оборудование, ведь модель теперь сходится.

Считаем. При ставке около 22% годовых на три года платёж составит примерно 57 000 ₽ в месяц.

Это добавляется к постоянным расходам: 456 000 + 57 000 = 513 000 ₽. Точка безубыточности растёт до 55 чеков в день.

**Правило, которое стоит применить здесь:** кредит допустим, если бизнес обслуживает платёж в пессимистичном сценарии, а не в оптимистичном. В нашем случае в пессимистичном сценарии — не обслуживает.

**Решение: стартуем без кредита.** Оборудование — частично б/у, частично в аренду с правом выкупа. Дольше, менее красиво, но проект не умирает от первого плохого квартала.

# Этап 7. План первых 90 дней

Абстрактный «план развития» бесполезен. Нужны проверяемые точки.

**Дни 1–30.** Запуск розницы. Цель: выйти на 35 чеков в день к концу месяца. Контрольная цифра — конверсия из проходящего потока не ниже 4%.

**Дни 31–60.** Запуск корпоративного канала. Цель: три постоянных клиента-организации. Розница: 45 чеков в день.

**Дни 61–90.** Выход на операционный ноль. Цель: 50 чеков в день плюс корпоративные поставки. Здесь принимается решение о втором пекаре.

**Точка «стоп».** Если к концу 90 дней розница ниже 35 чеков в день — модель не подтвердилась, и нужно менять концепцию или закрываться, пока не потрачен весь резерв.

Заранее назначенная точка выхода — самое недооценённое решение в бизнес-планировании. Без неё предприниматель досыпает деньги в неработающую модель, пока они не кончатся.

# Этап 8. Презентация: девять слайдов

Теперь собираем всё в документ для партнёра, инвестора или банка. Структура, которая работает:

**Слайд 1. Проблема.** В ЖК на 4 000 квартир нет пекарни в шаговой доступности; ближайшая точка со свежим хлебом — 700 м.

**Слайд 2. Решение.** Пекарня полного цикла 28 м² на первой линии + утренние корпоративные поставки.

**Слайд 3. Подтверждение спроса.** 19 оплаченных предзаказов из 60 контактов, конверсия 32%. Замеры трафика: 900 человек в будни, 1 400 в выходной.

**Слайд 4. Экономика одного чека.** Чек 480 ₽, себестоимость 168 ₽, валовая прибыль 312 ₽.

**Слайд 5. Точка безубыточности.** 49 чеков в день при постоянных расходах 456 000 ₽.

**Слайд 6. Стресс-тест.** Что происходит при падении продаж на 40% и почему модель это выдерживает.

**Слайд 7. Вложения и их назначение.** Сумма, структура, почему без кредита.

**Слайд 8. План 90 дней с контрольными точками.** Включая точку «стоп».

**Слайд 9. Риски и что с ними делаем.** Три главных, честно, с ответом на каждый.

**Важное про порядок.** Слайд со стресс-тестом ставится до слайда с вложениями. Причина простая: человек, у которого просят деньги, в первую очередь думает не «сколько заработаю», а «сколько потеряю». Проект, который сам показал свою слабую точку и ответ на неё, вызывает больше доверия, чем проект с одними победными цифрами.

# Что показал этот разбор

Три вывода, которые важнее самих расчётов.

**Первый: проект прошёл проверку не с первого раза.** Исходная модель стресс-тест провалила. Если бы предприниматель пропустил четвёртый этап, он узнал бы это через семь месяцев — за свои деньги.

**Второй: спасли проект не продажи, а сокращение постоянных расходов.** Снижение фикса с 650 до 456 тысяч изменило картину сильнее, чем любой рост выручки. При дорогих деньгах это общее правило: постоянные расходы опаснее, чем недостаток амбиций.

**Третий: отказ от кредита сделал проект жизнеспособным.** Красивый вариант с новым оборудованием выглядел лучше — и убивал бизнес при первом плохом квартале.

Бизнес-план нужен не для того, чтобы обосновать идею. Он нужен, чтобы найти место, где она ломается, — пока это ничего не стоит.

