## Почему не «готовая работа»

Рынок студенческих работ меняется на глазах. Студенты массово пользуются нейросетями, а вузы отвечают проверкой: системы антиплагиата научились находить признаки сгенерированного текста, а в части вузов студента просят пояснить, для каких задач он использовал ИИ.

Получается простая арифметика. Работа, написанная не вами, рискует не пройти проверку. А если пройдёт, на защите всё равно спросят по её содержанию. Поэтому наш научрук устроен иначе: он делает то же, что хороший научный руководитель, — задаёт направление, проверяет и задаёт неудобные вопросы. Текст пишете вы.

