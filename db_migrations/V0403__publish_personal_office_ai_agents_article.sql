## От личного офиса — к заказам

Теперь самое практичное. Личный офис ценен не только тем, что закрывает ваши дела. Он превращается в услугу.

Логика простая: если у вас есть штат из восьми специальностей и вы умеете им управлять — вы можете обслуживать не только себя.

**Рынок «личного помощника» существует давно.** Разбор почты и календаря, подготовка документов, поиск подрядчиков, сбор информации, оформление отчётности, бронирования, контроль сроков. Раньше это была работа человека за 40–80 тысяч в месяц, и позволить её могли немногие.

Сейчас один оператор с личным офисом ведёт нескольких клиентов одновременно. Не потому что работает по 16 часов — потому что рутину закрывают агенты, а человек остаётся на связи, принимает решения и отвечает за качество.

Задачи делятся на два типа, и оба оплачиваются.

**Бытовые.** Разобрать документы и оформить справки. Подобрать и сравнить подрядчиков на ремонт. Собрать маршрут поездки со сроками и бюджетом. Проверить договор перед подписанием. Вести семейный бюджет и напоминать о платежах. Оформить возврат или претензию. Это дёшево в исполнении и стабильно востребовано.

**Профессиональные.** Собрать коммерческое предложение. Написать вакансию и отсеять отклики. Настроить контент-план на месяц. Посчитать юнит-экономику перед запуском. Подготовить отчёт и дашборд. Разобрать код или ТЗ. Здесь чек выше в разы, а конкуренция ниже — большинство «помощников» на бытовых задачах и остаются.

Отдельный сегмент, который сейчас пустует: **малый бизнес, которому не нужен штат**. Салону, автосервису или небольшому производству не нужен маркетолог на ставку. Им нужно, чтобы кто-то раз в неделю закрывал маркетинговые задачи. Это ровно ваш формат.

## Честная экономика этой истории

Раз уж мы в жанре разбора, посчитаем без розовых очков.

Средний чек на сопровождение одного клиента в формате «личный помощник с ИИ» на рынке сейчас — от 15 до 40 тысяч рублей в месяц, в зависимости от того, бытовые задачи или профессиональные. Оператор в одиночку тянет 3–5 клиентов, дальше падает качество.

Считаем: 4 клиента по 25 тысяч — это 100 тысяч в месяц при полной загрузке. Расходы: подписки на инструменты — несколько тысяч.

Теперь честные оговорки, без которых цифра выше — вранье.

**Первое: полная загрузка приходит не сразу.** Первый клиент — самое трудное, и это не про инструменты, а про доверие. Реалистично: 2–4 месяца до устойчивого потока.

**Второе: агент не отвечает за результат — отвечаете вы.** Он выдаст правдоподобный текст, даже когда ошибается. Проверка фактов, цифр и юридических формулировок — на человеке, и это не формальность, а суть профессии.

**Третье: продаёте вы не «доступ к нейросети».** Клиент может открыть чат сам. Он платит за то, что вы знаете, какую задачу кому поставить, как проверить и как довести до готового результата. Ценность — в постановке и контроле, а не в доступе.

**Четвёртое: порог входа растёт.** Сейчас ниша полупустая, через год-два в ней будет тесно. Побеждать начнут те, у кого есть специализация — не «помощник вообще», а «помощник для стоматологических клиник» или «операционный помощник для маркетинговых агентств».

