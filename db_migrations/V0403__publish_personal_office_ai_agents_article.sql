- **Приложение** умеет ровно то, что в него заложили. Хотите другое — ждите обновления или ищите другое приложение.
- **Агент** умеет то, что вы ему объяснили. Хотите другое — объясняете иначе. Сегодня он аналитик, завтра — тот же аналитик, но помнящий специфику вашей отрасли.

