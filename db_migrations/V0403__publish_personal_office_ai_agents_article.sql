## Почему это не «ещё один чат с нейросетью»

Резонное возражение: чем это отличается от того, чтобы просто написать запрос в любую нейросеть?

Тремя вещами, и они принципиальны.

**Первое — роль вместо универсальности.** У каждого агента своя инструкция, тон и способ мышления. Продажник не отвечает как копирайтер. Аналитик не выдаёт вдохновляющих текстов. Универсальный ассистент всегда усреднён, ролевой — специфичен.

**Второе — маршрутизация.** Личный офис — это не список чатов, а система, которая понимает, кому задача. В «Оркестраторе» это работает буквально: вы описываете задачу, а система сама подбирает подходящего специалиста по смыслу — упомянули «воронку» и «трафик», задача уходит маркетологу, а не копирайтеру.

**Третье — распределение работы.** Самое интересное. [Планировщик ресурсов](/orchestrator) берёт список задач проекта и честно раскладывает их на три корзины: **что делать самому, что отдать ИИ, а под что действительно нужен живой человек**. Для третьей корзины сразу собирает вакансию — профиль, бюджет, вопросы на собеседование.

Вот это уже не чат. Это операционный слой между вами и работой.

