## Чему тут учиться

Навык называется скучно — **постановка задачи**. Но именно он отделяет тех, у кого агенты работают, от тех, у кого «нейросеть выдаёт ерунду».

Ерунду она выдаёт ровно тогда, когда не сказано: какой результат нужен, в каком формате, для кого, с какими ограничениями и по какому критерию считать сделанным. Это, между прочим, тот же навык, который отличает хорошего руководителя от плохого. Просто раньше его тренировали на людях, а теперь можно на агентах — быстрее и без испорченных отношений.

Что стоит освоить по порядку:

- **[Нейросети для работы](/courses/ai)** — база: как формулировать, чтобы получать результат, а не текст «про». Есть бесплатный первый урок.
- **[Промпт-инженер](/courses/prompteng)** — если хотите продавать этот навык отдельно.
- **[Заработок на нейросетях](/courses/neuroincome)** — про то, как превращать это в заказы, а не в хобби.
- **[Инструменты руководителя](/instrumenty-rukovoditelya)** — бесплатно, 4 мини-курса по 30 минут. Здесь как раз про постановку задач и критерии «готово» — на агентов ложится один в один.

Начать дешевле всего с [бесплатного мини-курса](/mini-course): один навык за вечер, без оплаты. Самый быстрый способ понять, интересно вам это или нет.

## Что будет дальше

Прогноз без футурологии, просто по логике происходящего.

**Софт продолжит дробиться на роли.** Монолитные приложения «на все случаи» проиграют наборам агентов, которые собираются под конкретного человека. Мы это уже видим: интерфейс всё чаще заменяется диалогом.

**Появится профессия оператора агентов.** Она уже появляется, просто называется по-разному: «ИИ-ассистент», «оператор», «помощник с нейросетями». Суть одна — человек, который управляет цифровым штатом в чьих-то интересах.

**Ценность сместится к постановке и проверке.** Исполнение дешевеет стремительно. Дорожает умение понять, что именно нужно сделать, и отличить хороший результат от правдоподобного.

**Личный офис станет нормой.** Как когда-то персональный компьютер: сначала диковинка для энтузиастов, потом инструмент профессионалов, потом просто то, что есть у всех.

