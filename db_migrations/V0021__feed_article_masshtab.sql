## Восемь рубрик: от макроэкономики до юнит-экономики

В издании пять аналитических рубрик и три практических. У каждой свой формат и периодичность, поэтому читатель заранее знает, что и когда получит.

**Аналитика:**

- **Индикаторы рынка** — раз в месяц: ставка, курс, инфляция, отрасли. Один-два экрана, графики и 3–5 выводов. Пример — октябрьский выпуск: ставка 14% сохраняется надолго, рубль за месяц укрепился на 4–6%, инфляция 7,1%. И отдельно: что это значит для бюджета компании на следующий год.
- **Карта трендов** — раз в квартал: 5–7 трендов на горизонте 12–24 месяцев по схеме «тренд → драйвер → риск → кто уже внедрил».
- **Разбор** — каждую неделю: сделки, запуски продуктов, выходы на новые рынки. Разбор строится на цифрах отчётности, а не на пресс-релизе: выручка, маржа, срок окупаемости и что пошло не так.
- **Экономика проекта** — раз в две недели: юнит-экономика на реальных примерах из маркетплейсов, сервисов и офлайн-розницы, со сценариями «что если» и типичными ошибками.
- **Регуляторный дайджест** — раз в две недели: только те законы, налоги и требования, которые меняют доходы и расходы бизнеса. Схема: что меняется, с какой даты, кого касается, что сделать. Свежий пример — налоговые поправки на 2027–2029 годы: дивиденды, маркетплейсы, штрафы и что успеть до конца года.

**Практика:**

- **Люди и роли** — каждую неделю: интервью с руководителями. Издание интересуют не биографии, а принятые решения. Каждая история сопровождается карточкой компании с данными ФНС.
- **Инструменты** — раз в две недели: сервисы учёта, аналитики и продаж через стоимость владения, сложность внедрения и интеграции. Формат — сравнительная таблица и три вывода.
- **Финансы для нефинансистов** — раз в две недели: EBITDA, NPV, ковенанты, амортизация простым языком, на примерах малого и среднего бизнеса.

