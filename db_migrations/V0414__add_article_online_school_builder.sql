Это не замена преподавателю. Это фильтр для потока однотипных вопросов между занятиями — тех самых «а можно ещё раз про третий шаг», которые съедают вечера.

**Деньги.** Приём оплат, чеки по 54-ФЗ, договор оферты. В кабинете видно выручку, комиссию платформы, ваш доход, выплаченное и остаток. Заявку на выплату вы оформляете сами.

