## Проблема, которую все обходят стороной

У преподавателя есть знания и есть ученики. Между ними стоит стена, о которую бьются тысячи людей: **упаковка**.

Чтобы продавать курс, нужно написать программу. Это методическая работа: разбить тему на модули, каждый модуль — на уроки, к каждому уроку придумать задание и проверку. Курс на 12 уроков — это неделя-полторы вечеров. Всё это время человек не зарабатывает, а готовится.

Потом выясняется, что программы мало. Нужен текст объявления, нужна цена, нужна страница, куда вести людей, нужен способ принять деньги и не нарушить 54-ФЗ. Репетитор, который отлично объясняет производные, внезапно должен стать маркетологом, дизайнером и бухгалтером.

