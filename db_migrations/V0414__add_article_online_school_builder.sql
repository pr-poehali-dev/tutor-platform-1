## Экономика: почему 8%

Мы сознательно выбрали модель без абонплаты.

Абонплата — это налог на надежду. Платформа получает деньги независимо от того, продали вы хоть что-то. У площадки пропадает мотивация помогать вам зарабатывать: выручка уже поступила.

Комиссия с продаж устроена наоборот. Мы зарабатываем, только когда зарабатываете вы. Если у вас нет продаж — вы нам ничего не должны, а мы теряем вместе с вами. Это неудобная для нас модель, зато честная.

**Конкретно: 8% от суммы продажи.** Конструктор курсов бесплатный, вход бесплатный, скрытых платежей нет.

## Чего мы не обещаем

Здесь обычно идёт блок про «тысячи довольных авторов». У нас его не будет, и вот почему.

Направление молодое. Кабинет школы мы открываем по приглашению — не потому что набиваем цену, а потому что хотим довести первых авторов до реальных продаж руками, а не бросить их в пустой интерфейс. Когда процесс отлажен, регистрация станет открытой.

Мы не обещаем, что курс продаст себя сам. Инструмент снимает методическую и техническую работу, но искать первых учеников всё равно придётся вам — поэтому конструктор и отдаёт каналы продвижения вместе с программой.

Мы не обещаем, что ИИ заменит вашу экспертизу. Он собирает каркас. Мясо на этот каркас нарастает только из вашего опыта: живых примеров, разбора типичных ошибок, историй учеников. Курс без этого будет средним — как и любой курс, собранный по шаблону.

