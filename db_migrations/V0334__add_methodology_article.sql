## Принцип первый: курс проектируется от результата, а не от темы

Стандартный путь создания курса выглядит так: берём тему, раскладываем на подтемы, наполняем содержанием.

Мы идём от обратного. Первый вопрос при проектировании — не «о чём курс», а **«что человек сможет делать после него, чего не мог до»**.

Разница видна на примере. Тема «делегирование» может развернуться в десять часов теории: история подхода, классификации, стили руководства. Всё это правда и всё это интересно.

Но результат формулируется иначе: «руководитель назначает по каждой задаче одного владельца и фиксирует это письмом». Из десяти часов остаётся тридцать минут — но эти тридцать минут меняют поведение, а десять часов меняли только эрудицию.

Отсюда наше правило: **если результат курса нельзя проверить, курс спроектирован неправильно**. «Понимать важность планирования» — не результат. «Составить план на 90 дней по шаблону» — результат.

## Принцип второй: каждый курс заканчивается артефактом

Это следствие первого принципа, но заслуживает отдельного пункта, потому что здесь мы расходимся с большинством.

**Артефакт — это то, что человек уносит с собой в материальном виде.** Заполненная матрица ответственности. Готовый сценарий разговора. Профиль должности. Расчёт юнит-экономики со своими цифрами.

Не конспект, не сертификат, не «новое понимание». Документ, который завтра лежит на рабочем столе и применяется.

Почему это важно. Знание без артефакта живёт около недели: человек прошёл курс, вдохновился, вернулся в операционку и через семь дней помнит общее ощущение, но не помнит, что конкретно делать.

Артефакт решает эту проблему механически. Он не требует запоминания — он требует применения.

Поэтому в наших курсах для руководителей человек не «изучает матрицу ответственности», а заполняет её по своему реальному процессу прямо внутри урока. К концу курса у него на руках не знание о матрице, а его собственная матрица.

## Принцип третий: урок — семь минут, и это не про клиповое мышление

Наши уроки в мини-курсах идут 7–9 минут. Нам регулярно говорят, что это подстройка под падающую концентрацию.

Это не так. Причина другая, и она про взрослых учеников.

**Взрослый человек учится в промежутках.** У него нет свободного вечера — у него есть двадцать минут между встречами, дорога и время после того, как уложил детей. Урок на сорок минут в такой график не помещается, и человек откладывает его «на потом, когда будет время». Потом не наступает.

Урок на семь минут помещается везде. И главное — он завершается. Человек не бросает на середине, а доходит до конца и получает ощущение продвижения, которое возвращает его к следующему уроку.

Второй аргумент — про плотность. Когда на тему дано сорок минут, туда неизбежно попадает вода: примеры для примеров, история вопроса, повторы. Когда дано семь минут, остаётся только то, без чего нельзя.

Ограничение работает как фильтр качества. Мы сами обнаружили, что сокращение урока вдвое почти никогда не приводит к потере смысла — только к потере лишнего.

## Принцип четвёртый: сначала проблема, потом инструмент

Порядок подачи внутри урока для нас важнее содержания.

Неработающая последовательность: вот инструмент → вот как он применяется → вот зачем он нужен.

Работающая: вот ситуация, в которой вы были → вот почему она возникает → вот что с этим делать.

Причина в том, как устроено внимание взрослого. Он не готов вкладываться в инструмент, пока не признал проблему своей. Пока проблема не узнана, любое объяснение воспринимается как теория.

Поэтому наши курсы для руководителей начинаются не с определений, а с фраз, которые человек слышал в своём кабинете: «Я думал, это делает Петров». «Сделали не то, что просили». «Наняли по ощущению — расстались через месяц».

Узнавание — это не приём для вовлечения. Это условие, при котором дальнейшее объяснение вообще усваивается.

## Принцип пятый: мы проверяем понимание, а не запоминание

Тест с вариантами ответа проверяет, помнит ли человек формулировку. Это самый дешёвый в производстве вид контроля и самый бесполезный.

Мы строим проверку иначе — через применение к своей ситуации.

Вместо «какие бывают роли в матрице ответственности» — «возьмите задачу, которая у вас сейчас буксует, и назовите владельца одной фамилией».

Вместо «назовите этапы разговора об ошибке» — «сформулируйте факт по вашему случаю так, чтобы в нём не было оценки».

Разница в том, что первый тип вопросов можно пройти, не поняв ничего. Второй — нельзя.

Побочный эффект: такая проверка сразу даёт человеку кусок его артефакта. Он не тратит время на тест, он делает работу.

## От чего мы отказались

Честный разбор методологии должен включать и это.

**Отказались от геймификации ради вовлечения.** В детском разделе награды за задания работают — там это часть игры. Во взрослых курсах баллы и рейтинги смещают фокус: человек начинает проходить курс ради прогресс-бара, а не ради результата. Мы убрали.

**Отказались от «интересного» контента.** Была версия курсов с историческими справками, любопытными исследованиями, красивыми примерами из мировых компаний. Курсы стали приятнее и бесполезнее: человек получал удовольствие и ничего не менял в работе. Оставили только то, что применяется.

**Отказались от длинных программ по умолчанию.** Не потому, что длинное — плохо. А потому, что длинную программу человек чаще всего не заканчивает, и результат нулевой при полной оплате. Лучше короткий курс, пройденный до конца, чем большой, брошенный на четверти.

