## Что делать, если тест не убедил

Бывает и так: результат посмотрел, а внутри ничего не откликнулось. Это нормально, и это не провал.

**Тест — не приговор, а список гипотез.** Он не говорит «ты обязан стать инженером». Он говорит: «вот направления, где твои особенности будут преимуществом, а не борьбой с собой». Дальше гипотезы нужно проверять.

Три способа проверить быстро:

**Посмотрите на день, а не на название.** Найдите описание обычного рабочего дня в профессии. Не миссию и не зарплату — именно рутину. Если рутина вызывает отвращение, красивое название не спасёт.

**Попробуйте руками.** У нас открыты бесплатные мини-курсы — один навык за вечер. Это самый дешёвый способ понять, ваше это или нет: не пять лет университета, а один вечер. [Посмотреть мини-курсы](/mini-course).

**Поговорите с тем, кто уже работает.** Один честный разговор с практикующим специалистом даёт больше, чем месяц раздумий. Спросите не «нравится ли вам работа», а «что бесит больше всего».

## Главное, что нужно понять

**Выбор профессии в 17 лет — это не выбор на всю жизнь.** Люди меняют направление в 25, в 30 и в 40. Мы учим взрослых новым профессиям каждый день и видим это постоянно.

Задача сейчас другая: не найти единственно правильный ответ, а **сделать первый осмысленный шаг вместо случайного**. Поступить туда, где вам будет интересно ближайшие несколько лет, и получить навыки, с которыми можно двигаться дальше.

