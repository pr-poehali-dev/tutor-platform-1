## Три ловушки, в которые попадают почти все

**Ловушка первая: ждать «призвания».**

В фильмах герой в один момент понимает своё предназначение — обычно под музыку. В жизни так не работает. Интерес к делу почти никогда не приходит до того, как ты им занялся. Он появляется в процессе: сначала ты пробуешь, потом начинает получаться, а уже потом становится по-настоящему интересно.

Поэтому вопрос «что я люблю?» в шестнадцать лет часто ставит в тупик. Правильнее спросить: **что мне даётся легче, чем другим, и что я готов делать даже когда скучно.**

**Ловушка вторая: выбирать по предмету, а не по делу.**

«Люблю биологию — пойду в медицину». Но биология в школе и работа врача — это очень разные вещи. В школе ты читаешь параграф и решаешь задачи. Врач разговаривает с испуганными людьми, принимает решения без полной информации и работает в ночные смены.

Предмет — это знания. Профессия — это то, чем ты занят восемь часов подряд. Смотреть надо на второе.

**Ловушка третья: слушать чужие страхи.**

«Художником денег не заработаешь», «программисты скоро не будут нужны», «иди на юриста, всегда пригодится». Обычно это говорят люди, которые сами в этих профессиях не работают. Их советы основаны не на данных, а на тревоге — иногда искренней и любящей, но всё равно тревоге.

Данные проверять можно. И нужно.

