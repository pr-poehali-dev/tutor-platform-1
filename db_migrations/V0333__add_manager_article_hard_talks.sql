# Часть первая. Разговор, который откладывают

## Что происходит, пока вы молчите

Руководитель заметил проблему в работе сотрудника. Решил не поднимать сейчас: настроение неподходящее, квартал горячий, человек и сам, наверное, понимает.

Проходит месяц. Проблема повторяется. Поднимать теперь неудобно — почему молчал в прошлый раз?

Проходит полгода. И вот здесь включается механизм, который стоит дороже всего.

**Проблема не стоит на месте — она накапливает эмоцию.** Каждый повтор добавляет раздражения. Когда разговор наконец случается, руководитель говорит уже не про конкретный случай, а про все шесть месяцев сразу. И звучит это не как обратная связь, а как приговор.

Сотрудник при этом слышит обвинение впервые. С его стороны картина такая: работал как работал, замечаний не было, и вдруг претензии за полгода и разговор про расставание.

Он не притворяется. **Он действительно не знал.**

Отсюда главное правило: обратная связь имеет срок годности. Разговор о конкретном случае работает, пока случай свежий — в пределах недели. Дальше он превращается в разговор о личности, а такой разговор не исправляет поведение, он рушит отношения.

## Пять шагов разговора, который работает

Структура нужна не для формальности. Она удерживает от главного соблазна — перейти на оценку человека.

**Шаг 1. Факт.** Что конкретно произошло. Без слов «всегда», «постоянно», «вечно». Не «ты вечно срываешь сроки», а «отчёт за март пришёл 12-го, срок был 5-е».

Проверка простая: факт — это то, что зафиксировала бы камера. «Опоздал на встречу» — факт. «Несерьёзно относишься» — оценка.

**Шаг 2. Последствие.** Что из этого вышло. Не «это плохо», а «клиент получил цифры позже и перенёс решение на следующий месяц».

Этот шаг чаще всего пропускают, а он критичен: без него человек не понимает масштаба и считает придиркой.

**Шаг 3. Пауза.** Дайте ответить. Здесь руководители ошибаются чаще всего — говорят весь монолог целиком, а потом спрашивают «что скажешь?».

Пауза нужна раньше. В половине случаев выясняется контекст, который меняет картину: были причины, о которых вы не знали.

**Шаг 4. Ожидание.** Что должно происходить дальше. Конкретно и проверяемо: не «будь внимательнее», а «если срок под угрозой — сообщаешь за два дня, а не в день сдачи».

**Шаг 5. Фиксация.** Короткое письмо после разговора: о чём договорились, что меняется, когда сверимся. Три строки.

Без пятого шага через месяц у вас будет две разные версии одного разговора.

## Формула, которая держит разговор в рамках

Если запомнить нечего больше, запомните три слова: **факт — последствие — ожидание**.

Пока вы внутри этой формулы, разговор остаётся про работу. Как только выходите за неё — начинается про личность, и результат становится непредсказуемым.

Тест перед разговором: сможете ли вы сказать то же самое человеку, к которому относитесь с уважением? Если формулировка меняется — значит, она была не про факт.

# Часть вторая. Найм «по ощущению»

## Половина неудачных наймов случается до собеседования

Типичная картина: вакансия горит, руководитель проводит десять собеседований, выбирает того, кто «зашёл больше всех», через месяц расстаётся.

Разбор обычно сводится к «не тот человек попался». Но причина возникла раньше — **ещё до первого собеседования**.

Не было профиля должности. То есть письменного ответа на вопрос: кого именно мы ищем и по каким признакам поймём, что нашли.

Без профиля происходит следующее: каждый интервьюер спрашивает своё, оценивает по своим критериям, и решение принимается по общему впечатлению. А общее впечатление — это в первую очередь коммуникабельность кандидата, а не его способность делать работу.

Так нанимают приятных людей вместо подходящих.

## Что входит в профиль должности

Профиль — это не описание вакансии для публикации. Это внутренний документ на одну страницу.

**Задачи первых трёх месяцев.** Не абстрактные обязанности, а конкретный результат: что человек должен сделать к концу испытательного срока.

**Обязательные навыки.** Те, без которых работа невозможна с первого дня. Их должно быть немного — три-четыре. Если список из пятнадцати пунктов, вы описываете не человека, а мечту.

**Навыки желательные.** Те, которым можно научить внутри. Разделение обязательных и желательных — половина ценности профиля: без него любой кандидат выглядит неполным.

**Признаки несовместимости.** Что делает работу невозможной независимо от опыта. Например: работа требует ежедневных звонков клиентам, а человек избегает телефонных разговоров.

**Как проверим.** Для каждого обязательного навыка — способ проверки на собеседовании.

## Тест на честность профиля

Профиль составлен правильно, если по нему двое разных интервьюеров придут к одинаковому выводу о кандидате.

Если выводы расходятся — профиль описывает не требования, а пожелания.

Второй тест: возьмите последнего сотрудника, который у вас не прижился. Прошёл бы он ваш профиль? Если да — профиль не ловит реальную причину неудачи и требует доработки.

## Вопросы про реальный опыт, а не про самооценку

Главная ошибка на собеседовании — вопросы, на которые невозможно ответить плохо.

«Вы стрессоустойчивы?» — все скажут да. «Умеете работать в команде?» — все скажут да. Эти вопросы не дают информации, они дают вежливые ответы.

Рабочая замена — вопросы про конкретный прошлый случай:

«Расскажите про последний раз, когда сорвался срок. Что произошло и что вы сделали?»

«Приведите пример, когда пришлось спорить с руководителем. Чем закончилось?»

«Какую задачу за последний год вы считаете неудачной? Почему?»

Разница принципиальная: первый тип вопросов проверяет, что человек о себе думает. Второй — что он реально делал. Придумать убедительный подробный пример на ходу почти невозможно, а вот сказать «да, я ответственный» может каждый.

## Три этапа отбора, которых хватает

Раздутая воронка — вторая частая ошибка. Пять этапов собеседований отсеивают не слабых, а тех, у кого есть выбор: сильные кандидаты уходят к работодателям, которые решают быстрее.

Достаточно трёх:

**Первый — соответствие профилю.** Короткий разговор на 20-30 минут: есть ли обязательные навыки, нет ли признаков несовместимости.

**Второй — проверка работой.** Небольшая задача, приближенная к реальной. Ключевое слово — небольшая: тестовое на восемь часов кандидаты не делают, они уходят.

**Третий — разговор с руководителем.** Про ожидания, а не про навыки: навыки проверены на предыдущих этапах.

## Что общего у двух ошибок

Обе выглядят как проявление человечности: не хочу расстраивать разговором, доверяю интуиции при найме.

Но обе на деле перекладывают риск на сотрудника. Человек, которому полгода не говорили о проблеме, лишён шанса её исправить. Человек, которого наняли без профиля, обречён не совпасть с невысказанными ожиданиями.

Ясность — это не жёсткость. Ясность — это форма уважения к человеку, с которым вы работаете.

