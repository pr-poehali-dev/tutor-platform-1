Это разные навыки. Первый нужен на экзамене. Второй — всю оставшуюся жизнь.

## Три вещи, которым больше не учат

**Отличать противоположность от противоречия.** «Белое или чёрное» — ложный выбор, между ними есть серое. «Чётное или нечётное» — настоящая альтернатива, третьего не дано. Путаница между этими случаями — основа манипуляции «либо ты с нами, либо против нас».

**Правильно строить отрицание.** Отрицание фразы «все лебеди белые» — не «все лебеди чёрные», а «существует хотя бы один нечёрный». Отсюда следует практическая вещь: чтобы опровергнуть общее утверждение, достаточно одного примера.

**Замечать утверждение следствия.** «Если был дождь, асфальт мокрый. Асфальт мокрый — значит был дождь». Звучит убедительно, но неверно: асфальт могли полить. На этой ошибке построена половина рекламы и изрядная часть новостей.

## Почему об этом заговорили снова

Летом 2026 года вопрос о возвращении логики в школьную программу обсуждали публично — с отсылкой к тому самому советскому опыту.

Аргумент простой: объём информации вырос, а инструмента для её проверки школьнику никто не дал. Отличить обоснованное утверждение от красиво поданного — навык, которому нигде специально не учат.

Вернут предмет или нет — вопрос открытый. Но ждать решения необязательно.

