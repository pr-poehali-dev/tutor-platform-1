## Как это было

Постановление о преподавании логики и психологии в средней школе вышло в 1946 году. С 1947-го предмет пошёл в старшие классы.

Логику вели отдельно от математики. Программа была небольшая, но цельная: формы мышления, законы логики, определение и деление понятий, силлогизм, доказательство и опровержение.

