## Что именно потерялось

Логика никуда не исчезла — она разошлась по другим предметам. И в этом вся проблема.

Таблицы истинности достались информатике. Доказательство от противного — геометрии. Круги Эйлера — математике, где их проходят за пару уроков в теме про множества.

