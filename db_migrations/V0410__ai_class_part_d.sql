## Куда идёт специализация: прогноз на 2-3 года

Теперь то, ради чего всё писалось. Пять тенденций, которые видны уже сейчас.

**Расслоение вместо гонки.** Гонка «чей флагман умнее» упирается в стену: каждый следующий шаг качества стоит непропорционально дороже. Рынок расслаивается — сверху несколько универсальных гигантов, снизу сотни узких моделей. Прибыль постепенно перетекает вниз, где дешевле и точнее.

**Оркестрация как норма.** Продукты перестают использовать одну модель. Появляется слой-маршрутизатор: простой запрос уходит дешёвой модели, сложный — рассуждающей, картинка — мультимодальной, чувствительные данные — локальной. Пользователь не знает и не должен знать, кто именно ответил.

**Отраслевые модели вытеснят универсальные в профессиях.** Медицина, право, инженерия, бухгалтерия — везде, где ошибка дорога, а терминология специфична, победит модель, обученная на отраслевых данных и прошедшая профильную проверку. Врач не станет пользоваться моделью, которая одинаково уверенно рассуждает о диагнозе и о рецепте борща.

**Локальные модели вырастут из требований, а не из технологий.** Драйвер здесь не мощность железа, а регулирование и здравый смысл: персональные данные, коммерческая тайна, суверенитет. Российских компаний это касается вдвойне — работа с отечественными моделями в собственном контуре становится не идеологией, а операционной необходимостью.

**Ценность сместится к постановке задачи.** Чем лучше модели, тем менее ценно умение ими пользоваться, и тем более ценно умение понять, что нужно сделать. Формулировка требований, критерии готовности, проверка результата — вот навык, который дорожает. Он же, кстати, отличает хорошего руководителя от плохого — просто теперь его тренируют ещё и на моделях.

