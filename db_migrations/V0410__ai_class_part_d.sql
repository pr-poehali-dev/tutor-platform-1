Порядок вопросов важен: каждый следующий отсекает варианты.

**Требует ли задача многошаговых рассуждений?** Если да — рассуждающий режим, без вариантов. Если нет — быстрая модель, не переплачивайте.

**Данные чувствительные?** Персональные, медицинские, финансовые, коммерческая тайна — сразу отсекайте всё, что уходит в чужое облако. Этот вопрос важнее вопроса о качестве.

**Задача повторяется каждый день или разовая?** Для повторяющихся считайте стоимость запроса и берите минимально достаточную модель. Для разовых берите лучшую — экономия на одном запросе бессмысленна.

**Нужен ли не-текст?** Картинки, документы, аудио на входе — нужна мультимодальность. Изображения и видео на выходе — нужен другой класс инструментов.

**Модель должна действовать сама?** Ходить в сеть, запускать код, работать с файлами — это агентные сценарии, и к ним нужен отдельный контроль: что она вправе делать, а что нет.

**Кто проверяет результат?** Если ответа нет — вернитесь к первому вопросу. Внедрение без проверяющего работает ровно до первой дорогой ошибки.
:::

