## Возьмём обычную мастерскую

Ремонт техники. Средний чек 2 500 ₽, себестоимость заказа 900 ₽ — запчасти и расходники. Постоянные расходы 180 000 ₽ в месяц: аренда, зарплата мастера, реклама, налоги.

Сейчас мастерская делает 120 заказов в месяц.

**Что получается:**

- Маржа с заказа: 2 500 − 900 = **1 600 ₽**
- Оборот: 300 000 ₽
- Прибыль: 120 × 1 600 − 180 000 = **12 000 ₽**

Оборот триста тысяч, а в кармане двенадцать. Знакомая ситуация.

**Точка безубыточности — 113 заказов.** То есть 113 заказов из 120 мастерская работает бесплатно, только чтобы закрыть расходы. Прибыль приносят последние семь.

