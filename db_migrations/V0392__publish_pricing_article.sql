## Правило, которое стоит запомнить

**Цена — единственный рычаг, который работает без затрат.**

Снизить себестоимость на 10% — нужны переговоры с поставщиками, объёмы, время. Привлечь на 20% больше клиентов — нужен бюджет на рекламу. Поднять цену на 10% — нужно решение, принятое за один вечер.

При этом порядок влияния такой: изменение цены бьёт по прибыли в несколько раз сильнее, чем такое же по величине изменение расходов или потока клиентов. Потому что цена действует на каждую сделку сразу и не тянет за собой новых затрат.

## Как применить это завтра

**Шаг 1. Посчитайте маржу с одной продажи.** Цена минус то, что вы тратите именно на эту продажу: товар, материалы, комиссия, доставка. Аренда и зарплаты сюда не входят — это постоянные расходы.

**Шаг 2. Найдите точку безубыточности.** Постоянные расходы разделите на маржу. Получится число продаж, до которого вы работаете в ноль. Многих это отрезвляет сильнее любой книги по бизнесу.

**Шаг 3. Посчитайте запас прочности.** Прибавьте к цене 10% и посмотрите, сколько клиентов вы можете потерять без потери денег. Обычно этот запас гораздо больше, чем кажется.

**Шаг 4. Поднимите цену на новых клиентах.** Не обязательно объявлять повышение всем сразу. Начните с новых обращений и смотрите на конверсию две недели. Если она не просела — вы просто оставляли деньги на столе.

