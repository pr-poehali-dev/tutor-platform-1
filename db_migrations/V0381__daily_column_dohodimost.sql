## Что происходит на третьей неделе

Первая неделя работает на энтузиазме покупки. Человек заплатил, он воодушевлён, у него включён режим «новая жизнь с понедельника». Уроки идут легко, потому что в начале любого курса — вводная часть, где всё понятно.

Вторая неделя — инерция. Запал слабеет, но привычка ещё держит.

А на третьей заканчивается и то и другое. И одновременно происходят три вещи.

**Материал перестаёт быть лёгким.** Вводная часть кончилась, начинается то, ради чего курс покупали. Требуется усилие, а не просто просмотр.

**Результата ещё не видно.** Человек вложил три недели, а похвастаться нечем: диплома нет, зарплата не выросла, портфолио пустое. Мозг делает честный вывод — вложения не окупаются.

**Появляется первый пропуск.** Заболел ребёнок, аврал на работе, поехали к родителям. Пропустил один урок — образовался долг. Долг вызывает вину. Вина заставляет избегать. Через неделю догонять уже стыдно, проще не открывать вкладку вообще.

Вот эта цепочка — пропуск, вина, избегание — и убивает большинство учеников. Не сложность материала. Не качество записи. Не преподаватель.

## Почему школы этого не видят

Потому что смотрят не туда.

Стандартная воронка школы заканчивается на оплате. Дальше метрики становятся размытыми: «удовлетворённость», «NPS», «отзывы». А отзывы оставляют те, кто дошёл — то есть меньшинство. Большинство просто молча исчезает, и его никто не опрашивает.

В итоге школа видит хорошие отзывы выживших и делает вывод, что с продуктом всё в порядке. А продукт теряет 85% клиентов.

Вторая причина — так было выгодно. Пока привлечение стоило дёшево, отвал не был проблемой: ушёл один, купили ещё троих. Реклама за три года подорожала кратно, и модель перестала сходиться. Теперь каждый потерянный ученик — это оплаченный и невозвращённый рубль.

## Что реально удерживает

Разберу приёмы, которые работают, по убыванию эффекта.

**Первый результат до третьей недели.** Не в конце курса, а на старте. Что-то, что человек может показать: собранный лендинг, решённый вариант ЕГЭ, готовый расчёт. Ощущение «у меня получается» — самое сильное топливо. Перестройте программу так, чтобы маленькая победа случилась на первой неделе, а не на двенадцатой.

**Разрешение отставать.** Звучит контринтуитивно, но именно жёсткий график создаёт вину. Дайте механику догона: «пропустил — вот сокращённая версия на 15 минут, ты в строю». Убираете вину — убираете избегание.

**Живой контакт в момент провала.** Не рассылка «мы скучаем» на десятый день, а сообщение на второй день молчания. Причём личное и без упрёка: «Застряли на модуле про интегралы? Это нормально, там правда тяжело». Отвал ловится в первые 48 часов тишины, потом человек уже ушёл.

**Видимый прогресс.** Полоска «пройдено 40%» работает лучше, чем кажется. Человеку тяжело бросить то, во что он уже вложился, — но только если он эти вложения видит.

**Обязательство перед людьми.** Групповой чат, где спрашивают «ну как, дошёл?», удерживает сильнее, чем любая автоматическая рассылка. Социальное обязательство сильнее личного.

## Где здесь ИИ — и где его переоценивают

ИИ снял главное ограничение: раньше персональное сопровождение упиралось в количество живых кураторов. Один куратор тянет 30 человек, дальше нужно нанимать. Теперь проверка задания с разбором ошибки и объяснением масштабируется почти бесплатно.

Это меняет экономику. Индивидуальное внимание перестало быть привилегией дорогих программ.

Но есть честная оговорка. ИИ хорошо отвечает, когда его спросили. Он плохо справляется с тем, чтобы не дать бросить — а именно на этом и сыплется доходимость. Ученик, который перестал заходить, ничего не спрашивает. Его нужно догнать первым.

Поэтому связка выглядит так: ИИ берёт на себя объяснения, проверку и разбор ошибок круглосуточно, а система — отслеживание тишины и своевременный толчок. Заменить преподавателя целиком пока не получается, и обещать это нечестно.

Занятно, что большинство школ применяют ИИ ровно наоборот: чтобы дешевле производить контент. Курсов стало больше, доходимость не изменилась. Инструмент есть, а проблему им не решают.

## Что это значит для вашей экономики

Простая арифметика, которая объясняет, почему это важнее любой рекламы.

Допустим, привлечение ученика стоит вам 3000 рублей, курс стоит 10 000. При доходимости 10% из ста учеников курс закончат десять. Эти десять могут купить второй курс и привести знакомых. Девяносто — нет.

Теперь поднимите доходимость до 30%. Расходы на привлечение те же. Но возвращаться и рекомендовать будут тридцать человек вместо десяти. Ваша выручка с той же рекламы выросла втрое — без единого дополнительного рубля в маркетинг.

Отсюда главный вывод: **при высокой доходимости вы можете позволить себе платить за привлечение больше конкурентов и всё равно оставаться в плюсе.** Это самое устойчивое преимущество в отрасли, где реклама дорожает каждый год.

## Что сделать на этой неделе

Три действия, которые дают эффект быстро.

**Посмотрите, где именно у вас обрывается.** Не «сколько дошло до конца», а на каком конкретно уроке график падает. Почти наверняка там окажется резкий скачок сложности или скучный блок теории без практики.

**Напишите тем, кто застрял.** Руками, десяти последним. Спросите не «почему бросили», а «на чём застряли». Ответы обычно оказываются неожиданными: люди называют не сложность, а бытовые причины и неловкость возвращаться.

**Перенесите первую победу на первую неделю.** Даже если ради этого придётся переставить модули местами.

И перестаньте считать конверсию в оплату главной метрикой. Оплата — это начало обязательства, а не его финал.

