### В чём суть

Контрольная в конце четверти показывает проблему, когда исправлять уже поздно: двойка поставлена, класс ушёл к новой теме, а пробел остался. Сильнее работает постоянная короткая обратная связь — педагоги называют это **формирующим оцениванием**. Его задача не поставить отметку, а вовремя увидеть, что пошло не так.

Как это устроено:

- **Входная диагностика** в начале года или курса: с чего стартуем.
- **Мини-проверка после каждой темы:** 3–5 задач, 10 минут.
- **Разбор ошибок сразу,** пока тема свежая.
- **Анализ по классу:** учитель видит, какую тему не понял весь класс, а какую — один ученик, и меняет план — даёт ещё урок, объясняет иначе, назначает консультацию.

