## Как устроен выбор

Перед тем как смотреть направления, определитесь с горизонтом. От него зависит всё остальное.

**Выходные.** Освоить один инструмент и применить в понедельник. Риска нет, эффект скромный, но мгновенный.

**Один-три месяца.** Добавить к текущей работе навык, который делает вас дороже или даёт подработку.

**Полгода и больше.** Полностью сменить сферу. Самый высокий потолок и самая высокая цена входа — не в деньгах, а во времени и нервах.

