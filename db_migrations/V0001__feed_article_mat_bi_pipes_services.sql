## Облачный BI: дашборд из Excel за минуту

[Облачный BI](https://mat-labs.ru/analytics/bi) решает самую частую задачу: есть выгрузка продаж из CRM или 1С, а нужны понятные графики.

**Как работает:**

1. Перетащите файл Excel или CSV на страницу — до 200 000 строк, первая строка должна содержать заголовки.
2. Система сама распознаёт даты, суммы и категории и подбирает графики.
3. Нажмите на любой столбец — весь дашборд отфильтруется по этому значению.
4. Нажмите «Поделиться» — руководитель откроет дашборд по ссылке без регистрации. Ссылка работает 90 дней.

**Главная особенность — сравнение с рынком.** Сервис ставит вашу выручку, маржу и выработку на сотрудника рядом с показателями отрасли по данным ФНС. В коробочных BI-системах такой функции нет.

**Безопасность.** Файл обрабатывается прямо в браузере и не отправляется на сервер. Дашборд хранится только на вашем устройстве, пока вы сами не нажмёте «Поделиться».

Нет файла под рукой — можно открыть демо на 1 200 сделках.

## Конвейер данных: отчёты собираются сами

[Конвейер данных](https://mat-labs.ru/analytics/pipes) снимает знакомую многим боль: каждую пятницу аналитик полдня выгружает данные из CRM, 1С и Метрики, склеивает в Excel и сверяет. А иногда выгрузка тихо ломается, и это замечают, только когда цифры на совещании не сходятся.

**Как работает — четыре шага в мастере:**

1. **Подключите источник** — ссылку на таблицу, токен amoCRM, вебхук Битрикс24 или адрес 1С. Мастер подскажет, где что взять.
2. **Настройте очистку** — дубли, пустые строки, суммы текстом вроде «1 200,50 ₽», даты в разных форматах и часовые пояса. Результат виден сразу на живой пробе данных.
3. **Поставьте расписание** — раз в сутки, каждые 6 часов или каждый час. При ошибке приходит письмо, загрузка повторяется автоматически.
4. **Смотрите отчёты** — одной кнопкой в облачном BI или по постоянной ссылке на CSV в Excel, Google Таблицах, Yandex DataLens или Power BI.

**10 готовых коннекторов:** Google Таблицы, файл по ссылке, amoCRM, Битрикс24, МойСклад, 1С (через OData), PostgreSQL, MySQL, Яндекс Метрика и любой REST API. Wildberries, Ozon, Яндекс Директ, VK Реклама, GetCourse, iiko, r_keeper, YCLIENTS и другие системы подключаются под ключ.

**Безопасность.** Пароли и токены хранятся в зашифрованном виде. Доступ к базам и CRM — только на чтение, изменить ваши данные невозможно. Хранилище находится в России.

