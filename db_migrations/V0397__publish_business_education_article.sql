## Как посчитать окупаемость до оплаты

Здесь начинается арифметика, которую почему-то никто не делает перед покупкой.

Формула простая:

**Срок окупаемости = стоимость обучения ÷ дополнительный доход в месяц**

Разберём на реальном примере. Курс по нейросетям для работы стоит 5 990 ₽. Если после него вы берёте один платный заказ на 15 000 ₽ — обучение окупилось за один заказ, а дальше вы в плюсе.

Другой пример. Курс интернет-маркетолога — 9 900 ₽. Один клиент на сопровождении рекламы приносит от 25 000 ₽ в месяц. Окупаемость — меньше половины первого месяца работы.

А теперь примерьте эту же формулу к программе за 300 000 ₽ с обещанием «дохода от 150 000». Даже если обещание сбудется — а оно сбывается редко — вы работаете два месяца в ноль, при условии что нашли работу сразу. Обычно поиск занимает ещё несколько месяцев.

**Вывод, который следует из арифметики:** дорогое обучение имеет смысл только там, где вы уже уверены в спросе на результат. Для проверки гипотезы «пойдёт ли мне эта сфера» дорогая программа — худший инструмент из возможных.

