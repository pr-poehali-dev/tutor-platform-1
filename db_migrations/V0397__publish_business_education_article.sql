## Как выбрать программу: четыре вопроса

Перед оплатой любого курса — не только нашего — задайте себе эти вопросы.

**Первый: какую задачу я смогу закрыть после?** Не «что узнаю», а именно что смогу сделать руками. Если ответа нет, не покупайте.

**Второй: есть ли практика с проверкой?** Просмотр видео не формирует навык. Нужны задания, которые кто-то или что-то проверяет и указывает на ошибки.

**Третий: что останется в портфолио?** После обучения должны остаться работы, которые можно показать заказчику. Сертификат работой не является.

**Четвёртый: можно ли попробовать до оплаты?** Если школа не даёт посмотреть хотя бы один полноценный урок бесплатно — это сигнал. Ей есть что скрывать.

