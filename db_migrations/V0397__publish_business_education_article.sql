## Четыре сценария, которые работают

Теперь к сути. Есть четыре разных способа превратить обучение в деньги, и они требуют разного.

### Сценарий 1. Надстройка над текущей работой

Самый быстрый и самый недооценённый.

Вы не меняете профессию. Вы добавляете к тому, что уже умеете, инструмент, который делает вас дороже.

Бухгалтер, освоивший нейросети, обрабатывает первичку вдвое быстрее и берёт больше клиентов на сопровождение. Менеджер, научившийся работать с ИИ-ассистентами, закрывает рутину за час вместо дня. Юрист с навыком быстрой подготовки документов успевает вести больше дел.

**Что учить:** [нейросети для работы](/courses/ai), [ИИ-бот в Telegram без кода](/courses/ai), [нейросети для маркетинга и продаж](/courses/marketing).

**Срок до эффекта:** несколько недель.
**Риск:** минимальный — вы не увольняетесь и ничем не рискуете.
**Честное ограничение:** прибавка редко бывает кратной. Это плюс 20–40% к эффективности, а не другая жизнь.

### Сценарий 2. Вторая профессия для подработки

Вы осваиваете навык, который можно продавать отдельно от основной работы, по вечерам и выходным.

Здесь важен выбор ниши. Работают те, где результат измерим и заказчик понимает, за что платит: настройка рекламы, ведение контента, сопровождение сделок, черчение, тендерное сопровождение.

**Что учить:** [промпт-инженер](/courses/prompteng), [интернет-маркетолог](/courses/marketing), [заработок на нейросетях](/courses/neuroincome), [AutoCAD](/courses/autocad).

**Срок до первых денег:** 2–4 месяца при регулярных занятиях.
**Риск:** средний — тратится личное время, а первые заказы приходят не сразу.
**Честное ограничение:** первый клиент — самое трудное. Не обучение, а именно он.

### Сценарий 3. Полная смена профессии

Самый радикальный путь и самый долгий.

Здесь нельзя обманываться: вход в новую профессию с нуля занимает от полугода до года, и ещё несколько месяцев уходит на поиск работы. Всё это время доход не растёт, а иногда падает.

Зато потолок выше. Профессии, где сейчас реальный дефицит кадров: [аналитик данных](/courses/analyst), [кибербезопасность](/courses/cybersec), [DevOps](/courses/devops), [ВЭД и таможня](/courses/ved), [тендеры и госзакупки](/courses/tenders), [бухгалтер](/courses/accounting).

**Срок:** 6–12 месяцев до первого оффера.
**Риск:** высокий — нужен финансовый запас на период перехода.
**Честное ограничение:** без портфолио вас не возьмут. Сертификат сам по себе не работает нигде.

