## Главная ошибка: покупают знания, а платят за результат

Начнём с различия, которое стоит людям сотен тысяч рублей.

**Знания** — это то, что вы узнали. **Навык** — то, что вы умеете делать. **Результат** — то, за что вам платят деньги.

Между ними лежат пропасти, и обучение обычно закрывает только первую.

Человек прошёл курс по маркетингу. Он знает, что такое воронка продаж, чем отличается охват от конверсии, как считать стоимость привлечения клиента. Знает. Но не может настроить рекламную кампанию, у которой сходится экономика.

Работодатель или заказчик покупает не знание. Он покупает **закрытую задачу**: настроенную рекламу, сданный отчёт, оформленную поставку, работающего бота.

Отсюда первый практический критерий выбора программы:

