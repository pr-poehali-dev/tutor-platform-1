Знание приставок и суффиксов позволяет понимать слова, которые вы никогда не учили. И это прямо проверяется на ОГЭ и ЕГЭ в заданиях на словообразование.

| Часть слова | Что делает | Пример |
|---|---|---|
| -er, -or | человек, который делает | teach → teacher, act → actor |
| -tion, -sion | действие или процесс | invent → invention, decide → decision |
| -ness | качество | kind → kindness |
| -ful | полный чего-то | help → helpful |
| -less | без чего-то | help → helpless |
| un-, im-, dis- | отрицание | happy → unhappy, possible → impossible, agree → disagree |

