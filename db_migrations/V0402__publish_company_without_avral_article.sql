## Точка 1. Найм и онбординг: минус 20 часов на человека

Возьмём типовую ситуацию. В команду выходит новый удалённый исполнитель.

Что происходит обычно: два-три созвона «расскажу как у нас устроено», хаотичная выдача задач, первые две недели правок, ощущение «проще сделать самому», и через месяц — либо человек кое-как вработался, либо расстались и всё сначала.

Цена вопроса — 15–25 часов руководителя на одного человека. И это при удачном исходе.

**Что делает [«Оркестратор»](/orchestrator).** Вы указываете роль и специфику проекта, ИИ собирает трек адаптации: матрицу навыков по уровням, входной контроль с тест-кейсами, план онбординга по дням, микрозадачи с критериями «готово» и карту рисков по исполнителю. Дальше в рабочем дашборде вы ведёте людей по статусам и видите метрики качества.

Что меняется структурно — три вещи:

- **Входной контроль отсекает слабых до старта.** Не после месяца правок, а на входе, за 20 минут теста.
- **Критерии «готово» убирают круг правок.** Спор «я думал, надо было иначе» физически невозможен, если критерий написан заранее.
- **Онбординг перестаёт быть событием.** Он становится процессом, который идёт без вас: план по дням у человека уже есть.

Генерация трека бесплатна — можно прямо сейчас вбить роль, которую вы давно собираетесь нанять, и посмотреть, как выглядит адаптация, собранная не в вашей голове.

## Точка 2. Решения о деньгах: минус три бессонные ночи

Второй пожиратель — решения с деньгами. Запускать ли направление. Поднимать ли цену. Брать ли кредит на расширение.

