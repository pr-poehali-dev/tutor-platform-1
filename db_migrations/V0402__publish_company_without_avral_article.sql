## Арифметика недели

Теперь сложим. Возьмём условную компанию: 14 человек, двое-трое новых сотрудников в квартал, один основатель, который «держит всё».

Куда уходили его 60 часов в неделю:

- онбординг и разъяснения новичкам — 8 ч
- ответы на вопросы по продукту и клиентам — 10 ч
- решения по цифрам и «посчитать на коленке» — 6 ч
- постановка задач и разбор правок — 12 ч
- найм: просмотр, собеседования, отсев — 5 ч
- собственно развитие компании — 9 ч
- всё остальное, включая тушение пожаров — 10 ч

Что происходит после того, как шесть точек закрыты системой:

- онбординг ведёт трек — **остаётся 2 ч**
- на вопросы по продукту отвечает обученная команда и ИИ-тренер — **остаётся 3 ч**
- решения по цифрам принимают руководители направлений с расчётом на руках — **остаётся 2 ч**
- задачи ставятся по формуле, правки схлопываются критериями «готово» — **остаётся 5 ч**
- найм идёт через входной контроль, до вас доходят финалисты — **остаётся 1,5 ч**
- развитие компании — **растёт до 12 ч**
- пожаров становится меньше, потому что большинство из них — последствия первых пяти строк — **остаётся 4 ч**

Итого: **около 30 часов вместо 60.**

И вот здесь начинается главное. Освободившиеся тридцать часов можно потратить двумя способами.

Первый — залить их новой работой. Так делают почти все, и через полгода расписание снова забито, только теперь «более важными» делами. Это не результат, это повышение пропускной способности узкого места. Узким местом остались вы.

Второй — **отдать половину компании, а половину себе.** Двенадцать часов на развитие, которого раньше не было. И восемнадцать — на человека, который всё это строил.

## Что реально меняется в структуре

Если пройти этот путь до конца, компания меняется не количественно, а по устройству:

- **Владелец из диспетчера становится архитектором.** Он не раздаёт задачи — он проектирует правила, по которым задачи раздаются сами.
- **Знание переезжает из голов в систему.** Уход ключевого сотрудника перестаёт быть катастрофой.
- **Руководители направлений получают право на решение.** Потому что у них появился инструмент считать, а не угадывать.
- **Новый человек — не риск, а процедура.** С предсказуемым сроком выхода на результат.
- **Появляется второй продукт** — из экспертизы, которая раньше просто была.

Это и есть ответ на вопрос «зачем бизнесу ИИ». Не чтобы быстрее писать письма. Чтобы **перестать быть незаменимым**.

## Где эта модель ломается

Обещали честно — вот ограничения. Их четыре, и все они не технические.

**Первое: нельзя автоматизировать беспорядок.** Если в компании нет описанного процесса, модуль не создаст его за вас — он создаст описание того хаоса, который есть. Начинать надо с матрицы ответственности, а не с дашборда.

**Второе: делегирование решений болезненно.** Первые месяцы руководители будут принимать решения хуже вас. Это неизбежная цена перехода, и большинство откатывается назад именно здесь — не выдержав чужих ошибок.

**Третье: цифры должны быть настоящими.** Финансовый разбор на выдуманных данных даст красивый и бесполезный результат. Плохие новости в отчёте — это не сбой, а самое ценное в нём.

**Четвёртое: свободное время нужно защищать.** Оно не остаётся свободным само. Если не поставить границу в календаре, вакуум заполнится за две недели.

