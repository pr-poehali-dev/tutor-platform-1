## Что это значит практически

Соберём выводы для тех, кто планирует подавать заявку.

**Готовьте не проект, а измеримый результат.** Формулировка «повысим осведомлённость» проигрывает формулировке «обучим 200 человек, из них 60 трудоустроятся». Второе можно проверить, первое — нет.

**Привязывайтесь к приоритетной теме честно.** Натянуть экологию на проект, который к ней не относится, — распространённая ошибка: эксперты видят это сразу. Лучше найти реальное пересечение вашей деятельности с приоритетом.

**Начинайте с малых сумм.** История успешно закрытых небольших грантов работает лучше, чем первая заявка на максимальную сумму. Фонды смотрят на то, справлялись ли вы раньше.

**Не подавайтесь в один фонд.** У площадок разные приоритеты и разные сроки. Один и тот же проект, переупакованный под профиль двух-трёх фондов, кратно повышает шансы.

**Считайте экономику проекта заранее.** Грант — это не подарок, а обязательство потратить деньги определённым образом и отчитаться. Проект, который не выдерживает собственную смету, создаёт проблемы вместо помощи.

