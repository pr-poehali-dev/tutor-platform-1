## Частые вопросы

**Скидка на каждый курс или на весь заказ?**
На весь заказ: она считается от общей стоимости всех курсов в корзине.

**Можно ли сочетать с промокодом?**
Нет, скидка корзины и промокоды не суммируются. Промокод по-прежнему работает при покупке одного курса.

**Что, если какой-то курс у меня уже есть?**
Купленные и бесплатные курсы в корзину не попадают и не учитываются в количестве — вы платите только за новое.

**Можно ли взять курсы из разных направлений?**
Да. Школьные, взрослые, профессии — любые платные курсы каталога, до 10 штук в одном заказе.

**Какой срок доступа?**
Как и при обычной покупке — навсегда, с ИИ-наставником, который отвечает в любое время.

**Можно ли сначала попробовать?**
Да. Первый урок в каждом курсе бесплатный — посмотрите формат и только потом собирайте корзину.

