## Зачем мы это сделали

Взрослые редко учатся «одному навыку». Маркетологу нужны нейросети, бухгалтеру — 1С и Excel, тому, кто запускает своё дело, — продажи, маркетплейсы и SMM. Раньше каждый курс приходилось покупать отдельно и по полной цене, и связка из трёх программ выходила в серьёзную сумму.

Теперь можно сразу собрать свою траекторию и заплатить за неё заметно меньше.

## Как воспользоваться

1. Откройте [каталог курсов](/courses) или [программы для взрослых](/kursy-dlya-vzroslyh).
2. Нажмите **«В корзину»** на карточках нужных курсов. Кнопка есть и на странице каждого курса.
3. Откройте корзину — справа внизу экрана появится оранжевая кнопка с числом курсов.
4. Проверьте итог: старая цена зачёркнута, рядом — новая и размер скидки.
5. Войдите в аккаунт, укажите почту для чека и оплатите всё одним платежом.

После оплаты все курсы сразу открываются в личном кабинете — навсегда, как и при обычной покупке.

