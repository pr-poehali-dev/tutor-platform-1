## В чём была проблема

Языковые модели пишут уравнения реакций «по памяти», как текст. Они хорошо знают, какие вещества вступают в реакцию, но регулярно ошибаются в коэффициентах. Классический пример — горение метана без коэффициентов: CH₄ + O₂ → CO₂ + H₂O. Кислорода слева 2 атома, справа 4 — закон сохранения массы нарушен.

Для ученика такая ошибка опасна: он запоминает неверную запись, а на экзамене за неё снимают баллы.

## Что мы сделали

**1. Каждое уравнение проверяется математически.** После ответа ИИ сервер находит в тексте все уравнения реакций и считает атомы каждого элемента слева и справа. Если баланс не сходится, коэффициенты рассчитываются точно — как система уравнений по каждому элементу — и подставляются в ответ.

**2. Чёткие правила записи для ИИ.** Реакции пишутся формулами, коэффициенты расставляются всегда, условия указываются над стрелкой: свет hν, нагревание t°, катализатор. Никакой записи формул словами в текстовом ответе.

**3. Полнота ответа.** Если спрашивают свойства класса веществ, ИИ перечисляет все типичные реакции из школьной программы и кодификатора ЕГЭ, а также то, чего этот класс не делает.

**4. Аккуратное оформление.** Индексы показываются нижними цифрами: H₂SO₄, Ca(OH)₂, C₂H₅Cl.

**5. Пометка в уроках.** В уроках курсов химии появилась отметка «Уравнения реакций проверены» с числом проверенных и исправленных уравнений.

## Проверка: химические свойства алканов

Мы задали ИИ-репетитору тот самый вопрос. Вот уравнения из ответа:

- **Горение:** CH₄ + 2O₂ → CO₂ + 2H₂O
- **Галогенирование на свету:** CH₄ + Cl₂ →(hν) CH₃Cl + HCl
- **Нитрование по Коновалову:** CH₄ + HNO₃ →(t°) CH₃NO₂ + H₂O
- **Дегидрирование:** C₂H₆ →(Pt, t°) C₂H₄ + H₂
- **Крекинг:** C₁₀H₂₂ →(t°) C₅H₁₂ + C₅H₁₀
- **Разложение метана:** CH₄ →(t°) C + 2H₂

ИИ также упомянул изомеризацию и то, что алканы не обесцвечивают бромную воду и раствор перманганата калия, — это отличает их от алкенов и алкинов.

Все шесть уравнений прошли проверку баланса. В уроке курса по той же теме система нашла и исправила одно уравнение неполного горения пропана: правильно 2C₃H₈ + 7O₂ → 6CO + 8H₂O.

## Чего проверка не умеет

Честно о границах. Проверка гарантирует **баланс атомов**, то есть правильные коэффициенты. Но она не может доказать, что реакция вообще идёт при этих условиях или что продукты выбраны верно, — это химия, а не арифметика. Эту часть обеспечивают правила для ИИ и более сильная модель для химии, но полностью заменить знания педагога они не могут.

Ионные уравнения и общие формулы вида CnH2n+2 проверка пока не трогает, чтобы не испортить заряды и индексы-переменные.

Если вы нашли ошибку в реакции — напишите нам через форму отзыва в конце урока. Каждое такое сообщение помогает сделать ИИ-репетитора точнее.

