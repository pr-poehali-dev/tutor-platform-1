1. *Гибридные автомобили.* Задача — увеличить продажи. Конкурирующие автобренды разбили на три группы и выявили психотипы владельцев. Итог: кастомный сегмент на 79 125 человек, уникальный охват 432 692 человека за месяц, рост конверсии в звонок или заявку на сайте на 23%.
