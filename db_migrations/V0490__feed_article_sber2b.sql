## Самое ценное — не реклама, а стратегия

На встрече нас зацепила одна мысль. Сегментация нужна не только для того, чтобы «стрелять точнее». Она отвечает на вопрос, *что* говорить каждой группе.

В презентации был пример с застройщиком. Двум «мужским» сегментам с одинаковым возрастом и доходом нужны разные сообщения: холостяку-индивидуалисту важны прозрачность сделки и помощь на каждом шаге, а семьянину — детский сад, школа и инфраструктура рядом с домом.

Для образования это ложится один в один. Родителю первоклассника и родителю одиннадцатиклассника мы говорим про разное: одному — про спокойные домашние задания без слёз, другому — про ЕГЭ и поступление. Сейчас мы угадываем, кто перед нами. Данные позволяют знать.

## Честно о бюджете

Молодой компании важно трезво смотреть на цифры. По презентации, минимальная стоимость проекта по сегментации и размещению — от 1,22 млн ₽ с НДС, а отдельные каналы стоят от сотен тысяч до нескольких миллионов рублей в месяц. Для стартапа на ранней стадии это не «попробовать на выходных», а осознанная инвестиция, которую нужно считать.

Поэтому мы не бежим запускать кампанию завтра. План такой:

1. **Начать с аналитики, а не с рекламы.** Проверять контрагентов и смотреть региональную статистику — это недорогой способ использовать данные Сбера уже сейчас.
2. **Выбрать регионы с умом.** У нас есть [справочник 12 200 школ в 32 городах и 11 регионах](/shkoly) и пилот рассылки школам. Данные о потребительской активности по городам помогут понять, где семьи больше тратят на образование, и начать оттуда.
3. **Сформулировать гипотезу сегмента.** Например, семьи со школьниками, которые уже платят за репетиторов или онлайн-курсы. И только потом считать, окупится ли таргетинг при нашей цене подписки 1 490 ₽ в месяц.

## Что это значит для других молодых компаний

Вот главное, что мы вынесли со встречи, — и что, на наш взгляд, полезно любой небольшой технологической команде:

- **Крупная экосистема открыта для небольших компаний.** Это не только реклама за миллионы, но и инструменты аналитики, проверки контрагентов и поиска клиентов.
- **Данные — это про сообщение, а не только про охват.** Сегментация подсказывает, *что* говорить каждой группе, и это ценно ещё до первого рубля на рекламу.
- **Партнёрство — это обмен опытом.** Сбер2B объединяет 400+ партнёров. Для молодой команды это шанс учиться на чужих проверенных кейсах, а не на своих ошибках.
- **Считайте экономику до запуска.** Сильный инструмент не отменяет простой арифметики: стоимость привлечения должна окупаться ценностью клиента.

