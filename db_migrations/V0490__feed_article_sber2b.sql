## С чего всё началось

МАТ-Лабс — небольшая команда разработчиков из Самары. Мы делаем автоматизацию с ИИ для малого и среднего бизнеса, а ещё развиваем собственные продукты. Самый крупный из них — образовательная платформа [УЧИСЬПРО](/): ИИ-наставник для школьников, разбор домашки по фото, подготовка к ОГЭ и ЕГЭ.

У любой молодой EdTech-компании одна и та же боль: продукт есть, а как дотянуться до нужной семьи — непонятно. Контекстная реклама дорожает, а родитель школьника в ленте ничем не отличается от любого другого взрослого. В рекламном кабинете мы видим «женщина, 35–44, интересы: образование». Но мы не видим, тратит ли семья деньги на репетиторов, кружки и подготовку к экзаменам.

С этим вопросом мы и пришли на встречу с представителями Сбер2B. Ниже — что мы узнали и почему это интересно не только нам, но и любой небольшой технологической компании.

## Что такое Сбер2B

Сбер2B — система бизнес-сервисов Сбера: аналитика, таргетинг, автоматизация, ИИ, онлайн-продажи и ЭДО. Масштаб, по данным компании:

- 50+ собственных решений для бизнеса;
- 400+ партнёров с лучшими практиками рынка;
- 2,5 тыс. клиентов из крупного бизнеса и госсектора;
- 1,2+ млн клиентов малого бизнеса.

Отдельно Сбер подчёркивает, что продукты входят в реестр отечественного ПО. Для нас это важно: часть наших клиентов — школы и бюджетные организации.

Самое интересное для молодой компании — не размер, а подход: сопровождение «от консалтинга до разработки» и решения, уже проверенные на реальных задачах. Нам показали два направления.

## Направление 1. Аналитика на данных, которых ни у кого больше нет

Сбер2B Аналитика работает с обезличенными и агрегированными данными экосистемы. Масштаб покрытия:

- 111+ млн физических лиц;
- 6+ млн юридических лиц;
- 7,7+ млн торговых точек;
- 10+ млн терминалов, из них более 6 млн — с эквайрингом Сбера;
- 1,1+ тыс. городов, все регионы России;
- 70+ источников данных и глубина ретроспективы 60+ месяцев с ежедневной детализацией.

Принципиальный момент: исследования строятся на обезличенных данных, персональная информация и коммерческая тайна не раскрываются. Для компании, которая работает с детьми и родителями, это не формальность, а условие, без которого мы бы вообще не стали обсуждать данные.

Из продуктов нам показали несколько, которые полезны и маленькой компании:

**Аналитика партнёров.** Проверка благонадёжности контрагентов по ИНН, ОГРН или названию, финансовая устойчивость, отслеживание изменений. В базе 9 млн компаний, данные пополняются ежедневно. Для нас это прикладная вещь: мы регулярно заключаем договоры со школами, частными центрами и партнёрами по франшизе.

**Подбор B2B-клиентов.** Сервис находит покупателей и поставщиков по реальным транзакциям, ставит каждой компании скор-балл по объёму и частоте потребления и оценивает готовность к покупке. Для B2B-направления МАТ-Лабс, то есть автоматизации для бизнеса, это потенциальная замена холодных баз.

**СберИндекс.Про.** Социально-экономическая статистика по регионам и городам в режиме, близком к реальному времени: потребительская и деловая активность, доходы населения. Обновляется еженедельно и ежемесячно.

**Data Tracker.** Макроэкономические и отраслевые данные, прогнозы экспертов Сбера, надстройка к Excel и AI-аналитик. Скорее инструмент для финансового планирования, чем для маркетинга.

## Направление 2. Сегментация и таргетинг

Вторая презентация была ближе к нашей боли. Сбер2B предлагает собрать целевые аудитории под задачу бизнеса и запустить рекламу на площадках Сбера и партнёров.

Основа — финансовые потоки. По данным компании, Сбер видит 70,5% безналичных платежей населения и 70% розничных торговых точек в 1,1 тыс. городов. Охват для сегментирования — 112 млн человек.

**Как строятся сегменты.** Из обезличенных транзакций собираются группы, например:

- покупатели конкурентов или смежных товаров и услуг;
- потенциальные покупатели с определённым уровнем доходов и сбережений;
- новые, лояльные, «спящие», ушедшие и вернувшиеся клиенты — по частоте, давности и сумме покупок.

Сверху добавляются данные сервисов экосистемы, статистика SberAds о поведении на сайтах и партнёрские DMP. В итоге получается 7 000+ аудиторных сегментов на банковских транзакциях, а всего около 10 000 сегментов, которые обновляются ежемесячно. География настраивается на уровне всей России, региона или города.

**Где показывается реклама.** Баннеры и видео в медиасети, посевы, приложение СберБанк Онлайн, банкоматы Сбера, Самокат и Купер, 2ГИС. Из партнёрских площадок в презентации — Рамблер, Афиша, Лента.ру, Газета.ру, Okko, Чемпионат и другие.

