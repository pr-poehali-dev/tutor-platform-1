**Честно о «10 минутах».** Это время подключения, если 1С уже опубликована на веб-сервере с интерфейсом OData. Если нет — публикацию делает ваш администратор 1С (обычно это отдельная задача на час-два). Без публикации можно подключить выгрузку файла из 1С по ссылке — об этом в конце.

## Пример: что хотим получить

Условная компания «СтройДвор» продаёт стройматериалы. Заявки ведутся в amoCRM, отгрузки — в 1С:Управление торговлей. Собственник хочет каждое утро видеть:

- сколько сделок в работе и на каком они этапе
- какие менеджеры закрывают больше
- сколько реально отгружено и на какую сумму

Для этого нужно два источника: **сделки из CRM** и **реализации из 1С**. Оба помещаются в бесплатный тариф «Старт»: 2 источника до 10 000 строк в каждом.

## Шаг 0. Вход в кабинет — 1 минута

1. Откройте [mat-labs.ru/analytics/pipes](https://mat-labs.ru/analytics/pipes) и нажмите «Подключить бесплатно».
2. Введите почту — придёт код. Пароль не нужен, аккаунт создаётся автоматически на тарифе «Старт».

## Шаг 1. Подключаем CRM — 3 минуты

В кабинете нажмите «Новый источник». Мастер проведёт по четырём экранам: **Источник → Доступ → Очистка → Расписание**.

### Вариант А: amoCRM

1. В amoCRM откройте «amoМаркет» → «⋯» → «Создать интеграцию» → «Внешняя».
2. Дайте доступ к данным аккаунта и сохраните.
3. На вкладке «Ключи и доступы» нажмите «Сгенерировать долгосрочный токен» и скопируйте его.
4. В мастере выберите **amoCRM** и заполните два поля. **Адрес аккаунта** — только поддомен: для `stroydvor.amocrm.ru` это `stroydvor`. **Долгосрочный токен** — вставьте скопированное.

Сервис загрузит сделки с воронками, этапами, ответственными и дополнительными полями.

### Вариант Б: Битрикс24

1. В Битрикс24 откройте «Разработчикам» → «Другое» → «Входящий вебхук».
2. Отметьте право **CRM (crm)** — чтения достаточно.
3. Скопируйте «Вебхук для вызова rest api» — адрес вида `https://ваш.bitrix24.ru/rest/1/…/`.
4. В мастере выберите **Битрикс24**, вставьте адрес и в поле «Что загружать» выберите **Сделки** (также доступны лиды, контакты и компании).

Нажмите **«Проверить подключение»**. Если всё верно, мастер покажет первые строки ваших данных.

## Шаг 2. Подключаем 1С — 3 минуты

### Подготовка (делает администратор 1С один раз)

1. В Конфигураторе: «Администрирование» → «Публикация на веб-сервере» → включить **«Публиковать стандартный интерфейс OData»**.
2. В режиме предприятия: «Администрирование» → «Интерфейс OData» → отметить нужные объекты, например документ «Реализация товаров и услуг».
3. Завести отдельного пользователя 1С **только с правами на чтение**.
4. Сервер должен быть доступен из интернета по https.

### Подключение в мастере

Выберите источник **1С (OData)** и заполните поля:

| Поле | Что вписать в нашем примере |
|---|---|
| Адрес OData | `https://1c.stroydvor.ru/base/odata/standard.odata` |
| Объект | `Document_РеализацияТоваровУслуг` |
| Пользователь 1С и пароль | тот самый пользователь «только чтение» |
| Только поля (необязательно) | `Date,Number,СуммаДокумента` |
| Фильтр (необязательно) | `Date ge datetime'2026-01-01T00:00:00'` — только документы с начала года |

**Совет:** указывайте только нужные поля и фильтр по дате. Так загрузка идёт быстрее, а вы не упираетесь в лимит 10 000 строк бесплатного тарифа.

Для остатков подойдёт объект `AccumulationRegister_ТоварыНаСкладах_RecordType`, для справочника товаров — `Catalog_Номенклатура`.

Нажмите «Проверить подключение».

## Шаг 3. Чистим данные — 1 минута

Это шаг, на который вручную уходит больше всего времени. В мастере он занимает несколько галочек:

- **Убрать лишние пробелы** и заглушки «—», «н/д»
- **Удалить пустые строки**
- **Удалить дубли** — можно указать, что считать дублем: всю строку целиком или, например, одинаковый номер документа
- **Числа:** «1 200,50 ₽» превращается в 1200.5
- **Даты** приводятся к одному формату ГГГГ-ММ-ДД
- **Часовой пояс отчётов** — например, московское время, чтобы данные CRM и 1С совпадали по дням

Результат каждой галочки сразу виден на живой пробе ваших данных.

## Шаг 4. Ставим расписание — 30 секунд

Выберите, как часто обновлять данные: вручную, раз в неделю, раз в сутки, каждые 6 часов или каждый час. На бесплатном тарифе доступны обновления раз в сутки и раз в неделю — для утреннего отчёта собственнику этого достаточно.

Если загрузка сломается (например, истёк токен), придёт письмо с понятной причиной, а сервис сам повторит попытку. В отчётах останутся данные последней успешной загрузки.

## Шаг 5. Открываем отчёт — 1 минута

У каждого источника в кабинете есть две кнопки:

- **«Открыть в BI»** — данные сразу открываются в [облачном BI](https://mat-labs.ru/analytics/bi). Сервис сам распознаёт даты, суммы и категории и строит графики. Клик по столбцу фильтрует весь дашборд.
- **Ссылка на CSV** — постоянный адрес со свежими данными. Его можно подключить в Excel («Данные» → «Из интернета»), Google Таблицы, Yandex DataLens или Power BI.

Что увидит собственник «СтройДвора» в нашем примере:

| Вопрос | Откуда ответ |
|---|---|
| Сколько сделок на каждом этапе воронки | Дашборд по сделкам из CRM |
| Кто из менеджеров закрывает больше | Тот же дашборд, клик по ответственному |
| Сколько отгружено по дням и на какую сумму | Дашборд по реализациям из 1С |

Дашбордом можно поделиться: ссылка открывается без регистрации и работает 90 дней.

