## Частые проблемы

**«1С не подключается».** Проверьте, что адрес открывается из интернета по https и что нужный объект отмечен в «Интерфейсе OData». Если базу нельзя выставлять наружу — подключите источник «Файл по ссылке»: настройте в 1С регулярную выгрузку в Excel или CSV на Яндекс Диск или FTP.

**«Данных больше 10 000 строк».** Добавьте фильтр по дате или перейдите на тариф «Бизнес» за 4 900 ₽ в месяц: 15 источников до 200 000 строк и обновление каждый час. В этот тариф входит и помощь с подключением 1С и CRM.

**«Хочу видеть CRM и 1С на одном графике».** Свести несколько систем в единую витрину можно на тарифе «Под ключ» (от 60 000 ₽ за внедрение) или самостоятельно — подключив обе CSV-ссылки в Google Таблицы, DataLens или Power BI.

**«Безопасно ли это?»** Пароли и токены хранятся зашифрованными и не показываются даже в кабинете. Доступ к 1С и CRM — только на чтение, изменить ваши данные невозможно. Хранилище находится в России.

