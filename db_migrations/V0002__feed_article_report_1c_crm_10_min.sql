## Зачем это нужно

Знакомая картина: в понедельник руководитель просит отчёт «сколько продали и откуда пришли клиенты». Менеджер выгружает сделки из CRM, бухгалтер — реализации из 1С, кто-то склеивает всё в Excel, правит даты и убирает дубли. Полдня работы — и через неделю всё заново.

Ниже — как настроить это один раз так, чтобы отчёт собирался сам.

## Что понадобится

| Что | Где взять | Сколько времени |
|---|---|---|
| Электронная почта | Любая рабочая — на неё придёт код входа | — |
| Доступ к CRM на чтение | Токен amoCRM или вебхук Битрикс24 | 2–3 минуты |
