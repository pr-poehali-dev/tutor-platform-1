export type Level = "low" | "mid" | "high";

export interface CompetencyScore {
  competency: Competency;
  percent: number;
  level: Level;
}

export function levelOf(percent: number): Level {
  if (percent < 50) return "low";
  if (percent < 75) return "mid";
  return "high";
}

export const LEVEL_LABEL: Record<Level, string> = {
  low: "Зона роста",
  mid: "Хорошая база",
  high: "Сильная сторона",
};

/** Ответы 1–5 → проценты 0–100 по каждой компетенции. */
export function scoreAnswers(answers: Record<number, number>): CompetencyScore[] {
  return COMPETENCIES.map((c) => {
    const qs = QUESTIONS.filter((q) => q.competency === c.id);
    const sum = qs.reduce((acc, q) => acc + (answers[q.id] ?? 1), 0);
    const percent = Math.round(((sum - qs.length) / (qs.length * 4)) * 100);
    return { competency: c, percent, level: levelOf(percent) };
  });
}

export function overallPercent(scores: CompetencyScore[]): number {
  return Math.round(scores.reduce((a, s) => a + s.percent, 0) / scores.length);
}

