/**
 * Готовые тексты объявлений для Яндекс.Директ.
 * Все тексты соблюдают лимиты Директа:
 *  - Заголовок 1: до 56 символов
 *  - Заголовок 2: до 30 символов
 *  - Описание: до 81 символа
 *  - Быстрые ссылки: до 30 символов, описание до 60
 *
 * Лендинг — отдельная страница /ads/{slug} с UTM-трекингом.
 */

export interface AdVariant {
  /** Заголовок 1 (главный, до 56 символов) */
  title1: string;
  /** Заголовок 2 (дополнительный, до 30 символов) */
  title2: string;
  /** Описание (до 81 символа) */
  description: string;
}

export interface QuickLink {
  label: string;
  description: string;
  path: string;
}

/**
 * Кампания в Рекламной сети Яндекса (РСЯ).
 *
 * Зачем отдельно от поиска: в поиске человек уже сформулировал запрос и ищет
 * решение — там выигрывает точное попадание в формулировку. В РСЯ он читает
 * статью и никого не просил ему что-то показывать, поэтому объявление должно
 * сначала остановить взгляд, а уже потом предлагать. Отсюда другие тексты
 * (цепляющие, а не «ключевые»), картинки вместо ключевых фраз в роли главного
 * носителя смысла и таргетинг по интересам, а не по словам.
 *
 * Частая ошибка — копировать поисковые объявления в РСЯ: показы идут,
 * CTR падает до сотых процента, площадки крутят мусорный трафик.
 */
export interface RsyaCampaign {
  /**
   * Ссылка с отдельной меткой utm_medium=cpm.
   *
   * Обязательно своя: если вести сети по той же ссылке, что и поиск, в отчётах
   * они склеятся в одну строку. А это два разных канала с разной ценой
   * конверсии — и отключать при сливе бюджета нужно уметь по отдельности.
   */
  finalUrl: string;
  /** Текстово-графические объявления: в РСЯ лимиты мягче, чем на поиске */
  variants: AdVariant[];
  /**
   * Что изображено на баннере. РСЯ требует картинку — без неё объявление
   * показывается редко и плохо. Тексты для генерации, а не готовые файлы.
   */
  imageIdeas: string[];
  /** Готовые баннеры в папке public/ads — можно скачать и загрузить в Директ */
  readyImages?: { src: string; ratio: string }[];
  /** Интересы и сегменты для таргетинга — в РСЯ они вместо ключевых фраз */
  interests: string[];
  /** Площадки и тематики, которые стоит отключить сразу */
  excludedPlacements: string[];
  /** На что настроить ретаргетинг: кто уже был на сайте, но не дошёл */
  retargeting: { name: string; condition: string; pitch: string }[];
  /** Практические настройки кампании — то, что чаще всего забывают */
  settings: string[];
}

export interface AdCampaign {
  slug: string;
  name: string;
  emoji: string;
  color: string;
  /** Аудитория и боли */
  audience: string;
  pains: string[];
  /**
   * Куда ведут кнопки лендинга и что на них написано.
   *
   * Раньше это было зашито в шаблон: любая кампания вела на /courses
   * и обещала «первый урок бесплатно». Для школьных кампаний это верно,
   * а для репетиторов — прямая ложь: им нужен конструктор курсов,
   * а не каталог. Несовпадение объявления и посадочной убивает конверсию
   * и снижает качество объявления в Директе.
   */
  cta?: {
    primaryLabel: string;
    primaryPath: string;
    secondaryLabel: string;
    secondaryPath: string;
    /** Подпись под финальной кнопкой — снимает возражение про оплату */
    finalNote: string;
    /** Плашка в шапке лендинга */
    badge: string;
  };
  /** Ключевые фразы для подбора */
  keywords: string[];
  /** Минус-слова */
  negativeKeywords: string[];
  /** Главный оффер */
  offer: string;
  /** Целевая страница на сайте (куда ведём с объявления) */
  landingPath: string;
  /** Финальный URL с UTM */
  finalUrl: string;
  variants: AdVariant[];
  quickLinks: QuickLink[];
  /** Уточнения (до 25 симв) */
  refinements: string[];
  /** Кампания в РСЯ — отдельная логика, есть не у всех направлений */
  rsya?: RsyaCampaign;
}

