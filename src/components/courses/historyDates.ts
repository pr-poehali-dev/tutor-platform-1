/** Возвращает дату/период события по названию урока или модуля. null — если события нет. */
export function getHistoryDate(title: string): string | null {
  const t = (title || "").toLowerCase();
  if (!t) return null;
  // Датировка уже стоит в самом названии — годом («Отечественная война 1812 года»)
  // или веками («Российская империя (XVIII–XIX вв.)»). Повторять её бейджем незачем.
  if (/\d{3,4}/.test(t)) return null;
  // NB: \b в JS не работает с кириллицей, поэтому границу слова тут не используем.
  if (/[ivxlcdm]{1,7}\s*(?:вв?\.|вв?\s|век)/.test(t)) return null;
  for (const rule of RULES) {
    if (rule.match.some((m) => t.includes(m))) return rule.date;
  }
  return null;
}