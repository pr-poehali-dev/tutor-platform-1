/** Продающее SEO-описание курса для публичной витрины.
 *  Пишется под поисковый запрос человека («сколько зарабатывает…», «с нуля»),
 *  а не под внутренний каталог. */
export interface CourseSeoCopy {
  /** Заголовок для выдачи — до 65 символов вместе с брендом */
  metaTitle: string;
  /** Описание для сниппета — до 170 символов */
  metaDescription: string;
  /** Ключевые запросы через запятую */
  keywords: string;
  /** Первый абзац витрины: суть курса человеческим языком */
  lead: string;
  /** Что человек получит на выходе — конкретные результаты */
  results: string[];
  /** Для кого курс — портреты, а не абстракции */
  forWhom: string[];
  /** Доход в профессии. Не указываем там, где заработок непредсказуем. */
  income?: {
    /** Что за роль: «Junior-разработчик», «Специалист по тендерам» */
    role: string;
    /** Диапазон дохода — как в вакансиях */
    range: string;
    /** Честное пояснение: от чего зависит и сколько идти */
    note: string;
  };
  /** Ситуация на рынке: спрос, дефицит кадров, формат работы */
  market?: string;
}

export type CourseSeoMap = Record<number, CourseSeoCopy>;
