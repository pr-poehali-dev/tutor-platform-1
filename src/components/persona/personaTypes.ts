/**
 * Типы и каталог ИИ-персон.
 *
 * Персона — это «сотрудник»: внешность (портрет), голос, характер и задача.
 * Один и тот же движок лица обслуживает всех: репетитора, продавца,
 * приёмную комиссию. Меняются только данные из этого файла.
 */

/** Роль определяет, как персона себя ведёт и что знает. */
export type PersonaRole = "tutor" | "sales" | "support" | "host";

/** Настройка положения черт лица под конкретный портрет (в % от размера). */
export interface FaceMap {
  /** Центр глаз по вертикали, % сверху. */
  eyesY: number;
  /** Левый и правый глаз по горизонтали, % слева. */
  eyeLeftX: number;
  eyeRightX: number;
  /** Ширина и высота одного глаза, % от кадра. */
  eyeW: number;
  eyeH: number;
  /** Центр рта. */
  mouthY: number;
  mouthX: number;
  /** Ширина рта, % от кадра. */
  mouthW: number;
}

/** Стандартная разметка для портрета «по грудь», лицо в центре кадра. */
