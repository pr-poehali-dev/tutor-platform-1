export interface Persona {
  id: string;
  /** Имя для обращения. */
  name: string;
  /** Полное имя на бейдже. */
  fullName: string;
  role: PersonaRole;
  /** Короткое описание задачи — видно в студии. */
  job: string;
  /** Портрет (CDN). */
  image: string;
  /** Голос TTS: nika | sofia | alex | dmitry | fox. */
  voice: string;
  /** Акцентный цвет интерфейса. */
  accent: string;
  /** Первая фраза при появлении. */
  greeting: string;
  /** Характер и правила поведения — уходит в подсказку модели. */
  persona: string;
  /** Разметка лица под конкретный портрет. */
  face: FaceMap;
  /** Быстрые вопросы-подсказки для пользователя. */
  quickAsks: string[];
}

