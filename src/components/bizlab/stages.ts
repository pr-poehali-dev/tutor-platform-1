/** Поля этапа с учётом условий показа. */
export function visibleFields(stage: BizStage, a: BizAnswers) {
  return stage.fields.filter((f) => {
    if (!f.showIf) return true;
    return f.showIf.in.includes(a[f.showIf.key] || "");
  });
}

/** Можно ли идти дальше: заполнены все обязательные поля этапа. */
export function stageReady(stage: BizStage, a: BizAnswers): boolean {
  return visibleFields(stage, a).every((f) => {
    if (f.optional) return true;
    const v = (a[f.key] || "").trim();
    return v.length > 0;
  });
}
