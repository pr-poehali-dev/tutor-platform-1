import { BoardReview } from "./api";
import { fmt, fmt1 } from "./calc";
import { BizAnswers, BizMetrics } from "./types";

/**
 * Разбор советом директоров на правилах — работает мгновенно и всегда,
 * без обращения к ИИ. Опирается только на посчитанные цифры пользователя.
 */
export function localBoard(m: BizMetrics, a: BizAnswers, score: number): BoardReview {
  const tested = a.demand_tested || "";
  const hasLoan = m.loanMonthly > 0;
  const isService = a.biz_type === "services" || a.biz_type === "online";
  const profitable = m.plannedProfit > 0;

  const headline = !profitable
    ? "В текущих цифрах бизнес убыточен — запускать в таком виде нельзя"
    : m.safetyMarginPct < 20
    ? "Прибыль есть, но запаса прочности почти нет — план держится на идеальном сценарии"
    : hasLoan && !m.stressSurvives
    ? "Модель рабочая, но кредит делает её хрупкой при первом же спаде"
    : "Модель сходится — дальше всё решает исполнение";

  const realityParts: string[] = [];
  if (tested === "no" || tested === "asked") {
    realityParts.push(
      "Главное, чего не хватает, — доказательства спроса. Все расчёты ниже построены на предположении, что ваш план продаж выполнится, но пока это гипотеза, а не факт.",
    );
  }
  if (m.plannedUnits > 0 && Number.isFinite(m.breakEvenUnits)) {
    realityParts.push(
      `Чтобы выйти в ноль, нужно ${fmt(m.breakEvenUnits)} продаж в месяц — это примерно ${fmt(m.breakEvenUnits / 30)} в день, без выходных. Спросите себя, откуда возьмётся столько людей уже в первые месяцы.`,
    );
  }
  if (m.runwayMonths < 6) {
    realityParts.push(
      `Подушки хватит на ${fmt1(m.runwayMonths)} месяца, а выход на плановые продажи обычно занимает 6-12 месяцев. Между этими сроками — разрыв, который придётся закрывать личными деньгами.`,
    );
  }
  if (profitable && m.safetyMarginPct >= 30) {
    realityParts.push(
      "Экономика выглядит устойчиво, но помните: расчёт всегда оптимистичнее жизни. Заложите, что первые полгода дадут 30-50% от плана.",
    );
  }

  const board = [
    {
      role: "Финансист",
      emoji: "💰",
      verdict: profitable
        ? `Прибыль ${fmt(m.plannedProfit)} ₽ в месяц при запасе прочности ${fmt1(m.safetyMarginPct)}%.`
        : `Убыток ${fmt(Math.abs(m.plannedProfit))} ₽ в месяц — расходы выше того, что приносят продажи.`,
      points: [
        `С каждой продажи остаётся ${fmt(m.unitMargin)} ₽ (${fmt1(m.marginPct)}%). Постоянные расходы ${fmt(m.fixedMonthly)} ₽ в месяц идут независимо от выручки.`,
        Number.isFinite(m.paybackMonths)
          ? `Вложения ${fmt(m.startCapital)} ₽ окупятся за ${fmt(m.paybackMonths)} мес. при выполнении плана.`
          : "При текущих цифрах вложения не окупятся — сначала нужно исправить экономику.",
      ],
      action: profitable
        ? `Отложите налоги сразу с каждого поступления и держите резерв ${fmt(m.fixedMonthly * 3)} ₽ — это три месяца работы.`
        : "Пересчитайте цену и постоянные расходы. Пока прибыль отрицательная, любые вложения только увеличат потери.",
    },
    {
      role: "Маркетолог",
      emoji: "📣",
      verdict:
        tested === "sales" || tested === "preorder"
          ? "Спрос подтверждён деньгами — это сильная позиция, таких меньшинство."
          : "Спрос не подтверждён оплатами — это самый большой риск во всём плане.",
      points: [
        m.cac > 0
          ? `Клиент обходится в ${fmt(m.cac)} ₽ и приносит ${fmt(m.ltv)} ₽ (LTV/CAC = ${fmt1(m.ltvCac)}, норма — от 3).`
          : `Бюджет на рекламу ${fmt(m.fixedMonthly > 0 ? 0 : 0)}— укажите его, чтобы понять реальную цену клиента.`,
        `План ${fmt(m.plannedUnits)} продаж в месяц. Проверьте обоснование: для розницы конверсия прохожих в покупателей обычно 1-3%, а не 10%.`,
      ],
      action:
        tested === "sales" || tested === "preorder"
          ? "Зафиксируйте, откуда пришли первые покупатели, и вкладывайтесь именно в этот канал."
          : "До вложений соберите минимум 3 реальные оплаты от незнакомых людей. Это стоит несколько тысяч рублей и одну неделю.",
    },
    {
      role: "Операционист",
      emoji: "⚙️",
      verdict: `Нужно стабильно выдавать ${fmt(m.plannedUnits / 30)} продаж в день — проверьте, хватит ли на это людей и мощности.`,
      points: [
        a.experience === "none" || a.experience === "hobby"
          ? "Опыта в этой сфере мало. Самый дешёвый способ его получить — поработать в таком бизнесе месяц или запустить в минимальном формате."
          : "Опыт в сфере есть — это заметно повышает шансы: вы знаете реальные сроки, поставщиков и типовые проблемы.",
        isService
          ? "В услугах узкое место — ваше время. Посчитайте, сколько заказов физически помещается в неделю, и не планируйте больше."
          : "Заложите запас по поставкам: срыв одного поставщика не должен останавливать продажи. Найдите второго заранее.",
      ],
      action:
        "Опишите один рабочий день по шагам. Всё, что делаете только вы лично, — это точка, где бизнес сломается при росте.",
    },
    {
      role: "Юрист",
      emoji: "⚖️",
      verdict:
        a.tax_mode === "usn15" || a.tax_mode === "osno"
          ? "Выбран режим с подтверждением расходов — потребуется дисциплина в документах."
          : "Режим простой в учёте — это правильный выбор для старта.",
      points: [
        a.money_source === "loan" || a.money_source === "mixed"
          ? a.collateral === "home"
            ? "Залог жилья — самый опасный вариант: риск выходит далеко за пределы бизнеса и затрагивает семью."
            : "По кредиту ИП отвечает всем личным имуществом. Оцените, готовы ли вы к этому в плохом сценарии."
          : "Работа на свои деньги — самая безопасная схема на старте: в худшем случае теряете вложения, а не имущество.",
        "До первой продажи проверьте: нужна ли онлайн-касса, требуется ли уведомление о начале деятельности и лицензия по вашему виду.",
      ],
      action:
        "Заведите отдельный расчётный счёт и не смешивайте личные деньги с бизнесом — это спасает и от путаницы, и от вопросов налоговой.",
    },
    {
      role: "Скептик",
      emoji: "🧨",
      verdict: !m.stressSurvives
        ? `Если продажи упадут на 40%, вы теряете ${fmt(Math.abs(m.stressProfit))} ₽ каждый месяц. И это обычный сценарий, а не катастрофа.`
        : "Даже при падении продаж на 40% бизнес остаётся на плаву — это редкая и сильная позиция.",
      points: [
        hasLoan
          ? `Платёж ${fmt(m.loanMonthly)} ₽ придёт и в плохой месяц. Выручка гуляет, платёж — нет: именно так теряют и бизнес, и залог.`
          : "Отсутствие кредита — ваше главное преимущество. Плохой месяц вы просто переживёте, а не окажетесь в долгах.",
        m.plannedUnits > 0 && Number.isFinite(m.breakEvenUnits)
          ? `Что если план продаж завышен вдвое? Тогда вместо прибыли будет ${fmt(m.unitMargin * (m.plannedUnits / 2) - m.fixedMonthly)} ₽ в месяц. Проверьте, переживёте ли это.`
          : "Проверьте план продаж на реализм: возьмите половину от своей цифры и посмотрите, что останется.",
      ],
      action:
        "Назначьте точку выхода заранее: конкретная выручка к конкретному месяцу, ниже которой вы закрываетесь. Это спасает от бесконечного долива денег в убыточное дело.",
    },
  ];

  const killers: BoardReview["killers"] = [];
  if (tested === "no" || tested === "asked") {
    killers.push({
      title: "Товар, который никто не купил до вложений",
      why: "Вы планируете вложить " + fmt(m.startCapital) + " ₽ в продукт, за который пока никто не заплатил. Это причина закрытия номер один среди молодых бизнесов.",
      fix: "Проверьте спрос за неделю и 5 000 ₽ по плану ниже. Три реальные оплаты — и можно вкладываться спокойно.",
    });
  }
  if (hasLoan && !m.stressSurvives) {
    killers.push({
      title: "Кредит при падении продаж",
      why: `Платёж ${fmt(m.loanMonthly)} ₽ фиксирован, а в плохой месяц убыток составит ${fmt(Math.abs(m.stressProfit))} ₽. Разницу придётся платить из личных денег — и так до конца срока.`,
      fix: "Уменьшите сумму кредита вдвое или отложите его до момента, когда бизнес выйдет на стабильную прибыль.",
    });
  }
  if (m.runwayMonths < 3) {
    killers.push({
      title: "Закончатся деньги раньше, чем придут клиенты",
      why: `Подушки хватит на ${fmt1(m.runwayMonths)} мес., а выход на плановые продажи занимает 6-12 месяцев. Разрыв закрывать нечем.`,
      fix: `Отложите старт до накопления ${fmt(m.fixedMonthly * 6)} ₽ или сократите постоянные расходы вдвое.`,
    });
  }
  if (m.marginPct < 25 && m.unitMargin > 0) {
    killers.push({
      title: "Слишком тонкая маржа",
      why: `${fmt1(m.marginPct)}% с продажи не оставляют места для ошибки: подорожание закупки на 10% съедает почти всю прибыль.`,
      fix: "Поднимите цену на 10-15% и проверьте реакцию. Обычно уходит меньше клиентов, чем кажется.",
    });
  }
  if (killers.length === 0) {
    killers.push({
      title: "Главный риск — оптимизм в плане продаж",
      why: "Цифры сходятся, но они построены на вашей оценке спроса. Если реальность окажется вдвое скромнее, запас прочности исчезнет.",
      fix: "Проверьте план на половинном сценарии и заранее решите, какие расходы сократите в этом случае.",
    });
  }

  const demandBudget = isService ? "0-3 000 ₽" : "5 000-10 000 ₽";
  const demand_plan = {
    title: "Как проверить спрос за 2 недели малыми деньгами",
    budget: demandBudget,
    steps: isService
      ? [
          "Опишите услугу одним предложением: что, кому и за сколько. Без описания компании и миссии",
          "Разместите объявление на Авито и в 3-5 местных чатах — это бесплатно",
          "Возьмите первых 3-5 клиентов и выполните работу руками, без найма и автоматизации",
          "У каждого спросите: почему выбрали и что чуть не остановило — это готовый текст для вашей рекламы",
        ]
      : [
          "Сделайте одну страницу с товаром, ценой и кнопкой заказа — хватит бесплатного конструктора",
          "Запустите рекламу на 5 000 ₽ с точной геолокацией вашего района",
          "Принимайте предзаказы с предоплатой, даже символической. Товар пока не закупайте",
          "Посчитайте стоимость одной заявки — в реальной работе она обычно не ниже, чем на тесте",
        ],
    success_metric:
      "3 и больше оплат от незнакомых людей за две недели, при этом цена привлечения ниже " +
      fmt(m.unitMargin > 0 ? m.unitMargin : 0) +
      " ₽ — вашей маржи с продажи.",
    fail_metric:
      "Заявок нет при нормальном показе рекламы, или люди интересуются, но не платят. Значит, менять нужно идею или цену, а не докручивать объявление.",
  };

  const before_launch = [
    tested === "sales" || tested === "preorder"
      ? "Зафиксируйте канал, откуда пришли первые оплаты, — вкладывайтесь в него"
      : "Получите минимум 3 реальные оплаты до любых вложений",
    "Посчитайте себестоимость ещё раз, включив упаковку, эквайринг, доставку и брак",
    "Зарегистрируйтесь и сразу подайте заявление на нужный налоговый режим",
    "Откройте отдельный расчётный счёт для бизнеса",
    `Накопите резерв на 3 месяца работы — это ${fmt(m.fixedMonthly * 3)} ₽`,
    "Заведите таблицу движения денег и платёжный календарь на месяц вперёд",
    hasLoan
      ? "Пересчитайте кредит на половинном плане продаж — сможете ли платить"
      : "Договоритесь с поставщиками об отсрочке платежа: это дешёвый способ пополнить оборотку",
    "Назначьте точку выхода: при какой выручке и к какому месяцу вы закрываетесь",
  ];

  const first_90_days = [
    {
      period: "Дни 1-30",
      focus: "Первые продажи руками",
      tasks: [
        "Продайте вручную первым 10 клиентам, без автоматизации и найма",
        "Записывайте каждую трату и каждое поступление с первого дня",
      ],
      metric: "Число реальных оплат и стоимость привлечения клиента",
    },
    {
      period: "Дни 31-60",
      focus: "Один канал до окупаемости",
      tasks: [
        "Доведите один канал привлечения до окупаемости, прежде чем брать второй",
        "Соберите отзывы и оформите карточку в картах и справочниках",
      ],
      metric: "Стоимость клиента в канале против маржи с продажи",
    },
    {
      period: "Дни 61-90",
      focus: "Проверка модели на фактах",
      tasks: [
        "Сравните фактические цифры с этим расчётом и найдите расхождения",
        "Пересчитайте точку безубыточности по реальным данным, а не по плану",
      ],
      metric: `Факт против плана: ${fmt(m.plannedUnits)} продаж и ${fmt(m.plannedProfit)} ₽ прибыли`,
    },
  ];

  const money_advice = hasLoan
    ? m.debtCover < 1.5 || !m.stressSurvives
      ? `Этот кредит брать не стоит. Платёж ${fmt(m.loanMonthly)} ₽ покрывается прибылью всего в ${fmt1(m.debtCover)} раза, а при падении продаж на 40% вы уходите в минус ${fmt(Math.abs(m.stressProfit))} ₽ в месяц. Безопасный максимум для вашей модели — сумма, где платёж не превышает ${fmt(Math.max(0, m.plannedProfit / 3))} ₽ в месяц. Начните на свои и возьмите кредит позже, когда прибыль станет стабильной.`
      : `Кредит вы тянете: платёж ${fmt(m.loanMonthly)} ₽ покрывается прибылью в ${fmt1(m.debtCover)} раза. Но держите отдельный резерв на 3 платежа — ${fmt(m.loanMonthly * 3)} ₽ — на случай плохих месяцев. И не увеличивайте сумму до выхода на стабильную прибыль.`
    : `Вы начинаете без заёмных денег — это лучшая позиция из возможных. В худшем сценарии вы теряете вложения, но не остаётесь с долгом. Кредит имеет смысл только тогда, когда бизнес уже стабильно прибылен и деньги нужны на понятное расширение, а не на выживание. Первый рост финансируйте прибылью, даже если он будет медленнее.`;

  const verdict_short = !profitable
    ? "Запускать в текущем виде нельзя: расчёт показывает убыток. Исправьте цену, себестоимость или постоянные расходы и пересчитайте — это бесплатно, в отличие от ошибки на практике."
    : score >= 70
    ? "Модель выдерживает проверку — можно двигаться дальше. Сфокусируйтесь на подтверждении спроса и на резерве: именно эти два пункта чаще всего решают судьбу первого года."
    : "Дорабатывайте до запуска. Идея жизнеспособна, но текущие цифры не оставляют права на ошибку — закройте отмеченные риски, и возвращайтесь к расчёту.";

  return {
    headline,
    reality_check: realityParts.join(" "),
    board,
    killers: killers.slice(0, 4),
    demand_plan,
    before_launch,
    first_90_days,
    money_advice,
    verdict_short,
  };
}
